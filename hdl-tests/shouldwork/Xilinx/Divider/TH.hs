-- | Top entity annotation for a function under test
topAnn :: String -> TopEntity
topAnn name =
  Synthesize
    { t_name = name
    , t_inputs =
        [ PortName "clk"
        , PortName "en"
        , PortName "dividend"
        , PortName "divisor"
        ]
    , t_output = PortName "result"
    }

-- | One clock cycle of a test: enable, dividend, divisor, and the expected
-- output, if it is defined
type Sample x y z = (Bool, x, y, Maybe z)

-- | Number of cycles in a test
nSamples :: Int
nSamples = 600

-- | Run the function under test on the given stimuli, and pair each cycle's
-- stimuli with its output. Outputs that are undefined, because they come from
-- the initial contents of the pipeline, are marked as such.
samples ::
  forall d x y z.
  (KnownNat d, NFDataX x, NFDataX y, NFDataX z) =>
  ( Clock XilinxSystem ->
    Enable XilinxSystem ->
    DSignal XilinxSystem 0 x ->
    DSignal XilinxSystem 0 y ->
    DSignal XilinxSystem d z
  ) ->
  [(Bool, x, y)] ->
  [Sample x y z]
samples f inputs =
  P.zipWith
    (\(e, x, y) z -> (e, x, y, if hasUndefined z then Nothing else Just z))
    inputs
    (sampleN (P.length inputs) (D.toSignal out))
 where
  (ens, xs, ys) = P.unzip3 inputs
  out =
    f clockGen
      (toEnable (fromList ens))
      (D.unsafeFromSignal (fromList xs))
      (D.unsafeFromSignal (fromList ys))

-- | Random stimuli, from a fixed seed: operands biased towards edge cases and
-- division by zero, and an enable that is low now and then.
stimuli ::
  forall x y.
  (Bounded x, Bounded y, Num x, Num y, Integral x, Integral y) =>
  Int ->
  [(Bool, x, y)]
stimuli seed = P.take nSamples (go (mkStdGen seed))
 where
  go g0 = (e, x, y) : go g4
   where
    (e, g1) = enable g0
    (special, g2) = uniformR (0 :: Int, 29) g1
    -- The only division that overflows, for signed operands
    ((x, y), g4)
      | special == 0 = ((minBound, -1), g2)
      | otherwise =
          let (x', g3) = operand g2
              (y', g4') = operand g3
          in ((x', y'), g4')

  enable :: StdGen -> (Bool, StdGen)
  enable g = let (r, g') = uniformR (0 :: Int, 9) g in (r /= 0, g')

  operand :: forall a. (Bounded a, Integral a) => StdGen -> (a, StdGen)
  operand g0 =
    case k of
      0 -> pick [0, 1, -1, 2, minBound, minBound + 1, maxBound, maxBound - 1] g1
      1 -> pick [0] g1
      2 -> small g1
      _ -> full g1
   where
    (k, g1) = uniformR (0 :: Int, 7) g0
    full g =
      let (v, g') = uniformR (toInteger (minBound @a), toInteger (maxBound @a)) g
      in (fromInteger v, g')
    small g =
      let (v, g') = uniformR (-20 :: Integer, 20) g
      in (fromInteger (max (toInteger (minBound @a)) v), g')
    pick vs g =
      let (i, g') = uniformR (0, P.length vs - 1) g
      in (vs P.!! i, g')

