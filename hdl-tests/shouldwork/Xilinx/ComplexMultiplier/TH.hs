-- Functions under test, wrapped in top entities in "ComplexMultiplier"
------------------------------------------------------------------------------

-- | Full precision, default configuration and latency
mulS16S16' :: Dut (Cmpy.ComplexMultiplyDefDelay 16 16) 16 16 33
mulS16S16' clk en _ = Cmpy.complexMultiply clk en
{-# INLINE mulS16S16' #-}

-- | Truncation, three real multipliers, a latency below the fully pipelined
-- one
mulResS18S25' :: Dut 3 18 25 20
mulResS18S25' clk en _ = Cmpy.complexMultiplyWith @3 Config{multiplierConstruction = UseDsps, optimizeGoal = Resources} clk en
{-# INLINE mulResS18S25' #-}

-- | Truncation to two bits, three real multipliers in LUTs, a latency above
-- the fully pipelined one
mulLutS35S27' :: Dut 12 35 27 2
mulLutS35S27' clk en _ = Cmpy.complexMultiplyWith @12 Config{multiplierConstruction = UseLuts, optimizeGoal = Resources} clk en
{-# INLINE mulLutS35S27' #-}

-- | Full precision, widest operands, default configuration and latency
mulS63S63' :: Dut (Cmpy.ComplexMultiplyDefDelay 63 63) 63 63 127
mulS63S63' clk en _ = Cmpy.complexMultiply clk en
{-# INLINE mulS63S63' #-}

-- | Rounding, default configuration and latency
roundS16S16' :: Dut (Cmpy.ComplexMultiplyDefDelay 16 16) 16 16 16
roundS16S16' = Cmpy.complexMultiplyRound
{-# INLINE roundS16S16' #-}

-- | Rounding, LUTs, latency 1
roundLutS8S8' :: Dut 1 8 8 9
roundLutS8S8' = Cmpy.complexMultiplyRoundWith @1 Config{multiplierConstruction = UseLuts, optimizeGoal = Performance}
{-# INLINE roundLutS8S8' #-}

-- | Rounding, three real multipliers, a latency far below the fully pipelined
-- one
roundResS40S30' :: Dut 2 40 30 20
roundResS40S30' = Cmpy.complexMultiplyRoundWith @2 Config{multiplierConstruction = UseDsps, optimizeGoal = Resources}
{-# INLINE roundResS40S30' #-}

-- | Rounding, four real multipliers, a wide output
roundS26S45' :: Dut 9 26 45 64
roundS26S45' = Cmpy.complexMultiplyRoundWith @9 Cmpy.defConfig
{-# INLINE roundS26S45' #-}
