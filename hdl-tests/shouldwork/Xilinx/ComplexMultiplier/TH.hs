-- | Top entity annotation for a function under test
topAnn :: String -> TopEntity
topAnn name =
  Synthesize
    { t_name = name
    , t_inputs =
        [ PortName "clk"
        , PortName "en"
        , PortName "round_cy"
        , PortName "a"
        , PortName "b"
        ]
    , t_output = PortName "result"
    }

-- | Type of the functions under test. Functions with truncation ignore the
-- round carry.
type Dut d a b o =
  Clock XilinxSystem ->
  Enable XilinxSystem ->
  DSignal XilinxSystem 0 Bit ->
  DSignal XilinxSystem 0 (Complex (Signed a)) ->
  DSignal XilinxSystem 0 (Complex (Signed b)) ->
  DSignal XilinxSystem d (Complex (Signed o))

-- | One clock cycle of a test: enable, round carry, operands, and the expected
-- output, if it is defined
type Sample a b o = (Bool, Bit, Complex (Signed a), Complex (Signed b), Maybe (Complex (Signed o)))

-- | Number of cycles in a test
nSamples :: Int
nSamples = 500

-- | Run the function under test on the given stimuli, and pair each cycle's
-- stimuli with its output. Outputs that are undefined, because they come from
-- the initial contents of the pipeline, are marked as such.
samples ::
  forall d a b o.
  (KnownNat d, KnownNat a, KnownNat b, KnownNat o) =>
  Dut d a b o ->
  [(Bool, Bit, Complex (Signed a), Complex (Signed b))] ->
  [Sample a b o]
samples f inputs =
  P.zipWith
    (\(e, c, x, y) z -> (e, c, x, y, if hasUndefined z then Nothing else Just z))
    inputs
    (sampleN (P.length inputs) (D.toSignal out))
 where
  (ens, cys, xs, ys) = L.unzip4 inputs
  out =
    f clockGen
      (toEnable (fromList ens))
      (D.unsafeFromSignal (fromList cys))
      (D.unsafeFromSignal (fromList xs))
      (D.unsafeFromSignal (fromList ys))

-- | Random stimuli, from a fixed seed: an enable that is low now and then, a
-- random round carry, and operands biased towards edge cases and products
-- that lie exactly on, or halfway between, two outputs. See 'operands'.
stimuli ::
  forall a b o.
  (KnownNat a, KnownNat b, KnownNat o) =>
  Int ->
  [(Bool, Bit, Complex (Signed a), Complex (Signed b))]
stimuli seed = P.take nSamples (go (mkStdGen seed))
 where
  go g0 = (e /= 0, if c then 1 else 0, x, y) : go g3
   where
    (e, g1) = uniformR (0 :: Int, 9) g0
    (c, g2) = uniformR (False, True) g1
    ((x, y), g3) = operands @a @b @o g2

-- | Operands: uniformly random, edge cases, or with trailing zeros that add up
-- to @k - 1@ or @k@, where @k@ is the number of bits of the exact product that
-- the IP discards. The discarded bits of such products are often all zero or
-- exactly one half.
operands ::
  forall a b o.
  (KnownNat a, KnownNat b, KnownNat o) =>
  StdGen ->
  ((Complex (Signed a), Complex (Signed b)), StdGen)
operands g0 =
  case kind of
    0 -> both (complexR 0) (complexR 0) g1
    1 -> both edge edge g1
    _ ->
      let (total, g2) = uniformR (max 0 (k - 1), k) g1
          (sa, g3) = uniformR (max 0 (total - (wb - 1)), min (wa - 1) total) g2
          sb = max 0 (min (wb - 1) (total - sa))
      in both (complexR sa) (complexR sb) g3
 where
  (kind, g1) = uniformR (0 :: Int, 3) g0
  wa = natToNum @a
  wb = natToNum @b
  k = wa + wb + 1 - natToNum @o

  both f h g =
    let (x, g') = f g
        (y, g'') = h g'
    in ((x, y), g'')

  complexR :: forall n. KnownNat n => Int -> StdGen -> (Complex (Signed n), StdGen)
  complexR s g =
    let (re, g') = scaled @n s g
        (im, g'') = scaled @n s g'
    in (re :+ im, g'')

  -- A random multiple of 2^s, plus or minus one now and then
  scaled :: forall n. KnownNat n => Int -> StdGen -> (Signed n, StdGen)
  scaled s g =
    let (v, g') = uniformR (lo `shiftR` s, hi `shiftR` s) g
        (d, g'') = uniformR (-1 :: Integer, 6) g'
        d' = if d > 1 then 0 else d
    in (fromInteger (max lo (min hi ((v `shiftL` s) + d'))), g'')
   where
    lo = toInteger (minBound @(Signed n))
    hi = toInteger (maxBound @(Signed n))

  edge :: forall n. KnownNat n => StdGen -> (Complex (Signed n), StdGen)
  edge g =
    let (i, g') = uniformR (0, P.length vs - 1) g
        (j, g'') = uniformR (0, P.length vs - 1) g'
    in ((vs P.!! i) :+ (vs P.!! j), g'')
   where
    vs = [0, 1, -1, minBound, minBound + 1, maxBound, maxBound - 1]

