-- | Top entity annotation for a function under test
topAnn :: String -> TopEntity
topAnn name =
  Synthesize
    { t_name = name
    , t_inputs =
        [ PortName "clk"
        , PortName "rst"
        , PortName "frame_config"
        , PortName "in_sample"
        ]
    , t_output = PortProduct "" [PortName "ready", PortName "out_sample"]
    }

-- | Function under test
type Dut s nfft bw =
  Clock XilinxSystem ->
  Reset XilinxSystem ->
  Signal XilinxSystem (FrameConfig s nfft) ->
  Signal XilinxSystem (Maybe (Complex (Signed bw))) ->
  ( Signal XilinxSystem Bool
  , Signal XilinxSystem (Maybe (FftOutput s nfft (OutputWidth s nfft bw))) )

-- | Stimuli of one clock cycle: reset, frame configuration, and input sample
type Stimulus s nfft bw = (Bool, (Direction, ScaleSchedule s nfft), Maybe (Complex (Signed bw)))

-- | Expected output of one clock cycle: whether the IP is ready, and the output
-- sample. The value of the output sample is 'Nothing' if it is undefined.
type Expected s nfft bw =
  ( Bool
  , Maybe
      ( Index (2 ^ nfft)
      , Maybe (Complex (Signed (OutputWidth s nfft bw)))
      , Bool
      , FrameStatus s
      )
  )

-- | One clock cycle of a test
type Sample s nfft bw = (Stimulus s nfft bw, Expected s nfft bw)

-- | Scaling schedules for the stimuli
class KnownScaling s => TestScaling (s :: Scaling) where
  -- | A random scaling schedule. Small shifts make frames overflow.
  randomSchedule :: forall nfft. KnownNat nfft => Proxy nfft -> StdGen -> (ScaleSchedule s nfft, StdGen)

instance TestScaling 'Unscaled where
  randomSchedule _ g = ((), g)

instance TestScaling 'BlockFloatingPoint where
  randomSchedule _ g = ((), g)

instance TestScaling 'Scaled where
  randomSchedule :: forall nfft. KnownNat nfft => Proxy nfft -> StdGen -> (ScaleSchedule 'Scaled nfft, StdGen)
  randomSchedule _ g0
    | kind == 0 = (scaleByN @nfft, g1)
    | kind == 1 = (imap (\i s -> if i == 0 then 3 else s) (scaleByN @nfft), g1)
    | otherwise = go g1
   where
    (kind, g1) = uniformR (0 :: Int, 3) g0
    groups = natToNum @(Groups nfft) :: Int
    lastMax = if P.odd (natToNum @nfft :: Int) then 1 else 3
    go g =
      let (shifts, g') = P.foldl step ([], g) [0 .. groups - 1]
          step (acc, h) i =
            let (v, h') = uniformR (0, if i == groups - 1 then lastMax else 3 :: Int) h
            in (acc P.++ [toEnum v], h')
      in (V.unsafeFromList shifts, g')

-- | Random stimuli, from a fixed seed: a reset, then frames with random gaps
-- between them, sometimes another reset, and enough idle cycles at the end for
-- the IP to finish. The frames have a random direction and scaling schedule,
-- and their samples are random values of random amplitudes, impulses,
-- full-scale tones, small values (which hit rounding ties) or extremes.
stimuli ::
  forall s nfft bw.
  (TestScaling s, KnownNat nfft, KnownNat bw) =>
  -- | Seed
  Int ->
  -- | Number of frames
  Int ->
  -- | Latency of the IP
  Int ->
  [Stimulus s nfft bw]
stimuli seed nFrames latency =
  resetCycles 3 dflt P.++ idle 4 P.++ go nFrames (mkStdGen seed)
 where
  n = 2 P.^ (natToNum @nfft :: Int) :: Int
  dflt = (Forward, P.fst (randomSchedule @s (Proxy @nfft) (mkStdGen 0)))
  idle k = P.replicate k (False, dflt, Nothing)
  resetCycles k c = P.replicate k (True, c, Nothing)

  go :: Int -> StdGen -> [Stimulus s nfft bw]
  go 0 _ = idle (latency + n + 20)
  go k g0 =
    gap P.++ rst P.++ frame P.++ go (k - 1) g6
   where
    (gapKind, g1) = uniformR (0 :: Int, 9) g0
    (gapLen, g2) = uniformR (1 :: Int, 40) g1
    gap
      | gapKind < 5 = []
      | gapKind < 7 = idle 1
      | otherwise = idle gapLen
    (rstKind, g3) = uniformR (0 :: Int, 19) g2
    rst
      | rstKind == 0 = resetCycles 2 dflt P.++ idle 4
      | otherwise = []
    (dir, g4) = uniformR (False, True) g3
    (sch, g5) = randomSchedule @s (Proxy @nfft) g4
    cfg = (if dir then Forward else Inverse, sch)
    (xs, g6) = frameSamples g5
    frame = [(False, cfg, Just x) | x <- xs]

  frameSamples :: StdGen -> ([Complex (Signed bw)], StdGen)
  frameSamples g0 = case kind of
    0 -> rnd (2 P.^ (natToNum @bw - 1 :: Int) - 1)
    1 -> rnd 4
    2 -> let (a, g') = uniformR (1, natToNum @bw - 1 :: Int) g1 in rndWith (2 P.^ a) g'
    3 -> let (i, g') = uniformR (0, n - 1) g1
             (v, g'') = extreme g'
         in ([if j == i then v else 0 :+ 0 | j <- [0 .. n - 1]], g'')
    4 -> let (k0, g') = uniformR (0, n - 1) g1
             (ph, g'') = uniformR (0, 1 :: Double) g'
         in ([tone k0 ph j | j <- [0 .. n - 1]], g'')
    _ -> let (v, g') = extreme g1 in (P.take n (P.cycle [v, negate' v]), g')
   where
    (kind, g1) = uniformR (0 :: Int, 6) g0
    rnd a = rndWith a g1
    rndWith :: Integer -> StdGen -> ([Complex (Signed bw)], StdGen)
    rndWith a g = P.foldr (\_ (acc, h) -> let (v, h') = value a h in (v : acc, h')) ([], g) [1 .. n]
    value a g =
      let (re, g') = uniformR (max lo (negate a), min hi (a - 1)) g
          (im, g'') = uniformR (max lo (negate a), min hi (a - 1)) g'
      in (fromInteger re :+ fromInteger im, g'')
    extreme g =
      let (i, g') = uniformR (0, 4 :: Int) g
          (j, g'') = uniformR (0, 4 :: Int) g'
          pick k = [minBound, maxBound, 0, 1, -1] P.!! k
      in (pick i :+ pick j, g'')
    negate' (a :+ b) = satNegate a :+ satNegate b
    satNegate v = if v == minBound then maxBound else negate v
    tone k0 ph j =
      let theta = 2 * pi * (fromIntegral (k0 * j) / fromIntegral n + ph) :: Double
          r = fromInteger hi :: Double
      in fromInteger (clamp (round (r * cos theta))) :+ fromInteger (clamp (round (r * sin theta)))
    clamp v = max lo (min hi v)
    lo = toInteger (minBound :: Signed bw)
    hi = toInteger (maxBound :: Signed bw)

-- | Run the function under test on the stimuli, and pair each cycle's stimuli
-- with its output
samples ::
  forall s nfft bw.
  KnownFft s nfft bw =>
  Dut s nfft bw ->
  [Stimulus s nfft bw] ->
  [Sample s nfft bw]
samples dut stims = P.zip stims (P.map expected (sampleN (P.length stims) (bundle out)))
 where
  (rsts, cfgs, xs) = P.unzip3 stims
  out =
    dut clockGen
      (unsafeFromActiveHigh (fromList rsts))
      (fromList_lazy [FrameConfig d sch | (d, sch) <- cfgs])
      (fromList xs)
  expected (ready, o) =
    ( ready
    , (\FftOutput{..} ->
          (index, if hasUndefined value then Nothing else Just value, lastSample, status))
        <$> o )

