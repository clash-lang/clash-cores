{-# OPTIONS_GHC -fconstraint-solver-iterations=10 -Wall -Werror #-}

{-# LANGUAGE AllowAmbiguousTypes #-}
{-# LANGUAGE ScopedTypeVariables #-}

module Fir.TH where

import Clash.Explicit.Prelude
import qualified Prelude as P

import qualified Clash.Signal.Delayed as D
import System.Random (StdGen, mkStdGen, uniformR)

import Clash.Cores.Xilinx.Fir.Explicit (Config (..), CoefficientStructure (..), DspSlice (..), Rounding (..))
import qualified Clash.Cores.Xilinx.Fir.Explicit as Fir

-- | Top entity annotation for a function under test
topAnn :: String -> TopEntity
topAnn name =
  Synthesize
    { t_name = name
    , t_inputs =
        [ PortName "clk"
        , PortName "en"
        , PortName "x"
        ]
    , t_output = PortName "y"
    }

-- | One clock cycle of a test: enable, sample, and the expected output, if it
-- is defined
type Sample x y = (Bool, x, Maybe y)

-- | Number of cycles in a test
nSamples :: Int
nSamples = 600

-- | Run the function under test on the given stimuli, and pair each cycle's
-- stimuli with its output. Outputs that are undefined, because they come from
-- the initial contents of the pipeline, are marked as such.
samples ::
  forall d x y.
  (KnownNat d, NFDataX x, NFDataX y) =>
  ( Clock XilinxSystem ->
    Enable XilinxSystem ->
    DSignal XilinxSystem 0 x ->
    DSignal XilinxSystem d y
  ) ->
  [(Bool, x)] ->
  [Sample x y]
samples f inputs =
  P.zipWith
    (\(e, x) y -> (e, x, if hasUndefined y then Nothing else Just y))
    inputs
    (sampleN (P.length inputs) (D.toSignal out))
 where
  (ens, xs) = P.unzip inputs
  out = f clockGen (toEnable (fromList ens)) (D.unsafeFromSignal (fromList xs))

-- | Random stimuli, from a fixed seed: samples biased towards the extremes,
-- with runs of extreme values that drive the output to its extremes, and an
-- enable that is low now and then, including in the first cycles.
stimuli :: forall x. (Bounded x, Integral x) => Int -> [(Bool, x)]
stimuli seed = P.take nSamples ((False, 0) : (True, maxBound) : go (mkStdGen seed))
 where
  go g0
    | runKind == 0 = P.zip ens (P.replicate runLen minBound) <> go g3
    | runKind == 1 = P.zip ens (P.replicate runLen maxBound) <> go g3
    | runKind == 2 = P.zip ens (P.cycle [minBound, maxBound]) <> go g3
    | otherwise = (e, x) : go g4
   where
    (runKind, g1) = uniformR (0 :: Int, 40) g0
    (runLen, g2) = uniformR (1 :: Int, 16) g1
    (ens, g3) = enables runLen g2
    (e, g1') = enable g1
    (x, g4) = sample g1'

  enables :: Int -> StdGen -> ([Bool], StdGen)
  enables 0 g = ([], g)
  enables n g = let (e, g') = enable g; (es, g'') = enables (n - 1) g' in (e : es, g'')

  enable :: StdGen -> (Bool, StdGen)
  enable g = let (r, g') = uniformR (0 :: Int, 9) g in (r /= 0, g')

  sample :: StdGen -> (x, StdGen)
  sample g0 =
    case k of
      0 -> pick [0, 1, 2, minBound, minBound + 1, maxBound, maxBound - 1] g1
      1 -> pick [0] g1
      2 -> small g1
      _ -> full g1
   where
    (k, g1) = uniformR (0 :: Int, 7) g0
    full g =
      let (v, g') = uniformR (toInteger (minBound @x), toInteger (maxBound @x)) g
      in (fromInteger v, g')
    small g =
      let (v, g') = uniformR (-20 :: Integer, 20) g
      in (fromInteger (max (toInteger (minBound @x)) v), g')
    pick vs g =
      let (i, g') = uniformR (0, P.length vs - 1) g
      in (vs P.!! i, g')

------------------------------------------------------------------------------
-- Functions under test, wrapped in top entities in "Fir"
------------------------------------------------------------------------------

-- | The configuration for the 7 series part the harness uses
k7 :: Config
k7 = Fir.defConfig{dspSlice = Dsp48E1}

type FirFun x d y =
  Clock XilinxSystem ->
  Enable XilinxSystem ->
  DSignal XilinxSystem 0 x ->
  DSignal XilinxSystem d y

-- | Symmetric low-pass filter, full precision
firSym' :: FirFun (Signed 16) 12 (Signed 31)
firSym' = Fir.firWith @12 k7
  ((-120) :> 0 :> 730 :> (-2100) :> 4900 :> 16000 :> 4900 :> (-2100) :> 730 :> 0 :> (-120) :> Nil
    :: Vec 11 (Signed 16))
{-# INLINE firSym' #-}

-- | Non-symmetric, wide coefficients, convergent rounding to even
firConvEven' :: FirFun (Signed 12) 13 (Signed 16)
firConvEven' = Fir.firWith @13 k7{rounding = ConvergentRoundingToEven}
  (131071 :> (-131072) :> 5000 :> (-77777) :> 12345 :> 1 :> (-1) :> 99999 :> Nil
    :: Vec 8 (Signed 18))
{-# INLINE firConvEven' #-}

-- | Unsigned data and coefficients, truncation
firUnsignedTrunc' :: FirFun (Unsigned 10) 11 (Unsigned 12)
firUnsignedTrunc' = Fir.firWith @11 k7{rounding = TruncateLsbs}
  (255 :> 0 :> 17 :> 128 :> 3 :> 200 :> Nil :: Vec 6 (Unsigned 8))
{-# INLINE firUnsignedTrunc' #-}

-- | Unsigned data, signed coefficients, symmetric rounding to infinity
firMixedSymInf' :: FirFun (Unsigned 12) 13 (Signed 14)
firMixedSymInf' = Fir.firWith @13 k7{rounding = SymmetricRoundingToInfinity}
  (100 :> (-512) :> 511 :> 3 :> (-7) :> 250 :> 1 :> Nil :: Vec 7 (Signed 10))
{-# INLINE firMixedSymInf' #-}

-- | Half-band filter, non-symmetric rounding up
firHalfBand' :: FirFun (Signed 16) 10 (Signed 18)
firHalfBand' = Fir.firWith @10 k7{rounding = NonSymmetricRoundingUp}
  ((-300) :> 0 :> 1200 :> 0 :> (-5000) :> 16384 :> (-5000) :> 0 :> 1200 :> 0 :> (-300) :> Nil
    :: Vec 11 (Signed 16))
{-# INLINE firHalfBand' #-}

-- | Hilbert transformer, treated as negative symmetric, symmetric rounding to
-- zero
firHilbert' :: FirFun (Signed 14) 11 (Signed 16)
firHilbert' = Fir.firWith @11 k7{rounding = SymmetricRoundingToZero, coefficientStructure = NegativeSymmetric}
  ((-2000) :> 0 :> (-6000) :> 0 :> 6000 :> 0 :> 2000 :> Nil :: Vec 7 (Signed 14))
{-# INLINE firHilbert' #-}

-- | Wide data, two DSP slices per multiplication, non-symmetric rounding down
firWide2' :: FirFun (Signed 30) 12 (Signed 32)
firWide2' = Fir.firWith @12 k7{rounding = NonSymmetricRoundingDown}
  (32767 :> (-32768) :> 1000 :> (-3) :> 20000 :> Nil :: Vec 5 (Signed 16))
{-# INLINE firWide2' #-}

-- | Wide data and coefficients, four DSP slices per multiplication,
-- convergent rounding to odd
firWide4' :: FirFun (Signed 30) 15 (Signed 40)
firWide4' = Fir.firWith @15 k7{rounding = ConvergentRoundingToOdd}
  (536870911 :> (-536870912) :> 123456789 :> (-1) :> Nil :: Vec 4 (Signed 30))
{-# INLINE firWide4' #-}

-- | Symmetric coefficients without exploiting the symmetry
firNonSymmetric' :: FirFun (Signed 16) 14 (Signed 29)
firNonSymmetric' = Fir.firWith @14 k7{coefficientStructure = NonSymmetric}
  (5 :> (-30) :> 200 :> 1000 :> 3000 :> 1000 :> 200 :> (-30) :> 5 :> Nil :: Vec 9 (Signed 16))
{-# INLINE firNonSymmetric' #-}

-- | The full precision output overflows for two consecutive samples of
-- @minBound@
firOverflow' :: FirFun (Signed 8) 7 (Signed 15)
firOverflow' = Fir.firWith @7 k7 ((-64) :> (-64) :> Nil :: Vec 2 (Signed 8))
{-# INLINE firOverflow' #-}

-- | Rounding up overflows for two consecutive samples of @maxBound@
firRoundOverflow' :: FirFun (Signed 8) 7 (Signed 7)
firRoundOverflow' = Fir.firWith @7 k7{rounding = NonSymmetricRoundingUp}
  (64 :> 64 :> Nil :: Vec 2 (Signed 8))
{-# INLINE firRoundOverflow' #-}

-- | Truncation to the widest output the IP supports: one bit less than full
-- precision
firTruncMax' :: FirFun (Signed 16) 9 (Signed 20)
firTruncMax' = Fir.firWith @9 k7{rounding = TruncateLsbs}
  (3 :> (-5) :> 7 :> 11 :> Nil :: Vec 4 (Signed 8))
{-# INLINE firTruncMax' #-}

-- | Symmetric coefficients of a half-band filter, without exploiting its zeros
firSymHalfBand' :: FirFun (Signed 16) 12 (Signed 20)
firSymHalfBand' = Fir.firWith @12 k7{rounding = ConvergentRoundingToEven, coefficientStructure = Symmetric}
  ((-300) :> 0 :> 1200 :> 0 :> (-5000) :> 16384 :> (-5000) :> 0 :> 1200 :> 0 :> (-300) :> Nil
    :: Vec 11 (Signed 16))
{-# INLINE firSymHalfBand' #-}

-- | Unsigned symmetric filter, full precision
firUnsignedSym' :: FirFun (Unsigned 16) 9 (Unsigned 34)
firUnsignedSym' = Fir.fir @9
  (65535 :> 1 :> 40000 :> 40000 :> 1 :> 65535 :> Nil :: Vec 6 (Unsigned 16))
{-# INLINE firUnsignedSym' #-}
