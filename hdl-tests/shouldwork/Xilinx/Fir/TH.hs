-- | Top entity annotation for a function under test
topAnn :: String -> TopEntity
topAnn name =
  Synthesize
    { t_name = name
    , t_inputs =
        [ PortName "clk"
        , PortName "en"
        , PortName "x"
        ]
    , t_output = PortName "y"
    }

-- | One clock cycle of a test: enable, sample, and the expected output, if it
-- is defined
type Sample x y = (Bool, x, Maybe y)

-- | Number of cycles in a test
nSamples :: Int
nSamples = 600

-- | Run the function under test on the given stimuli, and pair each cycle's
-- stimuli with its output. Outputs that are undefined, because they come from
-- the initial contents of the pipeline, are marked as such.
samples ::
  forall d x y.
  (KnownNat d, NFDataX x, NFDataX y) =>
  ( Clock XilinxSystem ->
    Enable XilinxSystem ->
    DSignal XilinxSystem 0 x ->
    DSignal XilinxSystem d y
  ) ->
  [(Bool, x)] ->
  [Sample x y]
samples f inputs =
  P.zipWith
    (\(e, x) y -> (e, x, if hasUndefined y then Nothing else Just y))
    inputs
    (sampleN (P.length inputs) (D.toSignal out))
 where
  (ens, xs) = P.unzip inputs
  out = f clockGen (toEnable (fromList ens)) (D.unsafeFromSignal (fromList xs))

-- | Random stimuli, from a fixed seed: samples biased towards the extremes,
-- with runs of extreme values that drive the output to its extremes, and an
-- enable that is low now and then, including in the first cycles.
stimuli :: forall x. (Bounded x, Integral x) => Int -> [(Bool, x)]
stimuli seed = P.take nSamples ((False, 0) : (True, maxBound) : go (mkStdGen seed))
 where
  go g0
    | runKind == 0 = P.zip ens (P.replicate runLen minBound) <> go g3
    | runKind == 1 = P.zip ens (P.replicate runLen maxBound) <> go g3
    | runKind == 2 = P.zip ens (P.cycle [minBound, maxBound]) <> go g3
    | otherwise = (e, x) : go g4
   where
    (runKind, g1) = uniformR (0 :: Int, 40) g0
    (runLen, g2) = uniformR (1 :: Int, 16) g1
    (ens, g3) = enables runLen g2
    (e, g1') = enable g1
    (x, g4) = genSample g1'

  enables :: Int -> StdGen -> ([Bool], StdGen)
  enables 0 g = ([], g)
  enables n g = let (e, g') = enable g; (es, g'') = enables (n - 1) g' in (e : es, g'')

  enable :: StdGen -> (Bool, StdGen)
  enable g = let (r, g') = uniformR (0 :: Int, 9) g in (r /= 0, g')

  genSample :: StdGen -> (x, StdGen)
  genSample g0 =
    case k of
      0 -> pick [0, 1, 2, minBound, minBound + 1, maxBound, maxBound - 1] g1
      1 -> pick [0] g1
      2 -> small g1
      _ -> full g1
   where
    (k, g1) = uniformR (0 :: Int, 7) g0
    full g =
      let (v, g') = uniformR (toInteger (minBound @x), toInteger (maxBound @x)) g
      in (fromInteger v, g')
    small g =
      let (v, g') = uniformR (-20 :: Integer, 20) g
      in (fromInteger (max (toInteger (minBound @x)) v), g')
    pick vs g =
      let (i, g') = uniformR (0, P.length vs - 1) g
      in (vs P.!! i, g')

-- | One clock cycle of a test of a function with valid-qualified samples:
-- enable, sample, and the expected ready and output
type ValidSample x y = (Bool, Maybe x, Bool, Maybe y)

-- | Like 'samples', for functions with valid-qualified samples. Their outputs
-- are always defined.
validSamples ::
  forall d x y.
  (KnownNat d, NFDataX x, NFDataX y) =>
  ValidFirFun x d y ->
  [(Bool, Maybe x)] ->
  [ValidSample x y]
validSamples f inputs =
  P.zipWith3
    (\(e, x) r y -> (e, x, r, y))
    inputs
    (sampleN (P.length inputs) (D.toSignal ready))
    (sampleN (P.length inputs) (D.toSignal out))
 where
  (ens, xs) = P.unzip inputs
  (ready, out) = f clockGen (toEnable (fromList ens)) (D.unsafeFromSignal (fromList xs))

-- | Random valid-qualified stimuli: the samples of 'stimuli', in stretches in
-- which a sample is valid with a probability of @1/p@ for a sample period of
-- @p@, and in bursts in which every sample is valid, so that the IP has to
-- refuse some.
validStimuli :: forall x. (Bounded x, Integral x) => Int -> Int -> [(Bool, Maybe x)]
validStimuli p seed = go (mkStdGen (seed + 1000)) (stimuli seed)
 where
  go _ [] = []
  go g0 xs = P.zipWith (\v (e, x) -> (e, if v then Just x else Nothing)) valids now <> go g3 later
   where
    (burst, g1) = uniformR (0 :: Int, 5) g0
    (len, g2) = uniformR (4 :: Int, 40) g1
    (now, later) = P.splitAt len xs
    (valids, g3) = validBits (P.length now) g2
    validBits 0 g = ([], g)
    validBits k g =
      let
        (r, g') = uniformR (1 :: Int, p) g
        (vs, g'') = validBits (k - 1) g'
      in ((burst == 0 || r == 1) : vs, g'')

