{-# LANGUAGE QuasiQuotes #-}

{- | Test infrastructure for the iCE40 primitives. The test benches compare the
Haskell simulation models of the primitives to the community simulation models
of Yosys (@share\/yosys\/ice40\/cells_sim.v@), validated against Yosys 0.70.

== Finding @cells_sim.v@

The test benches need Yosys' @ice40/cells_sim.v@ next to the HDL generated by
Clash. We look for it, at compile time, in:

1. The environment variable @ICE40_CELLS_SIM@, if set
2. @$(yosys-config --datdir)/ice40/cells_sim.v@

Each test bench passes its result through 'withCellsSim', a black box that
adds a file to the HDL output that includes @cells_sim.v@. As the file is part
of the HDL output, it ends up in the Clash manifest, so that Vivado reads it,
and in the HDL directory, where Icarus Verilog finds it.

== Stimuli and expected values

The stimuli are random, generated from a fixed seed per test bench. The
expected outputs are computed with the Haskell simulation model at compile
time. Bits that are undefined in the Haskell model are not checked.
-}
module Ice40TestCommon where

import Clash.Explicit.Prelude
import Clash.Explicit.Testbench
import Clash.Annotations.Primitive (Primitive (..), HDL (..), hasBlackBox)
import Clash.Sized.Internal.BitVector (BitVector (BV))

import Data.Bits (shiftL, shiftR, xor)
import Data.String.Interpolate (__i)
import Data.Word (Word64)
import Language.Haskell.TH (AnnTarget (ValueAnnotation), ExpQ, pragAnnD, tupE)
import Language.Haskell.TH.Syntax (lift)

import Ice40CellsSim (cellsSimPathQ)

import qualified Prelude as P

-- * Yosys' simulation models

{- | Returns its argument. Its black box adds a file to the HDL output that
includes Yosys' @ice40/cells_sim.v@ (see "Ice40CellsSim"). The file defines
@NO_ICE40_DEFAULT_ASSIGNMENTS@ first: the default values of input ports in
@cells_sim.v@ are a SystemVerilog feature, and the test suite runs Icarus
Verilog in Verilog 2001 mode. It has an include guard, as the test suite passes
the HDL files of all test benches in a module to Icarus Verilog at once.
-}
withCellsSim :: Signal dom Bool -> Signal dom Bool
withCellsSim s = s
{-# OPAQUE withCellsSim #-}
{-# ANN withCellsSim hasBlackBox #-}

-- The black boxes depend on the location of @cells_sim.v@, so we generate
-- their annotations with Template Haskell.
$( do
    path <- cellsSimPathQ
    let
      primitive :: String -> String -> String
      primitive comment assign = [__i|
        BlackBox:
          name: Ice40TestCommon.withCellsSim
          kind: Declaration
          includes:
            - name: ice40_cells_sim
              extension: v
              template: |-
                `ifndef ICE40_CELLS_SIM_INCLUDED
                `define ICE40_CELLS_SIM_INCLUDED
                `define NO_ICE40_DEFAULT_ASSIGNMENTS
                `include "#{path}"
                `endif
          template: |-
            #{comment} Simulation models: ~INCLUDENAME[0]
            #{assign}
        |]
      verilog = primitive "//" "assign ~RESULT = ~ARG[0];"
      vhdl = primitive "--" "~RESULT <= ~ARG[0];"
    sequence
      [ pragAnnD (ValueAnnotation 'withCellsSim)
          [| InlineYamlPrimitive [Verilog, SystemVerilog] $(lift verilog) |]
      , pragAnnD (ValueAnnotation 'withCellsSim)
          [| InlineYamlPrimitive [VHDL] $(lift vhdl) |]
      ]
 )

-- * Random generation

-- | Minimal state monad threading a (xorshift64*) random generator
newtype G a = G {runG :: Word64 -> (a, Word64)}

instance Functor G where
  fmap f (G g) = G (\s -> let (a, s1) = g s in (f a, s1))

instance Applicative G where
  pure a = G (\s -> (a, s))
  G f <*> G a = G (\s -> let (f1, s1) = f s; (a1, s2) = a s1 in (f1 a1, s2))

instance Monad G where
  G a >>= f = G (\s -> let (a1, s1) = a s in runG (f a1) s1)

evalG :: G a -> Int -> a
evalG g seed = fst (runG g (0x9E3779B97F4A7C15 * (fromIntegral seed + 1)))

-- | Random 64-bit word
genWord :: G Word64
genWord = G step
 where
  step s0 = (s3 * 0x2545F4914F6CDD1D, s3)
   where
    s1 = s0 `xor` (s0 `shiftR` 12)
    s2 = s1 `xor` (s1 `shiftL` 25)
    s3 = s2 `xor` (s2 `shiftR` 27)

-- | Uniformly random integer in the given (inclusive) range
uniformInteger :: Integer -> Integer -> G Integer
uniformInteger lo hi = do
  ws <- sequence (P.replicate 4 genWord)
  let r = P.foldl (\acc w -> acc * 2 P.^ (64 :: Int) + toInteger w) 0 ws
  pure (lo + r `mod` (hi - lo + 1))

genBV :: forall n. KnownNat n => G (BitVector n)
genBV = fromInteger <$> uniformInteger 0 (2 P.^ natToNum @n @Integer - 1)

genBit :: G Bit
genBit = unpack <$> genBV

genBool :: G Bool
genBool = bitToBool <$> genBit

-- | 'True' with the given probability (in percent)
chance :: Integer -> G Bool
chance p = (< p) <$> uniformInteger 0 99

elements :: [a] -> G a
elements xs = (xs P.!!) . fromInteger <$> uniformInteger 0 (toInteger (P.length xs) - 1)

-- * Domains

type Dom = System

-- | Domain with half the period of 'Dom', for double data rate signals
createDomain vSystem{vName = "Fast", vPeriod = 5000}

-- * Expected outputs

-- | Expected values along with a mask of the bits to check. Undefined bits are
-- not checked.
withMask :: BitPack a => a -> (BitVector (BitSize a), BitVector (BitSize a))
withMask o = case isX (pack o) of
  Left _ -> (0, 0)
  Right (BV m v) ->
    let care = complement (fromIntegral m) in (fromIntegral v .&. care, care)

-- | Pack a stimulus, replacing undefined bits (such as the field of a
-- 'Nothing') by zeroes.
definedBits :: BitPack a => a -> BitVector (BitSize a)
definedBits a = case pack a of
  BV m v -> fromIntegral v .&. complement (fromIntegral m)

-- | Simulate a circuit with the Haskell model, and return the expected values
-- along with a mask of the bits to check.
expected ::
  (BitPack i, BitPack o, NFDataX i) =>
  (Clock Dom -> Signal Dom i -> Signal Dom o) ->
  [i] ->
  [(BitVector (BitSize o), BitVector (BitSize o))]
expected circuit is =
  P.map withMask (sampleN_lazy (P.length is) (circuit clockGen (fromList is)))

-- | Memory blobs with the stimuli, expected values, and masks of the bits to
-- check, for 'tb'
blobs ::
  (BitPack i, BitPack o, NFDataX i) =>
  (Clock Dom -> Signal Dom i -> Signal Dom o) ->
  [i] ->
  ExpQ
blobs circuit is =
  tupE
    [ memBlobTH Nothing (P.map definedBits is)
    , memBlobTH Nothing (P.map fst es)
    , memBlobTH Nothing (P.map snd es)
    ]
 where
  es = expected circuit is

-- * Test benches

{- | Test bench for a circuit in a single domain. Plays the stimuli and
compares the outputs to the expected values, for every bit in the mask.
-}
tb ::
  forall n i o.
  (KnownNat n, 1 <= n, BitPack i, BitPack o) =>
  (Clock Dom -> Signal Dom i -> Signal Dom o) ->
  ( MemBlob n (BitSize i)
  , MemBlob n (BitSize o)
  , MemBlob n (BitSize o) ) ->
  Signal Dom Bool
tb circuit (stimBlob, expectedBlob, maskBlob) = withCellsSim done
 where
  clk = tbClockGen (not <$> done)

  cnt :: Signal Dom (Index n)
  cnt = register clk noReset enableGen 0 (satSucc SatBound <$> cnt)

  stim = unpack . asyncRomBlob stimBlob <$> cnt
  actual = pack <$> circuit clk stim
  expectedVal = asyncRomBlob expectedBlob <$> cnt
  mask = asyncRomBlob maskBlob <$> cnt

  done =
    assert clk noReset "outputs"
      ((.&.) <$> actual <*> mask)
      ((.&.) <$> expectedVal <*> mask)
      ((== maxBound) <$> cnt)
{-# INLINE tb #-}

-- | A circuit with inputs and outputs in both 'Dom' and 'Fast'
type DdrCircuit iSlow iFast oSlow oFast =
  Clock Dom ->
  Clock Fast ->
  Signal Dom iSlow ->
  Signal Fast iFast ->
  (Signal Dom oSlow, Signal Fast oFast)

-- | Like 'expected', for a 'DdrCircuit'. Takes the stimuli for 'Dom'; there
-- are two stimuli for 'Fast' for each of them.
expectedDdr ::
  (BitPack oSlow, BitPack oFast, NFDataX iSlow, NFDataX iFast) =>
  DdrCircuit iSlow iFast oSlow oFast ->
  [iSlow] ->
  [iFast] ->
  ( [(BitVector (BitSize oSlow), BitVector (BitSize oSlow))]
  , [(BitVector (BitSize oFast), BitVector (BitSize oFast))] )
expectedDdr circuit iSlow iFast =
  ( P.map withMask (sampleN_lazy (P.length iSlow) oSlow)
  , P.map withMask (sampleN_lazy (P.length iFast) oFast) )
 where
  (oSlow, oFast) = circuit clockGen clockGen (fromList iSlow) (fromList iFast)

-- | Like 'blobs', for a 'DdrCircuit'
blobsDdr ::
  ( BitPack iSlow, BitPack iFast, BitPack oSlow, BitPack oFast
  , NFDataX iSlow, NFDataX iFast ) =>
  DdrCircuit iSlow iFast oSlow oFast ->
  [iSlow] ->
  [iFast] ->
  ExpQ
blobsDdr circuit iSlow iFast =
  tupE
    [ memBlobTH Nothing (P.map definedBits iSlow)
    , memBlobTH Nothing (P.map fst esSlow)
    , memBlobTH Nothing (P.map snd esSlow)
    , memBlobTH Nothing (P.map definedBits iFast)
    , memBlobTH Nothing (P.map fst esFast)
    , memBlobTH Nothing (P.map snd esFast)
    ]
 where
  (esSlow, esFast) = expectedDdr circuit iSlow iFast

-- | Like 'tb', for a 'DdrCircuit'. Both domains run for the same amount of
-- time.
tbDdr ::
  forall n iSlow iFast oSlow oFast.
  ( KnownNat n, 1 <= n
  , BitPack iSlow, BitPack iFast, BitPack oSlow, BitPack oFast ) =>
  DdrCircuit iSlow iFast oSlow oFast ->
  ( MemBlob n (BitSize iSlow)
  , MemBlob n (BitSize oSlow)
  , MemBlob n (BitSize oSlow)
  , MemBlob (2 * n) (BitSize iFast)
  , MemBlob (2 * n) (BitSize oFast)
  , MemBlob (2 * n) (BitSize oFast) ) ->
  Signal Dom Bool
tbDdr circuit (stimS, expS, maskS, stimF, expF, maskF) =
  withCellsSim done
 where
  clkS = tbClockGen (not <$> doneS)
  clkF = tbClockGen (not <$> doneF)

  cntS :: Signal Dom (Index n)
  cntS = register clkS noReset enableGen 0 (satSucc SatBound <$> cntS)
  cntF :: Signal Fast (Index (2 * n))
  cntF = register clkF noReset enableGen 0 (satSucc SatBound <$> cntF)

  (oS, oF) =
    circuit clkS clkF
      (unpack . asyncRomBlob stimS <$> cntS)
      (unpack . asyncRomBlob stimF <$> cntF)

  maskedS = asyncRomBlob maskS <$> cntS
  maskedF = asyncRomBlob maskF <$> cntF

  doneS =
    assert clkS noReset "outputs (slow)"
      ((.&.) <$> (pack <$> oS) <*> maskedS)
      ((.&.) <$> (asyncRomBlob expS <$> cntS) <*> maskedS)
      ((== maxBound) <$> cntS)
  doneF =
    assert clkF noReset "outputs (fast)"
      ((.&.) <$> (pack <$> oF) <*> maskedF)
      ((.&.) <$> (asyncRomBlob expF <$> cntF) <*> maskedF)
      ((== maxBound) <$> cntF)

  done = (&&) <$> doneS <*> unsafeSynchronizer clkF clkS doneF
{-# INLINE tbDdr #-}
