{-# LANGUAGE ScopedTypeVariables #-}
{-# OPTIONS_GHC -fconstraint-solver-iterations=10 #-}

{- | Test bench helpers for the tests of Intel IP: stimuli, reference traces and a ROM
driven test bench.

A test bench compares the IP's simulation model, generated by Quartus, with the
Haskell simulation model in @clash-cores@, cycle by cycle. The reference trace
is computed at compile time, by simulating the very same functions in Haskell
(where they use their Haskell models) on the same stimuli: inputs, enables and
resets for every cycle. The test bench replays the stimuli from a ROM, and
checks the outputs of the IP against the trace whenever it is defined.
-}
module IpTestCommon where

import Clash.Explicit.Prelude
import qualified Prelude as P

import Data.Maybe (fromMaybe, isJust)
import Data.Word (Word32, Word64)
import GHC.Float (castFloatToWord32, castWord32ToFloat, castWord64ToDouble)

import Clash.Explicit.Testbench (tbClockGen)
import qualified Clash.Signal.Delayed as D

-- | Domain of the tests
type Dom = System

-- | A function under test, with one or more instances of the IP
type Dut i o = Clock Dom -> Reset Dom -> Enable Dom -> Signal Dom i -> Signal Dom o

-- | Stimulus of a single cycle
data Cycle i = Cycle
  { cycleReset :: Bool
  , cycleEnable :: Bool
  , cycleInput :: i
  }

-- | Content of a ROM entry: input, reset, enable and the expected outputs
type Entry i k m = (i, Bool, Bool, Vec k (Maybe (BitVector m)))

-- * Random numbers

-- | SplitMix64
nextRand :: Word64 -> (Word64, Word64)
nextRand s =
  let s' = s + 0x9e3779b97f4a7c15
      z1 = (s' `xor` (s' `shiftR` 30)) * 0xbf58476d1ce4e5b9
      z2 = (z1 `xor` (z1 `shiftR` 27)) * 0x94d049bb133111eb
   in (z2 `xor` (z2 `shiftR` 31), s')

randoms :: Word64 -> [Word64]
randoms s = let (x, s') = nextRand s in x : randoms s'

-- * Stimuli

-- | Bit patterns of interesting floating point numbers: zeros, subnormal
-- numbers, the smallest and largest normal numbers, infinities, NaNs, and
-- numbers around one and around the bounds of 32 bit integers.
specialWords :: [Word32]
specialWords =
  [ 0x00000000, 0x80000000, 0x00000001, 0x80000001, 0x007fffff, 0x807fffff
  , 0x00800000, 0x80800000, 0x00800001, 0x00ffffff, 0x7f7fffff, 0xff7fffff
  , 0x7f800000, 0xff800000, 0x7fc00000, 0xffc00000, 0x7f800001, 0xffffffff
  , 0x3f800000, 0xbf800000, 0x3f800001, 0x3fffffff, 0x40000000, 0x3f000000
  , 0xbfc00000, 0x40200000, 0x4b000000, 0x33800000, 0x34000000, 0x1f800000
  , 0x5f800000, 0x4effffff, 0x4f000000, 0xcf000000, 0xcf000001, 0x4f800000 ]

-- | Random bit pattern of a floating point number, of one of several kinds
randomWord :: Word64 -> Word64 -> Word32
randomWord k x =
  let w = fromIntegral x :: Word32
      e = fromIntegral (x `shiftR` 40) :: Word32
      withExp ex = (w .&. 0x807fffff) .|. (ex `shiftL` 23)
   in case k `mod` 7 of
        0 -> w
        -- around one
        1 -> withExp (120 + e `mod` 16)
        -- small numbers: products and quotients underflow
        2 -> withExp (e `mod` 50)
        -- large numbers: products and sums overflow
        3 -> withExp (254 - e `mod` 30)
        -- few mantissa bits set: exact results and ties
        4 -> (w .&. 0xff800000) .|. (w .&. 0x7f0003)
        -- around the bounds of 32 bit integers
        5 -> withExp (150 + e `mod` 10)
        _ -> withExp (60 + e `mod` 140)

randomFloat :: Word64 -> Word64 -> Float
randomFloat k x = castWord32ToFloat (randomWord k x)

specials :: [Float]
specials = P.map castWord32ToFloat specialWords

-- | Pairs of floats: all pairs of 'specials', followed by @n@ random pairs.
-- Some random pairs are close to each other, some multiply or divide to
-- numbers close to the smallest normal number.
floatPairs :: Int -> Word64 -> [(Float, Float)]
floatPairs n seed = [(x, y) | x <- specials, y <- specials] <> P.take n (go (randoms seed))
 where
  go (k : x : y : z : rs) =
    let a = randomFloat k x
        b = randomFloat (k `shiftR` 8) y
        pair = case z `mod` 5 of
          0 -> (a, castWord32ToFloat (castFloatToWord32 a `xor` fromIntegral (y `mod` 8)))
          1 -> (a, negate (castWord32ToFloat (castFloatToWord32 a `xor` fromIntegral (y `mod` 8))))
          -- a * b close to the smallest normal number
          2 -> (a, nearby (z `shiftR` 59) (minNormal / realToFrac a) b)
          -- a / b close to the smallest normal number
          3 -> (nearby (z `shiftR` 59) (minNormal * realToFrac b) a, b)
          _ -> (a, b)
     in pair : go rs
  go _ = []

-- | The smallest normal 'Float'
minNormal :: Double
minNormal = 2 ^^ (-126 :: Int)

-- | A 'Float' within a few units in the last place of the given number. Uses
-- the fallback if the number is out of the range of normal 'Float's.
nearby ::
  -- | Random number, chooses the distance
  Word64 ->
  -- | Number
  Double ->
  -- | Fallback
  Float ->
  Float
nearby r d fallback
  | isNaN f || isInfinite f || f == 0 || isDenormalized f = fallback
  | otherwise = castWord32ToFloat (castFloatToWord32 f + fromIntegral (r `mod` 9) - 4)
 where
  f = realToFrac d :: Float

-- | Triples of floats, see 'floatPairs'. Some random triples have a @c@ close
-- to @-a*b@, some have an @a*b@ close to the smallest normal number.
floatTriples :: Int -> Word64 -> [(Float, Float, Float)]
floatTriples n seed =
  [(x, y, z) | x <- sp, y <- sp, z <- sp] <> P.take n (go (randoms seed))
 where
  sp = P.take 14 specials
  go (k : x : y : z : rs) =
    let a = randomFloat k x
        b = randomFloat (k `shiftR` 8) y
        triple = case z `mod` 3 of
          0 -> (a, b, negate (a * b) * (1 + fromIntegral (z `shiftR` 61) * 2 ^^ (-23 :: Int)))
          1 -> (a, nearby (z `shiftR` 59) (minNormal / realToFrac a) b, if testBit z 10 then 0 else -0)
          _ -> (a, b, randomFloat (k `shiftR` 16) z)
     in triple : go rs
  go _ = []

-- | Single floats, see 'floatPairs'
floats :: Int -> Word64 -> [Float]
floats n seed = specials <> P.take n (go (randoms seed))
 where
  go (k : x : rs) = randomFloat k x : go rs
  go _ = []

-- | Doubles: the 'specials' (as doubles), interesting doubles outside of the
-- range of 'Float', followed by @n@ random ones. Most random ones are in the
-- range of 'Float', many around its smallest normal number.
doubles :: Int -> Word64 -> [Double]
doubles n seed =
  P.map realToFrac specials
    <> P.map castWord64ToDouble
      [ 0x0000000000000001, 0x8000000000000001, 0x7fefffffffffffff, 0x7ff8000000000000
      , 0xfff8000000000000, 0x7ff0000000000001, 0x47efffffe0000000, 0x47efffffefffffff
      , 0x47effffff0000000, 0x380fffffe0000000, 0x380ffffff0000000, 0x380fffffffffffff
      , 0x3810000000000000, 0x36a0000000000000, 0x3ff0000010000000, 0x3ff0000030000000 ]
    <> P.take n (go (randoms seed))
 where
  go (k : x : rs) =
    let e = case k `mod` 4 of
          0 -> (x `shiftR` 52) .&. 0x7ff
          1 -> 0x380 - 4 + (k `shiftR` 8) `mod` 8
          _ -> 0x380 + (k `shiftR` 8) `mod` 0x100
     in castWord64ToDouble ((x .&. 0x800fffffffffffff) .|. (e `shiftL` 52)) : go rs
  go _ = []

-- | 32 bit integers: interesting ones (around powers of two and the bounds),
-- followed by @n@ random ones with random magnitudes
words32 :: Int -> Word64 -> [BitVector 32]
words32 n seed =
  [0, 1, 2, 3, 0x7fffffff, 0x80000000, 0x80000001, 0xffffffff, 0xfffffffe, 0x01000001
  , 0x01000003, 0x00ffffff, 0x7fffff80, 0x7fffffc0, 0x7fffffbf, 0x02000006, 0xfefffffd]
    <> P.take n (go (randoms seed))
 where
  go (k : x : rs) = (fromIntegral x `shiftR` fromIntegral (k `mod` 32)) : go rs
  go _ = []

-- | Per cycle stimuli for the given inputs: reset for the first three
-- cycles, an enable that is high three out of four cycles, and another reset
-- of two cycles in the middle.
cycles :: [i] -> [Cycle i]
cycles [] = []
cycles inputs@(i : _) = P.zipWith3 Cycle resets enables (i : i : i : inputs)
 where
  n = P.length inputs + 3
  resets = [t < 3 || (t >= n `P.div` 2 && t < n `P.div` 2 + 2) | t <- [0 :: Int ..]]
  enables = [r `mod` 4 /= 0 | r <- randoms 0xe7ab1e]

-- * Reference traces

-- | Simulate a function under test in Haskell, and return the ROM entries for
-- the test bench. Undefined outputs aren't checked.
trace ::
  forall i o k.
  (NFDataX i, NFDataX o, BitPack o, KnownNat k) =>
  Dut i (Vec k o) ->
  [Cycle i] ->
  [Entry i k (BitSize o)]
trace dut cs = P.zipWith entry cs (sampleN (P.length cs) out)
 where
  out =
    dut
      clockGen
      (unsafeFromActiveHigh (fromList (P.map cycleReset cs <> P.repeat False)))
      (toEnable (fromList (P.map cycleEnable cs <> P.repeat True)))
      (fromList (P.map cycleInput cs <> P.repeat (cycleInput (P.last cs))))
  entry Cycle{cycleReset, cycleEnable, cycleInput} os =
    (cycleInput, cycleReset, cycleEnable, fmap check os)
  check o
    | hasUndefined o = Nothing
    | otherwise = Just (pack o)

-- | Test bench that replays the ROM entries and checks the outputs of the
-- function under test.
romTB ::
  forall n i o k.
  (KnownNat n, 1 <= n, BitPack i, NFDataX i, BitPack o, NFDataX o, KnownNat k) =>
  -- | Makes the simulation libraries of Intel part of the test bench
  (Bool -> Bool) ->
  Dut i (Vec k o) ->
  MemBlob n (BitSize (Entry i k (BitSize o))) ->
  Signal Dom Bool
romTB simLibs dut blob = simLibs <$> done
 where
  clk = tbClockGen (not <$> done)
  cnt :: Signal Dom (Index n)
  cnt = register clk noReset enableGen 0 (satSucc SatBound <$> cnt)
  entry :: Signal Dom (Entry i k (BitSize o))
  entry = unpack . asyncRomBlob blob <$> cnt
  (input, rst, en, expected) = unbundle entry
  out = dut clk (unsafeFromActiveHigh rst) (toEnable en) input
  -- Only compare outputs that are defined in the reference trace
  actual = mask <$> expected <*> fmap (fmap pack) out
  mask es os = zipWith (\e o -> if isJust e then o else 0) es os
  expected' = fmap (fmap (fromMaybe 0)) expected
  done0 = register clk noReset enableGen False ((== maxBound) <$> cnt)
  done =
    assert clk noReset "romTB" (bundle (cnt, actual)) (bundle (cnt, expected')) done0

-- * Functions under test

-- | Run a function on 'DSignal's on a 'Signal' of tuples
unary ::
  (Clock Dom -> Reset Dom -> Enable Dom -> DSignal Dom 0 a -> DSignal Dom d b) ->
  Clock Dom -> Reset Dom -> Enable Dom -> Signal Dom a -> Signal Dom b
unary f clk rst en a = D.toSignal (f clk rst en (D.fromSignal a))

binary ::
  (Clock Dom -> Reset Dom -> Enable Dom -> DSignal Dom 0 a -> DSignal Dom 0 b -> DSignal Dom d c) ->
  Clock Dom -> Reset Dom -> Enable Dom -> Signal Dom (a, b) -> Signal Dom c
binary f clk rst en ab = D.toSignal (f clk rst en (D.fromSignal a) (D.fromSignal b))
 where
  (a, b) = unbundle ab

ternary ::
  (Clock Dom -> Reset Dom -> Enable Dom -> DSignal Dom 0 a -> DSignal Dom 0 b -> DSignal Dom 0 c -> DSignal Dom d e) ->
  Clock Dom -> Reset Dom -> Enable Dom -> Signal Dom (a, b, c) -> Signal Dom e
ternary f clk rst en abc =
  D.toSignal (f clk rst en (D.fromSignal a) (D.fromSignal b) (D.fromSignal c))
 where
  (a, b, c) = unbundle abc
