#!/usr/bin/env python3
"""Generate `Clash.Cores.Intel.Floating.Internal.CoefficientsPow`: the polynomial coefficients of the single
precision power function of the bit-exact models of Intel's Floating Point Functions IP.

Usage (from the root of the repository):

  python3 tools/intel-floating-coefficients/gen_coefficients_pow.py \\
    > src/Clash/Cores/Intel/Floating/Internal/CoefficientsPow.hs

The tables are computed here, from first principles (see `recipes.py`); nothing is read from the IP.
"""

from fractions import Fraction

import mpmath as mp

from recipes import Recipe, haskell_table, main


def log_quotient(s, t):
    """`ln (1 + z) / z` on the four regions of the logarithm, each of 128 segments"""
    r, j = s >> 7, s & 127
    if r == 0:
        z = (j + t) / 256
    elif r == 1:
        z = mp.mpf(1) / 2 + (j + t) / 256
    elif r == 2:
        z = -mp.mpf(1) / 2 + (j + t) / 512
    else:
        z = -mp.mpf(1) / 4 + (j + t) / 512
    return mp.log1p(z) / z if z != 0 else mp.mpf(1) - z / 2


def exp(j, t):
    return mp.exp((j + t) / 256)


# Both tables: absolute error, five Chebyshev nodes, 200 bits of working precision.
TABLES = {
    "powLogCoefficients": Recipe(
        function=log_quotient,
        segments=512,
        grids=[37, 37, 37, 38],
        count=5,
        end=1 - Fraction(1, 2**15),
        precision=200,
        digits=60,
        delta=Fraction(99, 100),
        order="ascending",
    ),
    "powExpCoefficients": Recipe(
        function=exp,
        segments=178,
        grids=[38, 38, 38, 39],
        count=5,
        precision=200,
        digits=60,
        delta=Fraction(99, 100),
        order="ascending",
    ),
}

DOCS = {
    "powLogCoefficients": """\
{- | Logarithm: 512 segments of @P (z) = ln (1 + z) / z@, 128 per region,
index @r * 128 + s@: region 0 @z = (s + t) / 256@ (x in [1, 1.5)), 1
@z = 1/2 + (s + t) / 256@ ([1.5, 2)), 2 @z = -1/2 + (s + t) / 512@
([0.5, 0.75)) and 3 @z = -1/4 + (s + t) / 512@ ([0.75, 1)), with @t@ in
@[0, 1 - 2^-15]@ (15 fraction bits). Polynomial @C0 + C1 * t + C2 * t^2 +
C3 * t^3@; units C0, C1 and C2 2^-37, C3 2^-38.
-}""",
    "powExpCoefficients": """\
{- | Exponential: 178 segments of @exp ((j + t) / 256)@ for @t@ in @[0, 1)@
(the reduced argument is below ln 2). Polynomial @C0 + C1 * t + C2 * t^2 +
C3 * t^3@; units C0, C1 and C2 2^-38, C3 2^-39.
-}""",
}

HEADER = r"""{-|
Copyright  :  (C) 2026, QBayLogic B.V.
License    :  BSD2 (see the file LICENSE)
Maintainer :  QBayLogic B.V. <devops@qbaylogic.com>

Polynomial coefficients of the power function of Intel's Floating Point
Functions IP in single precision, see
"Clash.Cores.Intel.Floating.Internal.BitExact".

This module is generated by
@tools\/intel-floating-coefficients\/gen_coefficients_pow.py@; don't edit it
by hand.

The IP computes @x ** y@ as @exp (y * ln x)@, with a logarithm and an
exponential of about 34 bits, each a cubic polynomial per segment. The integer
coefficients of each segment were computed from first principles: the
monomials @1, t, t^2, t^3@, each scaled by the weight of its coefficient's
least significant bit and evaluated at the five Chebyshev nodes (of the first
kind) of the segment's range of @t@, span a lattice; LLL reduction
(delta = 0.99) and Babai's nearest plane algorithm give a close lattice vector
to the function's values at the nodes (absolute error), whose coordinates are
the coefficients (the method behind Sollya's @fpminimax@). Coefficient formats
were inferred from the IP's outputs and its resource reports; the coefficients
themselves are not taken from the IP and the module contains no data taken from
Intel's IP. The tables hold the plain polynomial coefficients: the model adds
the rounding constants of the datapath itself.

Each list holds @(C0, C1, C2, C3)@ per segment, in table order.
-}

{-# OPTIONS_HADDOCK hide #-}

module Clash.Cores.Intel.Floating.Internal.CoefficientsPow
  ( powLogCoefficients
  , powExpCoefficients
  ) where

import Prelude
"""


def render(tables):
    blocks = [
        haskell_table(DOCS[name], name, "(Integer, Integer, Integer, Integer)", rows) for name, rows in tables.items()
    ]
    return HEADER + "\n" + "\n\n".join(blocks) + "\n"


if __name__ == "__main__":
    main(TABLES, render, __doc__)
