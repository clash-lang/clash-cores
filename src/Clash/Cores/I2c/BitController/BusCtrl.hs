  Bus status controller of the I2C bit controller. Synchronizes and filters the
  I2C bus lines, detects START and STOP conditions, and detects arbitration
  loss.
-}
module Clash.Cores.I2c.BitController.BusCtrl where

import Clash.Prelude

import Clash.Cores.I2c.BitController.StateMachine (BitStateMachine (..))
import Clash.Cores.I2c.Types

data BusStatusCtrl = BusStatusCtrl
  { sI2c :: I2cIn
  -- ^ Synchronized and filtered SCL and SDA
  , dI2c :: I2cIn
  -- ^ Delayed 'sI2c'
  , al :: Bool
  -- ^ Internal arbitration lost signal
  , cI2c :: Vec 2 I2cIn
  -- ^ Capture SCL and SDA
  , fI2c :: Vec 3 I2cIn
  -- ^ Filter input for SCL and SDA
  , filterCnt :: Unsigned 14
  -- ^ Clock divider for filter
  , startCondition :: Bool
  -- ^ START detected
  , stopCondition :: Bool
  -- ^ STOP detected
  , busy :: Bool
  -- ^ Internal busy signal
  , cmdStop :: Bool
  -- ^ STOP command issued, but no STOP condition detected yet
  }
  deriving (Show, Generic, NFDataX)

busStartState :: BusStatusCtrl
busStartState =
  BusStatusCtrl
    { sI2c = (high, high)
    , dI2c = (high, high)
    , al = False
    , cI2c = repeat (high, high)
    , fI2c = repeat (high, high)
    , filterCnt = 0
    , startCondition = False
    , stopCondition = False
    , busy = False
    , cmdStop = False
    }

busStatusCtrl ::
  -- | Clock divider
  Unsigned 16 ->
  -- | Command
  I2cCommand ->
  -- | Clock enable
  Bool ->
  -- | I2C input
  I2cIn ->
  -- | Bit controller state
  BitStateMachine ->
  -- | Check SDA
  Bool ->
  -- | SDA output enable
  Bool ->
  BusStatusCtrl ->
  BusStatusCtrl
busStatusCtrl clkCnt cmd clkEn i2cI bitState sdaCheck sdaOutEn s =
  BusStatusCtrl
    { -- capture SCL and SDA
      cI2c = s.cI2c <<+ i2cI
    , -- filter SCL and SDA; (attempt to) remove glitches
      filterCnt = if filterTick then resize (shiftR clkCnt 2) else s.filterCnt - 1
    , fI2c = if filterTick then s.fI2c <<+ head s.cI2c else s.fI2c
    , -- filtered SCL and SDA signal
      sI2c = (majority (map fst s.fI2c), majority (map snd s.fI2c))
    , dI2c = s.sI2c
    , -- detect start condition => detect falling edge on SDA while SCL is high
      -- detect stop condition  => detect rising edge on SDA while SCL is high
      startCondition = sSda == low && dSda == high && sScl == high
    , stopCondition = sSda == high && dSda == low && sScl == high
    , -- i2c busy signal
      busy = (s.startCondition || s.busy) && not s.stopCondition
    , cmdStop = cmdStopNext
    , al = arbitrationLost
    }
 where
  filterTick = s.filterCnt == 0
  (sScl, sSda) = s.sI2c
  dSda = snd s.dI2c

  -- generate arbitration lost signal
  -- arbitration lost when:
  -- 1) controller drives SDA high, but the i2c bus is low
  -- 2) stop detected while not requested
  --
  -- Unexpected STOP conditions are only detected while executing a command, as
  -- STOP conditions observed while idle were generated by another controller
  -- while this controller was not using the bus.
  --
  -- The STOP condition generated by this controller is observed through the
  -- input synchronizer and filter, so it can be detected after the bit
  -- controller has already started executing the next command. 'cmdStop' is therefore set
  -- when a STOP command is issued, and only cleared once a STOP condition has
  -- been detected.
  controllerHighBusLow = sdaCheck && sSda == low && sdaOutEn

  cmdStopNext
    | clkEn && cmd == I2cStop = True
    | s.stopCondition = False
    | otherwise = s.cmdStop

  arbitrationLost =
    controllerHighBusLow || (bitState /= Idle && s.stopCondition && not s.cmdStop)

  majority :: Vec 3 Bit -> Bit
  majority (a :> b :> c :> _) = (a .&. b) .|. (a .&. c) .|. (b .&. c)
