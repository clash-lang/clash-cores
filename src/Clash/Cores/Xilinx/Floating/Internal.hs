-- | Customize Xilinx floating point IP.
--
-- These customizations influence how the IP will be synthesized. They do not
-- affect behavior.
data Config = Config
  { archOpt :: !ArchOpt
    -- ^ Architecture optimizations
  , dspUsage :: !DspUsage
    -- ^ DSP slice usage
  , bMemUsage :: !BMemUsage
    -- ^ Block memory usage of the square root in half precision and of the
    -- exponential in single and double precision
  } deriving (Eq, Show)

-- | Architecture optimizations.
--
-- For those operations that support different architecture optimizations.
data ArchOpt
  = SpeedArch
    -- ^ Speed-optimized architecture
  | LatencyArch
    -- ^ Low latency architecture
  deriving (Eq, Show)

archOptToTcl :: ArchOpt -> String
archOptToTcl = \case
  SpeedArch -> "Speed_Optimized"
  LatencyArch -> "Low_Latency"

-- | DSP slice usage.
--
-- For those operations that can use DSP slices. Not all such operations support
-- all variants.
data DspUsage
  = NoDspUsage
    -- ^ Do not use any DSP slices
  | MediumDspUsage
  | FullDspUsage
  | MaxDspUsage
  deriving (Eq, Show)

dspUsageToTcl :: DspUsage -> String
dspUsageToTcl = \case
  NoDspUsage -> "No_Usage"
  MediumDspUsage -> "Medium_Usage"
  FullDspUsage -> "Full_Usage"
  MaxDspUsage -> "Max_Usage"

-- | Block memory usage.
--
-- Configures whether the square root in half precision uses block memory,
-- which lowers its maximum latency, and whether the exponential in single and
-- double precision uses block memory for its tables instead of distributed
-- memory, which can raise its maximum latency by one. The other operations,
-- including the square root in single and double precision and the
-- exponential in half precision, ignore this setting. (The reciprocal and
-- reciprocal square root in half precision always use block memory.)
data BMemUsage
  = NoBMemUsage
    -- ^ Do not use block memory
  | FullBMemUsage
    -- ^ Use block memory
  deriving (Eq, Show)

bMemUsageToTcl :: BMemUsage -> String
bMemUsageToTcl = \case
  NoBMemUsage -> "No_Usage"
  FullBMemUsage -> "Full_Usage"

-- | NaN as generated by Xilinx.
--
-- Quiet NaN, no payload, positive.
xilinxNaN :: Float
xilinxNaN = unpack 0x7FC00000

-- | Perform the same conditioning on a Float as the Xilinx IP does.
--
-- All NaNs are mapped to 'xilinxNaN', all subnormal numbers to zero.
--
-- Note that there are a few exceptions where the Xilinx IP does not condition
-- Float values. Those functions are documented as such.
--
-- __NB__: Not synthesizable
conditionFloat
  :: Float
  -> Float
conditionFloat = xilinxCondition

-- | Perform the same conditioning on a Float as the Xilinx IP does.
--
-- 'conditionFloat' lifted to 'Functor'.
--
-- __NB__: Not synthesizable
conditionFloatF
  :: Functor f
  => f Float
  -> f Float
conditionFloatF = fmap conditionFloat

-- | Round a result to a Float the way the Xilinx IP does: round to 24
-- significant bits as if the exponent were unbounded, then flush results below
-- the smallest normal number to a zero of the same sign. NaNs become
-- 'xilinxNaN'.
--
-- IEEE rounding instead rounds results below the smallest normal number to the
-- subnormal grid. For results just below the smallest normal number, from
-- @2^-126 - 2^-150@ up to @2^-126 - 2^-151@, it gives the smallest normal
-- number where the IP gives zero.
--
-- __NB__: Not synthesizable
xilinxRound :: Double -> Float
xilinxRound d
  | isNaN d = xilinxNaN
  | abs d >= float2Double minNormalF = double2Float d
  | roundsToMinNormal = if d < 0 then negate minNormalF else minNormalF
  | d < 0 || isNegativeZero d = -0
  | otherwise = 0
 where
  minNormalF = 2 ^^ (-126 :: Int) :: Float
  -- Scale into the normal range of Float, so that 'double2Float' rounds to 24
  -- significant bits. Scaling by a power of two is exact.
  roundsToMinNormal =
    abs (double2Float (scaleFloat 64 d)) >= scaleFloat 64 minNormalF

-- | Floating point formats the Xilinx Floating-Point IP supports: 'Half',
-- 'Float' (single precision) and 'Double'. The IP supports no others, so there
-- is no need to define other instances.
class (BitPack a, NFDataX a, RealFloat a) => XilinxFloat a where
  -- | Name of the precision in the IP's settings, e.g. @Single@
  precisionName :: proxy a -> String

  -- | Width of the exponent, in bits
  exponentWidth :: proxy a -> Integer

  -- | Width of the significand including its hidden bit, which the IP calls
  -- the fraction width
  fractionWidth :: proxy a -> Integer

  -- | NaN as generated by the IP: quiet, no payload, positive
  ipNaN :: a

  -- | Model of an operation of the IP with two inputs: addition, subtraction,
  -- multiplication or division. Like the IP, it treats every NaN input as the
  -- NaN the IP generates and subnormal inputs as a zero of the same sign. It
  -- rounds the result to full precision before flushing a result below the
  -- smallest normal number to a zero of the same sign. Clash simulation uses
  -- this model.
  --
  -- __NB__: Not synthesizable
  xilinxBinary :: (forall b. Fractional b => b -> b -> b) -> a -> a -> a
  xilinxBinary = xilinxBinaryExact

instance XilinxFloat Half where
  precisionName _ = "Half"
  exponentWidth _ = 5
  fractionWidth _ = 11
  ipNaN = unpack 0x7E00

-- | For single precision, the model computes the result as a 'Double' and
-- rounds it to a 'Float' like the IP does. That gives the same result as
-- computing the exact result, because a 'Double' has more than twice the
-- precision of a 'Float' plus two bits, and it is much faster.
instance XilinxFloat Float where
  precisionName _ = "Single"
  exponentWidth _ = 8
  fractionWidth _ = 24
  ipNaN = xilinxNaN
  xilinxBinary f x y = xilinxRound (f (cond x) (cond y))
   where
    cond = float2Double . conditionFloat

instance XilinxFloat Double where
  precisionName _ = "Double"
  exponentWidth _ = 11
  fractionWidth _ = 53
  ipNaN = unpack 0x7FF8000000000000

-- | Condition an input the way the IP does: all NaNs become 'ipNaN', and all
-- subnormal numbers become a zero of the same sign.
--
-- __NB__: Not synthesizable
xilinxCondition :: XilinxFloat a => a -> a
xilinxCondition x
  | isNaN x          = ipNaN
  | isDenormalized x = if x > 0 then 0 else -0
  | otherwise        = x

-- | Model of an operation of the IP with two inputs, computing the exact
-- result as a 'Rational' and rounding it with 'xilinxRoundExact'. Results that
-- are NaN, infinite or exactly zero follow from computing in the target type
-- itself, which handles their signs as IEEE prescribes.
--
-- So do results whose magnitude is above the smallest normal number, which
-- saves computing the exact result for most inputs. Rounding is monotonic, so
-- the exact result is above the smallest normal number too, and there the IP
-- rounds like IEEE. 'Half' computes in 'Float' and rounds that to 'Half', and
-- so does 'fromRational' for 'Half', so the same holds for 'Half'. A result
-- equal to the smallest normal number does not qualify: IEEE rounds some exact
-- results just below it up to it, where the IP gives zero (see 'xilinxRound').
--
-- __NB__: Not synthesizable
xilinxBinaryExact ::
  XilinxFloat a => (forall b. Fractional b => b -> b -> b) -> a -> a -> a
xilinxBinaryExact f (xilinxCondition -> x) (xilinxCondition -> y)
  | isNaN native = ipNaN
  | isInfinite native || isInfinite x || isInfinite y = native
  | abs native > minNormal = native
  | exact == 0 = native
  | otherwise = xilinxRoundExact exact
 where
  native = f x y
  exact = f (toRational x) (toRational y)
  minNormal = encodeFloat 1 (fst (floatRange x) - 1)

-- | Round a non-zero exact result the way the IP does: round to the precision
-- of the target type as if the exponent were unbounded, then flush results
-- below the smallest normal number to a zero of the same sign. See
-- 'xilinxRound' for why this differs from IEEE rounding.
--
-- __NB__: Not synthesizable
xilinxRoundExact :: forall a. RealFloat a => Rational -> a
xilinxRoundExact r
  | abs r >= minNormal = fromRational r
  -- Scale such that the smallest normal number becomes one. Rounding the
  -- scaled value then rounds to the full precision, and rounds up to one if
  -- and only if the unscaled value rounds up to the smallest normal number.
  | abs (fromRational (r * 2 ^^ (1 - emin)) :: a) >= 1 =
      if r < 0 then negate (fromRational minNormal) else fromRational minNormal
  | r < 0 = -0
  | otherwise = 0
 where
  emin = fst (floatRange (undefined :: a))
  minNormal = 2 ^^ (emin - 1) :: Rational

-- | Round @m * 2^e@, for a non-zero integer @m@, the way the IP does: to the
-- precision of the target type as if the exponent were unbounded (to nearest,
-- ties to even), and then to a zero of the same sign if the magnitude is below
-- the smallest normal number, or to an infinity of the same sign if it is at
-- least @2^emax@ (it rounded beyond the largest finite number). Like
-- 'xilinxRoundExact', but it uses integer arithmetic only, so it rounds
-- exactly in every precision. ('fromRational' to 'Half' rounds to 'Float'
-- first, which can round wrongly.)
--
-- __NB__: Not synthesizable
xilinxRoundScaled :: forall a. RealFloat a => Integer -> Int -> a
xilinxRoundScaled m e
  | m < 0 = negate (xilinxRoundScaled (negate m) e)
  | top > emax = 1 / 0
  | top < emin = 0
  -- Exact: 'q' has at most 'p' significant bits (if rounding carried, it is a
  -- power of two) and the result is a normal number. For 'Half',
  -- 'encodeFloat' goes through 'Float', which is exact as well.
  | otherwise = encodeFloat q (e + dropped)
 where
  p = floatDigits (undefined :: a)
  -- The smallest normal number is @2^(emin-1)@, the largest finite number is
  -- just below @2^emax@
  (emin, emax) = floatRange (undefined :: a)
  -- Drop the bits below the precision, rounding to nearest, ties to even
  dropped = max 0 (bitLength m - p)
  q = roundShiftR dropped m
  -- The rounded magnitude @q * 2^(e + dropped)@ lies in @[2^(top-1), 2^top)@
  top = e + dropped + bitLength q

-- | Number of bits of a positive integer
bitLength :: Integer -> Int
bitLength i = fromIntegral (integerLog2 i) + 1

-- | Shift a non-negative integer to the right by the given number of bits,
-- rounding to nearest, ties to even.
roundShiftR :: Int -> Integer -> Integer
roundShiftR s m
  | s <= 0 = m
  | rest > half || (rest == half && odd q) = q + 1
  | otherwise = q
 where
  q = m `shiftR` s
  rest = m .&. (bit s - 1)
  half = bit (s - 1)

-- | Model of the IP's fused multiply-add, @x * y + z@ with a single rounding.
--
-- Like the IP, it treats every NaN input as the NaN the IP generates and
-- subnormal inputs as a zero of the same sign. The exact result, computed with
-- 'Integer's, is rounded once like the other operations round theirs
-- ('xilinxRoundScaled'): to nearest, ties to even, as if the exponent were
-- unbounded, then to a zero of the same sign below the smallest normal number
-- and to an infinity of the same sign beyond the largest finite number. So a
-- product beyond the largest finite number gives a finite result if the addend
-- brings the sum back in range.
--
-- The special cases follow IEEE 754: an infinity times a zero is NaN, and so
-- is the sum of an infinite product and an infinite addend of the opposite
-- sign. An exact result of zero is a positive zero, unless the product and the
-- addend are both negative zeros (@-0 * y + -0@ for positive @y@, say).
--
-- __NB__: Not synthesizable
xilinxFma :: XilinxFloat a => a -> a -> a -> a
xilinxFma (xilinxCondition -> x) (xilinxCondition -> y) (xilinxCondition -> z)
  | isNaN x || isNaN y || isNaN z = ipNaN
  -- The product is infinite, or NaN for an infinity times a zero. Computing it
  -- in the type itself gets its sign right.
  | isInfinite x || isInfinite y =
      if isNaN p || (isInfinite z && z /= p) then ipNaN else p
  | isInfinite z = z
  -- Exact zero: the sum of a product and an addend that are both zero has the
  -- sign IEEE 754 prescribes, see above. The product of zeros is exact.
  | m == 0 = if isNegativeZero p && isNegativeZero z then -0 else 0
  | otherwise = xilinxRoundScaled m e
 where
  p = x * y
  (mx, ex) = decodeFloat x
  (my, ey) = decodeFloat y
  (mz, ez) = decodeFloat z
  -- The exact result is m * 2^e: align the product and the addend to the
  -- smaller of their exponents. Zeros do not take part, so that their exponent
  -- of zero does not make the shifts needlessly large.
  terms = P.filter ((/= 0) . fst) [(mx * my, ex + ey), (mz, ez)]
  e = if P.null terms then 0 else P.minimum (P.map snd terms)
  m = P.sum [t `shiftL` (et - e) | (t, et) <- terms]

-- | Model of the IP's square root.
--
-- Like the IP, it treats every NaN input as the NaN the IP generates and
-- subnormal inputs as a zero of the same sign. The square root of a negative
-- zero is a negative zero, so negative subnormal inputs give a negative zero.
-- The square root of any other negative number, including negative infinity,
-- is NaN.
--
-- The square roots of normal numbers are normal numbers, so no flushing to
-- zero or overflow happens. The IP rounds them to nearest, like 'sqrt' does
-- for 'Float' and 'Double': IEEE 754 requires square roots to be correctly
-- rounded. Square roots are never exactly halfway between two numbers, so ties
-- do not occur. 'sqrt' for 'Half' takes the square root in 'Float' and rounds
-- that to 'Half'. Rounding twice gives the correctly rounded square root as
-- long as the intermediate precision has at least @2p + 2@ bits, for a
-- precision of @p@ bits (S. A. Figueroa, "When is double rounding
-- innocuous?", 1995): 'Float' has 24, and @2 * 11 + 2 = 24@.
--
-- __NB__: Not synthesizable
xilinxSqrt :: XilinxFloat a => a -> a
xilinxSqrt (xilinxCondition -> x)
  | isNaN x = ipNaN
  | x == 0 = x
  | x < 0 = ipNaN
  | otherwise = sqrt x

-- | Model of the IP's absolute value: it clears the sign bit and nothing else.
-- Unlike the other operations, it leaves subnormal numbers and NaNs (including
-- their payloads) alone.
--
-- __NB__: Not synthesizable
xilinxAbs :: XilinxFloat a => a -> a
xilinxAbs x = unpack (clearBit bits (finiteBitSize bits - 1))
 where
  bits = pack x

-- | Model of the IP's conversion between precisions, including conversions to
-- the same precision.
--
-- Like the IP, it treats every NaN input as the NaN the IP generates and
-- subnormal inputs as a zero of the same sign. Conversions to a narrower
-- precision round like the arithmetic operations do, see
-- 'xilinxRoundScaled': to nearest, ties to even, as if the exponent were
-- unbounded, then to a zero of the same sign below the smallest normal number
-- and to an infinity of the same sign beyond the largest finite number.
-- Conversions to the same or a wider precision are exact, apart from the
-- treatment of NaNs and subnormal inputs.
--
-- __NB__: Not synthesizable
xilinxConvert :: forall a b. (XilinxFloat a, XilinxFloat b) => a -> b
xilinxConvert (xilinxCondition -> x)
  | isNaN x = ipNaN
  | isInfinite x = if x < 0 then -1 / 0 else 1 / 0
  | x == 0 = if isNegativeZero x then -0 else 0
  | otherwise = uncurry xilinxRoundScaled (decodeFloat x)

-- | Model of the IP's conversion of an integer to a floating point number:
-- round to nearest, ties to even. Zero becomes a positive zero.
--
-- __NB__: Not synthesizable
xilinxFromInteger :: RealFloat a => Integer -> a
xilinxFromInteger 0 = 0
xilinxFromInteger i = xilinxRoundScaled i 0

-- | Model of the IP's conversion of a floating point number to a 32-bit signed
-- integer.
--
-- It rounds to nearest, ties to even, and saturates results that do not fit,
-- including infinities. Every NaN becomes 'minBound'. Like other operations,
-- the IP treats subnormal inputs as zero.
--
-- __NB__: Not synthesizable
xilinxToS32 :: XilinxFloat a => a -> Signed 32
xilinxToS32 (xilinxCondition -> x)
  | isNaN x = minBound
  | isInfinite x = if x < 0 then minBound else maxBound
  -- 'round' rounds ties to even
  | otherwise = fromInteger (max lo (min hi (round (toRational x))))
 where
  lo = toInteger (minBound :: Signed 32)
  hi = toInteger (maxBound :: Signed 32)

{- Note [Correctly rounded models]
The IP's reciprocal, reciprocal square root, exponential and logarithm are not
correctly rounded: the datasheet only promises results accurate to one unit in
the last place (except for the reciprocal and reciprocal square root in half
precision, which are correctly rounded). The IP's exact algorithms are not
documented, so instead of the IP's results, the models below give the correctly
rounded results: the exact result rounded the way the other operations round
theirs ('xilinxRoundScaled'), with the IP's treatment of NaNs, subnormal inputs
and the special cases.

The reciprocal and the reciprocal square root of a number with a significand
of @p@ bits follow from an integer division and an integer square root with at
least @p + 2@ significant bits, plus a bit that tells whether the remainder is
zero. That is enough to round correctly.

The exponential and the logarithm are transcendental: for a rational input
other than zero (and one, for the logarithm), the exact result is irrational,
so it is never a number of the precision nor halfway between two of them. The
models use Ziv's strategy: they compute an approximation in fixed point with a
proven bound on its error, giving an interval that contains the exact result.
If both ends of that interval round to the same number, so does the exact
result. Otherwise, which happens rarely, they compute again with twice as many
bits, and so on. Since the exact result is not halfway between two numbers,
this always ends. All arithmetic is on 'Integer's, so the error bounds hold
exactly.
-}

-- | Model of the IP's reciprocal, @1 / x@, rounded correctly (see the
-- documentation of @recip@ in "Clash.Cores.Xilinx.Floating").
--
-- Like the IP, it treats every NaN input as the NaN the IP generates and
-- subnormal inputs as a zero of the same sign. The reciprocal of a zero is an
-- infinity of the same sign, that of an infinity a zero of the same sign.
-- Results below the smallest normal number become a zero of the same sign.
--
-- __NB__: Not synthesizable
xilinxRecip :: XilinxFloat a => a -> a
xilinxRecip (xilinxCondition -> x)
  | isNaN x = ipNaN
  | x == 0 = if isNegativeZero x then -1 / 0 else 1 / 0
  | isInfinite x = if x < 0 then -0 else 0
  | otherwise = xilinxRoundScaled (signum m * (2 * q + sticky)) (negate (e + s + p + 2))
 where
  p = floatDigits x
  (m, e) = decodeFloat x
  s = bitLength (abs m)
  -- 1 / x = 2^(s+p+1) / |m| * 2^-(e+s+p+1), where the quotient lies in
  -- (2^(p+1), 2^(p+2)]: it has at least p + 2 bits.
  (q, r) = bit (s + p + 1) `quotRem` abs m
  -- The remainder only matters for rounding through whether it is zero:
  -- 2q + 1 stands for any number between 2q and 2q + 2.
  sticky = if r == 0 then 0 else 1

-- | Model of the IP's reciprocal square root, @1 / sqrt x@, rounded correctly
-- (see the documentation of @rsqrt@ in "Clash.Cores.Xilinx.Floating").
--
-- Like the IP, it treats every NaN input as the NaN the IP generates and
-- subnormal inputs as a zero of the same sign. The reciprocal square root of a
-- zero is an infinity of the same sign, so that of a negative subnormal
-- number is negative infinity. That of any other negative number, including
-- negative infinity, is NaN. That of positive infinity is positive zero.
--
-- __NB__: Not synthesizable
xilinxRSqrt :: XilinxFloat a => a -> a
xilinxRSqrt (xilinxCondition -> x)
  | isNaN x = ipNaN
  | x == 0 = if isNegativeZero x then -1 / 0 else 1 / 0
  | x < 0 = ipNaN
  | isInfinite x = 0
  | otherwise = xilinxRoundScaled (2 * y + sticky) (negate (h + k + 1))
 where
  p = floatDigits x
  (m0, e0) = decodeFloat x
  -- x = m * 2^(2h), with an even exponent
  (m, h) = if even e0 then (m0, e0 `div` 2) else (2 * m0, (e0 - 1) `div` 2)
  -- 1 / sqrt x = sqrt (2^(2k) / m) * 2^-(h+k). With m < 2^s, the square root
  -- is more than 2^(k - s/2) >= 2^(p+1), so it has at least p + 2 bits.
  k = p + 2 + (bitLength m + 1) `div` 2
  (q, r) = bit (2 * k) `quotRem` m
  -- floor (sqrt (2^(2k) / m)) = floor (sqrt q)
  y = integerSqrt q
  sticky = if r == 0 && y * y == q then 0 else 1

-- | Model of the IP's exponential, @e^x@, rounded correctly (see the
-- documentation of @exp@ in "Clash.Cores.Xilinx.Floating").
--
-- Like the IP, it treats every NaN input as the NaN the IP generates and
-- subnormal inputs as a zero of the same sign, whose exponential is one. The
-- exponential of positive infinity is positive infinity, that of negative
-- infinity positive zero. Results beyond the largest finite number become
-- positive infinity, results below the smallest normal number positive zero.
--
-- __NB__: Not synthesizable
xilinxExp :: forall a. XilinxFloat a => a -> a
xilinxExp (xilinxCondition -> x)
  | isNaN x = ipNaN
  | isInfinite x = if x > 0 then x else 0
  | x == 0 = 1
  -- e^x > e^emax > 2^emax: rounds to infinity
  | x > fromIntegral emax = 1 / 0
  -- e^x < e^(emin-2) < 2^(emin-2): rounds to below the smallest normal number,
  -- 2^(emin-1)
  | x < fromIntegral (emin - 2) = 0
  -- 1 + x < e^x < 1 + 2x for 0 < x < 1: with |x| < 2^-(p+2), e^x is closer to
  -- one than halfway to the numbers next to it, 1 - 2^-(p+1) and 1 + 2^(1-p).
  | e < negate (p + 2) - bitLength (abs m) = 1
  | otherwise = ziv (expApprox m e)
 where
  p = floatDigits x
  (emin, emax) = floatRange x
  (m, e) = decodeFloat x

-- | Model of the IP's natural logarithm, @log x@, rounded correctly (see the
-- documentation of @log@ in "Clash.Cores.Xilinx.Floating").
--
-- Like the IP, it treats every NaN input as the NaN the IP generates and
-- subnormal inputs as a zero of the same sign. The logarithm of a zero of
-- either sign, and so of a subnormal number, is negative infinity. That of any
-- other negative number, including negative infinity, is NaN. That of
-- positive infinity is positive infinity, and that of one positive zero.
--
-- __NB__: Not synthesizable
xilinxLog :: XilinxFloat a => a -> a
xilinxLog (xilinxCondition -> x)
  | isNaN x = ipNaN
  | x == 0 = -1 / 0
  | x < 0 = ipNaN
  | isInfinite x = x
  | x == 1 = 0
  | otherwise = ziv (logApprox m e)
 where
  (m, e) = decodeFloat x

-- | Ziv's strategy, see Note [Correctly rounded models]. Given an
-- approximation with a working precision of @w@ bits, @approx w = (v, err, e)@
-- such that the exact result lies in @[(v - err) * 2^e, (v + err) * 2^e]@ and
-- @err@ is about @2^-w@ times @v@, try more bits until the interval decides
-- how the exact result rounds.
ziv :: forall a. XilinxFloat a => (Int -> (Integer, Integer, Int)) -> a
ziv approx = go (floatDigits (undefined :: a) + 24)
 where
  go w
    | lo /= 0 && signum lo == signum hi && rLo == rHi = rLo
    | otherwise = go (2 * w)
   where
    (v, err, e) = approx w
    lo = v - err
    hi = v + err
    -- 'xilinxRoundScaled' is monotonic, so if both ends of the interval round
    -- to the same number, everything in between does. Both have the same sign,
    -- so comparing with '==' is exact (zeros have the same sign too).
    rLo = xilinxRoundScaled lo e :: a
    rHi = xilinxRoundScaled hi e

-- | Approximation of @e^x@ for a non-zero @x = m * 2^e@ with
-- @|x| < 2^13@, for 'ziv', with @w@ bits after the binary point.
--
-- Reduce the argument with @x = k * ln 2 + r@, so that @e^x = 2^k * e^r@ and
-- @|r| <= ln 2 / 2 + 2^-w@, and sum the Taylor series of @e^r@ in fixed point.
--
-- Errors, in units of @2^-w@:
--
-- * @x * 2^w@ rounded down: less than 1. @ln 2@ has @g@ more bits, with an
--   error less than 3, so @k * ln 2@ (@|k| < 2^14@) is off by less than
--   @3 * 2^14 / 2^g < 1@, plus less than 1 for rounding it to @w@ bits. So
--   @|R - r * 2^w| < 3@, where @R@ is the computed @r@.
--
-- * The Taylor series of @e^(R / 2^w)@: each computed term is within 2 of the
--   exact term, see 'expTaylor', and the terms after the last one add less
--   than 2: less than @2n + 2@ for @n@ terms after the first (which is exact).
--
-- * @e^(r)@ versus @e^(R / 2^w)@: less than @e^0.36 * 3 < 5@.
expApprox :: Integer -> Int -> Int -> (Integer, Integer, Int)
expApprox m e w = (s, 2 * toInteger nTerms + 8, fromInteger k - w)
 where
  g = 16
  -- x * 2^w, rounded down
  xw = shiftFloor m (e + w)
  l = ln2Fixed (w + g)
  -- x / ln 2, rounded to nearest
  k = (2 * (xw `shiftL` g) + l) `div` (2 * l)
  r = xw - ((k * l) `shiftR` g)
  (s, nTerms) = expTaylor w r

-- | Sum of the Taylor series of @e^(r / 2^w)@ in fixed point with @w@ bits
-- after the binary point, for @|r| <= 2^(w-1)@, and the number of terms after
-- the first.
--
-- The term @T_i@ is the previous one times @r@, rounded down to @w@ bits, then
-- divided by @i@ and rounded towards zero. If the previous term was within
-- @E_(i-1)@ of the exact @t_(i-1)@, @T_i@ is within
-- @(E_(i-1) * |r| / 2^w + 1) / i + 1 <= (E_(i-1) / 2 + 1) / i + 1@ of @t_i@,
-- and by induction (@E_0 = 0@) within 2. The sum stops at the first term that
-- is zero. The exact terms after it are at most 2 times @(1/4)^j@ (@|r| < 1/2@,
-- @i >= 1@), which adds less than 1.
expTaylor :: Int -> Integer -> (Integer, Int)
expTaylor w r = go (bit w) (bit w) 1
 where
  go !acc !term !i
    | term' == 0 = (acc, i)
    | otherwise = go (acc + term') term' (i + 1)
   where
    term' = ((term * r) `shiftR` w) `quot` toInteger i

-- | Approximation of @log x@ for @x = m * 2^e@, with @m > 0@ and @x /= 1@,
-- for 'ziv', with a precision of about @w@ bits relative to @log x@.
--
-- Write @x = (m / d) * 2^k@ with @m / d@ in @(sqrt 2 / 2, sqrt 2]@, so
-- @log x = k * ln 2 + 2 * atanh z@ with @z = (m - d) / (m + d)@ and
-- @|z| <= 0.172@. If @k /= 0@, @|log x| > ln 2 / 2@. If @k = 0@, @log x@ is
-- about @2z@, so the fixed point numbers get as many more bits as @z@ has
-- leading zeros.
--
-- Errors: the series is within @err@ of @atanh z@ (see 'atanhFixed'), so twice
-- it within @2 err@. Like in 'expApprox', @k * ln 2@ (@|k| < 2^14@) is within 2.
logApprox :: Integer -> Int -> Int -> (Integer, Integer, Int)
logApprox m e w = (v, 2 * err + 2, negate wf)
 where
  b = bitLength m
  -- (m / 2^(b-1))^2 > 2
  big = m * m > bit (2 * b - 1)
  (d, k) = if big then (bit b, e + b) else (bit (b - 1), e + b - 1)
  num = m - d
  extra
    | k /= 0 || num == 0 = 2
    | otherwise = max 0 (bitLength (m + d) - bitLength (abs num)) + 2
  wf = w + extra
  g = 16
  (s, err) = atanhFixed wf num (m + d)
  v = 2 * s + ((toInteger k * ln2Fixed (wf + g)) `shiftR` g)

-- | @atanh (a / b)@ in fixed point with @w@ bits after the binary point, for
-- @|a / b| <= 1/2@, and a bound on its error: @(v, err)@ such that the exact
-- result lies in @[v - err, v + err]@ (in units of @2^-w@).
--
-- For @z = a / b >= 0@: @atanh z = sum (z^(2j+1) / (2j+1))@. The computed @z@ is
-- rounded down, less than 1 below the exact one, its square less than 2 below
-- the exact one (@z <= 1/2@). The powers @U_j@ are the previous one times @z^2@,
-- rounded down; @u_j - U_j < (u_(j-1) - U_(j-1)) / 4 + 1 + 1@, so by induction
-- (@u_0 - U_0 < 1@) @U_j@ is less than 3 below @u_j@. Dividing by @2j+1@ and
-- rounding down, the terms are less than 2 below the exact ones (less than 1
-- for the first). The sum stops at the first power that is zero, so the exact
-- ones after it are less than @3 * (1/4)^i@, which adds less than 4.
atanhFixed :: Int -> Integer -> Integer -> (Integer, Integer)
atanhFixed w a b
  | a < 0 = let (v, err) = atanhFixed w (negate a) b in (negate v, err)
  | otherwise = go 0 z 0 0
 where
  z = (a `shiftL` w) `quot` b
  z2 = (z * z) `shiftR` w
  go :: Integer -> Integer -> Integer -> Int -> (Integer, Integer)
  go !acc !u !j !cnt
    | u == 0 = (acc, 2 * toInteger cnt + 5)
    | otherwise =
        go (acc + u `quot` (2 * j + 1)) ((u * z2) `shiftR` w) (j + 1) (cnt + 1)

-- | @ln 2@ in fixed point with @w@ bits after the binary point, within 3 of
-- the exact value (in units of @2^-w@).
ln2Fixed :: Int -> Integer
ln2Fixed w
  | w <= ln2Bits = ln2Table `shiftR` (ln2Bits - w)
  | otherwise = ln2Compute w

-- | Number of bits after the binary point of 'ln2Table'
ln2Bits :: Int
ln2Bits = 1024

-- | @ln 2@ with 'ln2Bits' bits after the binary point, computed once
ln2Table :: Integer
ln2Table = ln2Compute ln2Bits
{-# NOINLINE ln2Table #-}

-- | @ln 2 = 2 * atanh (1/3)@ in fixed point with @w@ bits after the binary
-- point, within 2 of the exact value: computed with 32 more bits (error less
-- than @2 * err@, far less than @2^32@), then rounded down to @w@ bits.
ln2Compute :: Int -> Integer
ln2Compute w = (2 * fst (atanhFixed (w + 32) 1 3)) `shiftR` 32

-- | @m * 2^e@ rounded down to an integer
shiftFloor :: Integer -> Int -> Integer
shiftFloor m e
  | e >= 0 = m `shiftL` e
  | otherwise = m `shiftR` negate e

-- | Integer square root: the largest integer whose square is at most the given
-- non-negative integer.
--
-- __NB__: Not synthesizable
integerSqrt :: Integer -> Integer
integerSqrt i
  | i < 0 = P.error "integerSqrt: negative number"
  | i < 2 = i
  | otherwise = newton start
 where
  -- Estimate from the most significant (at most 53) bits, after shifting out an
  -- even number of bits. 'sqrt' of a 'Double' rounds correctly and converting
  -- at most 53 bits to a 'Double' is exact, so 'start' is at least the square
  -- root: floor (sqrt h) + 1 >= sqrt (h + 1).
  t = max 0 ((bitLength i - 52) `div` 2)
  start = (floor (P.sqrt (fromInteger (i `shiftR` (2 * t)) :: Double)) + 1) `shiftL` t
  -- Newton's iteration from above
  newton x =
    let x' = (x + i `quot` x) `shiftR` 1
    in if x' >= x then x else newton x'

-- | One-hot encoded version of t'Prelude.Ordering'. The order of fields is
-- chosen to match the ordering picked by Xilinx's Floating Point comparison IP.
data Ordering
  = EQ
  | LT
  | GT
  | NaN
  deriving (Generic, NFDataX, Eq, ShowX, Show, Lift)
deriveAnnotation (simpleDerivator OneHot Wide) [t| Ordering |]
deriveBitPack [t| Ordering |]

-- | Converts t'Ordering' to Prelude's t'Prelude.Ordering'. If the given
-- ordering is 'NaN', 'Nothing' is returned.
toMaybeOrdering :: Ordering -> Maybe P.Ordering
toMaybeOrdering = \case
  EQ -> Just P.EQ
  LT -> Just P.LT
  GT -> Just P.GT
  NaN -> Nothing

-- | Perform comparison on two floating point numbers. The type returned is a
-- locally defined version of t'Ordering'. If you want prelude's
-- t'Prelude.Ordering', see 'toMaybeOrdering'.
xilinxCompare :: XilinxFloat a => a -> a -> Ordering
xilinxCompare x y
  | isNaN x = NaN
  | isNaN y = NaN
  | otherwise =
      case compare (xilinxCondition x) (xilinxCondition y) of
        P.LT -> LT
        P.EQ -> EQ
        P.GT -> GT

-- | Width of an AXI4-Stream @TDATA@ field carrying @n@ bits: @n@ rounded up to
-- a whole number of bytes. Inputs are padded with zeros; the padding bits of
-- outputs are dropped.
type AxiWidth n = 8 * DivRU n 8

-- | Wizard settings for the Floating-Point IP: the settings every instance in
-- this module shares, followed by the given extra options.
floatingWizard ::
  forall d nExtraOpts .
  -- | Latency
  SNat d ->
  -- | @CONFIG.Operation_Type@. E.g., @Divide@.
  String ->
  -- | Extra Wizard options (will be added to the default ones)
  Vec nExtraOpts (OptionName, XilinxWizardOption) ->
  XilinxWizard (6 + nExtraOpts)
floatingWizard SNat operType extraOptions =
  XilinxWizard
    { wiz_name = "floating_point"
    , wiz_vendor = "xilinx.com"
    , wiz_library = "ip"
    , wiz_version = "7.1"
    , wiz_options =
         ("CONFIG.Operation_Type",     StrOpt operType)
      :> ("CONFIG.Flow_Control",       StrOpt "NonBlocking")
      :> ("CONFIG.Has_ACLKEN",         BoolOpt True)
      :> ("CONFIG.Has_RESULT_TREADY",  BoolOpt False)
      :> ("CONFIG.Maximum_Latency",    BoolOpt False)
      :> ("CONFIG.C_Latency",          IntegerOpt (natToNum @d))
      :> extraOptions
    }
{-# INLINE floatingWizard #-}

-- | Instantiate the Floating-Point IP for an operation with one input
unaryInst ::
  forall d nExtraOpts n dom a b .
  ( KnownNat nExtraOpts
  , KnownDomain dom
  , KnownNat d
  , BitPack a
  , BitPack b
  ) =>
  -- | Instantiation type hint
  String ->
  -- | @CONFIG.Operation_Type@. E.g., @Fixed_to_float@.
  String ->
  -- | Extra Wizard options (will be added to the default ones)
  Vec nExtraOpts (OptionName, XilinxWizardOption) ->
  Clock dom ->
  Enable dom ->
  DSignal dom n a ->
  DSignal dom (n + d) b
unaryInst nm operType extraOptions clk ena a =
  D.unsafeFromSignal $ unpack . resize <$> unPort (snd go)
 where
  go ::
    ( Port "m_axis_result_tvalid" dom Bit
    , Port "m_axis_result_tdata" dom (BitVector (AxiWidth (BitSize b)))
    )
  go =
    instWithXilinxWizard
      (instConfig nm)
      (floatingWizard (SNat @d) operType extraOptions)
      (ClockPort @"aclk" clk)
      (Port @"aclken" (boolToBit <$> fromEnable ena))
      (Port @"s_axis_a_tdata" (axiData <$> D.toSignal a))
      (Port @"s_axis_a_tvalid" (pure 1 :: Signal dom Bit))
{-# INLINE unaryInst #-}

