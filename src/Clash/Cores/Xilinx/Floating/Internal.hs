-- | Customize Xilinx floating point IP.
--
-- These customizations influence how the IP will be synthesized. They do not
-- affect behavior.
data Config = Config
  { archOpt :: !ArchOpt
    -- ^ Architecture optimizations
  , dspUsage :: !DspUsage
    -- ^ DSP slice usage
  , bMemUsage :: !BMemUsage
    -- ^ Use block memory for exponential function
  } deriving (Eq, Show)

-- | Architecture optimizations.
--
-- For those operations that support different architecture optimizations.
data ArchOpt
  = SpeedArch
    -- ^ Speed-optimized architecture
  | LatencyArch
    -- ^ Low latency architecture
  deriving (Eq, Show)

archOptToTcl :: ArchOpt -> String
archOptToTcl = \case
  SpeedArch -> "Speed_Optimized"
  LatencyArch -> "Low_Latency"

-- | DSP slice usage.
--
-- For those operations that can use DSP slices. Not all such operations support
-- all variants.
data DspUsage
  = NoDspUsage
    -- ^ Do not use any DSP slices
  | MediumDspUsage
  | FullDspUsage
  | MaxDspUsage
  deriving (Eq, Show)

dspUsageToTcl :: DspUsage -> String
dspUsageToTcl = \case
  NoDspUsage -> "No_Usage"
  MediumDspUsage -> "Medium_Usage"
  FullDspUsage -> "Full_Usage"
  MaxDspUsage -> "Max_Usage"

-- | Block memory usage.
--
-- Configures whether the exponential operator uses block memory.
data BMemUsage
  = NoBMemUsage
    -- ^ Do not use block memory
  | FullBMemUsage
    -- ^ Use block memory
  deriving (Eq, Show)

bMemUsageToTcl :: BMemUsage -> String
bMemUsageToTcl = \case
  NoBMemUsage -> "No_Usage"
  FullBMemUsage -> "Full_Usage"

-- | NaN as generated by Xilinx.
--
-- Quiet NaN, no payload, positive.
xilinxNaN :: Float
xilinxNaN = unpack 0x7FC00000

-- | Perform the same conditioning on a Float as the Xilinx IP does.
--
-- All NaNs are mapped to 'xilinxNaN', all subnormal numbers to zero.
--
-- Note that there are a few exceptions where the Xilinx IP does not condition
-- Float values. Those functions are documented as such.
--
-- __NB__: Not synthesizable
conditionFloat
  :: Float
  -> Float
conditionFloat = xilinxCondition

-- | Perform the same conditioning on a Float as the Xilinx IP does.
--
-- 'conditionFloat' lifted to 'Functor'.
--
-- __NB__: Not synthesizable
conditionFloatF
  :: Functor f
  => f Float
  -> f Float
conditionFloatF = fmap conditionFloat

-- | Round a result to a Float the way the Xilinx IP does: round to 24
-- significant bits as if the exponent were unbounded, then flush results below
-- the smallest normal number to a zero of the same sign. NaNs become
-- 'xilinxNaN'.
--
-- IEEE rounding instead rounds results below the smallest normal number to the
-- subnormal grid. For results just below the smallest normal number, from
-- @2^-126 - 2^-150@ up to @2^-126 - 2^-151@, it gives the smallest normal
-- number where the IP gives zero.
--
-- __NB__: Not synthesizable
xilinxRound :: Double -> Float
xilinxRound d
  | isNaN d = xilinxNaN
  | abs d >= float2Double minNormalF = double2Float d
  | roundsToMinNormal = if d < 0 then negate minNormalF else minNormalF
  | d < 0 || isNegativeZero d = -0
  | otherwise = 0
 where
  minNormalF = 2 ^^ (-126 :: Int) :: Float
  -- Scale into the normal range of Float, so that 'double2Float' rounds to 24
  -- significant bits. Scaling by a power of two is exact.
  roundsToMinNormal =
    abs (double2Float (scaleFloat 64 d)) >= scaleFloat 64 minNormalF

-- | Floating point formats the Xilinx Floating-Point IP supports: 'Half',
-- 'Float' (single precision) and 'Double'.
class (BitPack a, NFDataX a, RealFloat a) => XilinxFloat a where
  -- | Name of the precision in the IP's settings, e.g. @Single@
  precisionName :: proxy a -> String

  -- | Width of the exponent, in bits
  exponentWidth :: proxy a -> Integer

  -- | Width of the significand including its hidden bit, which the IP calls
  -- the fraction width
  fractionWidth :: proxy a -> Integer

  -- | NaN as generated by the IP: quiet, no payload, positive
  ipNaN :: a

  -- | Model of an operation of the IP with two inputs: addition, subtraction,
  -- multiplication or division. Conditions the inputs like the IP does (see
  -- 'xilinxCondition') and rounds the result like the IP does. The default
  -- computes the exact result, see 'xilinxBinaryExact'.
  --
  -- __NB__: Not synthesizable
  xilinxBinary :: (forall b. Fractional b => b -> b -> b) -> a -> a -> a
  xilinxBinary = xilinxBinaryExact

instance XilinxFloat Half where
  precisionName _ = "Half"
  exponentWidth _ = 5
  fractionWidth _ = 11
  ipNaN = unpack 0x7E00

-- | For single precision, computing the result as a Double and rounding it
-- with 'xilinxRound' gives the same result as computing the exact result,
-- because a Double has more than twice the precision of a Float plus two
-- bits. It is much faster.
instance XilinxFloat Float where
  precisionName _ = "Single"
  exponentWidth _ = 8
  fractionWidth _ = 24
  ipNaN = xilinxNaN
  xilinxBinary f x y = xilinxRound (f (cond x) (cond y))
   where
    cond = float2Double . conditionFloat

instance XilinxFloat Double where
  precisionName _ = "Double"
  exponentWidth _ = 11
  fractionWidth _ = 53
  ipNaN = unpack 0x7FF8000000000000

-- | Condition an input the way the IP does: all NaNs become 'ipNaN', and all
-- subnormal numbers become a zero of the same sign.
--
-- __NB__: Not synthesizable
xilinxCondition :: XilinxFloat a => a -> a
xilinxCondition x
  | isNaN x          = ipNaN
  | isDenormalized x = if x > 0 then 0 else -0
  | otherwise        = x

-- | Model of an operation of the IP with two inputs, computing the exact
-- result as a 'Rational' and rounding it with 'xilinxRoundExact'. Results that
-- are NaN, infinite or exactly zero follow from computing in the target type
-- itself, which handles their signs as IEEE prescribes.
--
-- So do results whose magnitude is above the smallest normal number, which
-- saves computing the exact result for most inputs. Rounding is monotonic, so
-- the exact result is above the smallest normal number too, and there the IP
-- rounds like IEEE. 'Half' computes in 'Float' and rounds that to 'Half', and
-- so does 'fromRational' for 'Half', so the same holds for 'Half'. A result
-- equal to the smallest normal number does not qualify: IEEE rounds some exact
-- results just below it up to it, where the IP gives zero (see 'xilinxRound').
--
-- __NB__: Not synthesizable
xilinxBinaryExact ::
  XilinxFloat a => (forall b. Fractional b => b -> b -> b) -> a -> a -> a
xilinxBinaryExact f (xilinxCondition -> x) (xilinxCondition -> y)
  | isNaN native = ipNaN
  | isInfinite native || isInfinite x || isInfinite y = native
  | abs native > minNormal = native
  | exact == 0 = native
  | otherwise = xilinxRoundExact exact
 where
  native = f x y
  exact = f (toRational x) (toRational y)
  minNormal = encodeFloat 1 (fst (floatRange x) - 1)

-- | Round a non-zero exact result the way the IP does: round to the precision
-- of the target type as if the exponent were unbounded, then flush results
-- below the smallest normal number to a zero of the same sign. See
-- 'xilinxRound' for why this differs from IEEE rounding.
--
-- __NB__: Not synthesizable
xilinxRoundExact :: forall a. RealFloat a => Rational -> a
xilinxRoundExact r
  | abs r >= minNormal = fromRational r
  -- Scale such that the smallest normal number becomes one. Rounding the
  -- scaled value then rounds to the full precision, and rounds up to one if
  -- and only if the unscaled value rounds up to the smallest normal number.
  | abs (fromRational (r * 2 ^^ (1 - emin)) :: a) >= 1 =
      if r < 0 then negate (fromRational minNormal) else fromRational minNormal
  | r < 0 = -0
  | otherwise = 0
 where
  emin = fst (floatRange (undefined :: a))
  minNormal = 2 ^^ (emin - 1) :: Rational

-- | One-hot encoded version of t'Prelude.Ordering'. The order of fields is
-- chosen to match the ordering picked by Xilinx's Floating Point comparison IP.
data Ordering
  = EQ
  | LT
  | GT
  | NaN
  deriving (Generic, NFDataX, Eq, ShowX, Show, Lift)
deriveAnnotation (simpleDerivator OneHot Wide) [t| Ordering |]
deriveBitPack [t| Ordering |]

-- | Converts t'Ordering' to Prelude's t'Prelude.Ordering'. If the given
-- ordering is 'NaN', 'Nothing' is returned.
toMaybeOrdering :: Ordering -> Maybe P.Ordering
toMaybeOrdering = \case
  EQ -> Just P.EQ
  LT -> Just P.LT
  GT -> Just P.GT
  NaN -> Nothing

-- | Perform comparison on two floating point numbers. The type returned is a
-- locally defined version of t'Ordering'. If you want prelude's
-- t'Prelude.Ordering', see 'toMaybeOrdering'.
xilinxCompare :: XilinxFloat a => a -> a -> Ordering
xilinxCompare x y
  | isNaN x = NaN
  | isNaN y = NaN
  | otherwise =
      case compare (xilinxCondition x) (xilinxCondition y) of
        P.LT -> LT
        P.EQ -> EQ
        P.GT -> GT

-- | Width of an AXI4-Stream @TDATA@ field carrying @n@ bits: @n@ rounded up to
-- a whole number of bytes. Inputs are padded with zeros; the padding bits of
-- outputs are dropped.
type AxiWidth n = 8 * DivRU n 8

-- | Wizard settings for the Floating-Point IP: the settings every instance in
-- this module shares, followed by the given extra options.
floatingWizard ::
  forall d nExtraOpts .
  -- | Latency
  SNat d ->
  -- | @CONFIG.Operation_Type@. E.g., @Divide@.
  String ->
  -- | Extra Wizard options (will be added to the default ones)
  Vec nExtraOpts (OptionName, XilinxWizardOption) ->
  XilinxWizard (6 + nExtraOpts)
floatingWizard SNat operType extraOptions =
  XilinxWizard
    { wiz_name = "floating_point"
    , wiz_vendor = "xilinx.com"
    , wiz_library = "ip"
    , wiz_version = "7.1"
    , wiz_options =
         ("CONFIG.Operation_Type",     StrOpt operType)
      :> ("CONFIG.Flow_Control",       StrOpt "NonBlocking")
      :> ("CONFIG.Has_ACLKEN",         BoolOpt True)
      :> ("CONFIG.Has_RESULT_TREADY",  BoolOpt False)
      :> ("CONFIG.Maximum_Latency",    BoolOpt False)
      :> ("CONFIG.C_Latency",          IntegerOpt (natToNum @d))
      :> extraOptions
    }
{-# INLINE floatingWizard #-}

-- | Instantiate the Floating-Point IP for an operation with one input
unaryInst ::
  forall d nExtraOpts n dom a b .
  ( KnownNat nExtraOpts
  , KnownDomain dom
  , KnownNat d
  , BitPack a
  , BitPack b
  ) =>
  -- | Instantiation type hint
  String ->
  -- | @CONFIG.Operation_Type@. E.g., @Fixed_to_float@.
  String ->
  -- | Extra Wizard options (will be added to the default ones)
  Vec nExtraOpts (OptionName, XilinxWizardOption) ->
  Clock dom ->
  Enable dom ->
  DSignal dom n a ->
  DSignal dom (n + d) b
unaryInst nm operType extraOptions clk ena a =
  D.unsafeFromSignal $ unpack . resize <$> unPort (snd go)
 where
  go ::
    ( Port "m_axis_result_tvalid" dom Bit
    , Port "m_axis_result_tdata" dom (BitVector (AxiWidth (BitSize b)))
    )
  go =
    instWithXilinxWizard
      (instConfig nm)
      (floatingWizard (SNat @d) operType extraOptions)
      (ClockPort @"aclk" clk)
      (Port @"aclken" (boolToBit <$> fromEnable ena))
      (Port @"s_axis_a_tdata" (axiData <$> D.toSignal a))
      (Port @"s_axis_a_tvalid" (pure 1 :: Signal dom Bit))
{-# INLINE unaryInst #-}

-- | Instantiate the Floating-Point IP for an operation with two inputs
binaryInst ::
  forall d nExtraOpts n dom a b c .
  ( KnownNat nExtraOpts
  , KnownDomain dom
  , KnownNat d
  , BitPack a
  , BitPack b
  , BitPack c
  ) =>
  -- | Instantiation type hint
  String ->
  -- | @CONFIG.Operation_Type@. E.g., @Divide@.
  String ->
  -- | Extra Wizard options (will be added to the default ones)
  Vec nExtraOpts (OptionName, XilinxWizardOption) ->
  Clock dom ->
  Enable dom ->
  DSignal dom n a ->
  DSignal dom n b ->
  DSignal dom (n + d) c
binaryInst nm operType extraOptions clk ena a b =
  D.unsafeFromSignal $ unpack . resize <$> unPort (snd go)
 where
  go ::
    ( Port "m_axis_result_tvalid" dom Bit
    , Port "m_axis_result_tdata" dom (BitVector (AxiWidth (BitSize c)))
    )
  go =
    instWithXilinxWizard
      (instConfig nm)
      (floatingWizard (SNat @d) operType extraOptions)
      (ClockPort @"aclk" clk)
      (Port @"aclken" (boolToBit <$> fromEnable ena))
      (Port @"s_axis_a_tdata" (axiData <$> D.toSignal a))
      (Port @"s_axis_a_tvalid" (pure 1 :: Signal dom Bit))
      (Port @"s_axis_b_tdata" (axiData <$> D.toSignal b))
      (Port @"s_axis_b_tvalid" (pure 1 :: Signal dom Bit))
{-# INLINE binaryInst #-}

-- | Pad a value to a whole number of bytes, for use as AXI4-Stream @TDATA@
axiData :: BitPack a => a -> BitVector (AxiWidth (BitSize a))
axiData = resize . pack
{-# INLINE axiData #-}
