  :: forall b d dom n
   . ( XilinxFloat b
     , KnownDomain dom
     , KnownNat d
     , HasCallStack
     )
  => Clock dom
  -> Enable dom
  -> DSignal dom n Double
  -> DSignal dom (n + d) b
