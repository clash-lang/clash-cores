       ("CONFIG.C_Mult_Usage", StrOpt (dspUsageToTcl FullDspUsage))
    :> precisionOpts "Double"
  synth = unaryInst "rsqrt" "Rec_Square_Root" extraOpts clk en x
{-# INLINE rsqrtWith #-}

