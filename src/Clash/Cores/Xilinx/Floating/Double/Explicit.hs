  -> Enable dom
  -> DSignal dom n Bool
  -- ^ Whether the input is the last one of an accumulation
  -> DSignal dom n Double
  -> DSignal dom (n + AccumDefDelay) Double
accum = withFrozenCallStack $ accumWith defAccumConfig
