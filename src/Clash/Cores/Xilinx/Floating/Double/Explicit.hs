-- The t'Config' makes no difference: in double precision, the IP always uses
-- @FullDspUsage@ for the reciprocal square root.
rsqrtWith
  :: forall d dom n
   . ( KnownDomain dom
     , KnownNat d
     , HasCallStack
     )
  => Config
  -> Clock dom
  -> Enable dom
  -> DSignal dom n Double
