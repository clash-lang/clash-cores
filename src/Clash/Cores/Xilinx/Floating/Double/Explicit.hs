Support for the [Xilinx Floating-Point LogiCORE IP v7.1](https://docs.amd.com/v/u/en-US/pg060-floating-point)
in double precision ('Double'), with explicit clock and enable arguments.

"Clash.Cores.Xilinx.Floating.Double" has the same functions with a hidden clock
