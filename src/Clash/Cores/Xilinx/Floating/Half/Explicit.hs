   . ( KnownDomain dom
     , KnownNat d
     , HasCallStack
     )
  => Config
  -> Clock dom
  -> Enable dom
  -> DSignal dom n Half
  -> DSignal dom (n + d) Half
expWith = withFrozenCallStack G.expWith
{-# INLINE expWith #-}

