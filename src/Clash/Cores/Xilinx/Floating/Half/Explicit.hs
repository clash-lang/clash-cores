Support for the [Xilinx Floating-Point LogiCORE IP v7.1](https://docs.amd.com/v/u/en-US/pg060-floating-point)
in half precision ('Half'), with explicit clock and enable arguments.

"Clash.Cores.Xilinx.Floating.Half" has the same functions with a hidden clock
and enable. See there for how the functions instantiate the IP, how they behave
and the maximum latency of each operation.

The IP does not support conversions between integers and half precision, so
this module has no @fromU32@ and @fromS32@.

Related modules:

* "Clash.Cores.Xilinx.Floating.Explicit" and
  "Clash.Cores.Xilinx.Floating.Double.Explicit" are the same for single and
  double precision.

* "Clash.Cores.Xilinx.Floating.Generic.Explicit" has the same functions,
  generic in the precision.
-}

module Clash.Cores.Xilinx.Floating.Half.Explicit
  ( -- * Instantiating IP
    addWith
  , add
  , AddDefDelay
  , subWith
  , sub
  , SubDefDelay
  , mulWith
  , mul
  , MulDefDelay
  , divWith
  , div
  , DivDefDelay
  , Ordering(..)
  , toMaybeOrdering
  , compare
  , compareWith
  , CompareDefDelay
    -- * Customizing IP
  , Config(..)
  , defConfig
  , ArchOpt(..)
  , DspUsage(..)
  , BMemUsage(..)
    -- * Additional functions
  , xilinxNaN
  ) where

import Clash.Explicit.Prelude hiding (Ordering(..), add, sub, mul, div, compare)

import GHC.Stack (HasCallStack, withFrozenCallStack)
import Numeric.Half (Half)

import Clash.Cores.Xilinx.Floating.Generic.Explicit (defConfig)
import qualified Clash.Cores.Xilinx.Floating.Generic.Explicit as G
import Clash.Cores.Xilinx.Floating.Internal
  ( ArchOpt(..), BMemUsage(..), Config(..), DspUsage(..), Ordering(..)
  , toMaybeOrdering )

-- | NaN as generated by the IP: quiet, no payload, positive.
xilinxNaN :: Half
xilinxNaN = G.xilinxNaN

-- | Customizable floating point addition.
addWith
  :: forall d dom n
   . ( KnownDomain dom
     , KnownNat d
     , HasCallStack
     )
  => Config
  -> Clock dom
  -> Enable dom
  -> DSignal dom n Half
  -> DSignal dom n Half
  -> DSignal dom (n + d) Half
addWith = withFrozenCallStack G.addWith
{-# INLINE addWith #-}

-- | Floating point addition with default settings.
add
  :: forall dom n
   . ( KnownDomain dom
     , HasCallStack
     )
  => Clock dom
  -> Enable dom
  -> DSignal dom n Half
  -> DSignal dom n Half
  -> DSignal dom (n + AddDefDelay) Half
add = withFrozenCallStack G.add
{-# INLINE add #-}

-- | The default delay for floating point addition with default customization.
type AddDefDelay = G.AddDefDelay Half

