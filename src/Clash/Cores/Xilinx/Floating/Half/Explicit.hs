toFloat
  :: forall dom n
   . ( KnownDomain dom
     , HasCallStack
     )
  => Clock dom
  -> Enable dom
  -> DSignal dom n Half
  -> DSignal dom (n + ToFloatDefDelay) Float
toFloat = withFrozenCallStack toFloatWith
{-# INLINE toFloat #-}

-- | The default delay for conversion of @Half@ to @Float@
