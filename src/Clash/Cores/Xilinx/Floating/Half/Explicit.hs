-- | Customizable floating point comparison
--
-- Produces 'Clash.Cores.Xilinx.Floating.Half.Explicit.NaN' if any of the
-- inputs is NaN. Otherwise, it behaves like Haskell's 'Prelude.compare'.
--
-- Only the delay is configurable, so this function does not take a @Config@
-- argument.
compareWith
  :: forall d dom n
   . ( KnownDomain dom
     , KnownNat d
     , HasCallStack
     )
  => Clock dom
  -> Enable dom
  -> DSignal dom n Half
  -> DSignal dom n Half
  -> DSignal dom (n + d) Ordering
compareWith = withFrozenCallStack G.compareWith
{-# INLINE compareWith #-}

-- | Floating point comparison, with default delay
