Support for the [Xilinx Floating-Point LogiCORE IP v7.1](https://docs.amd.com/v/u/en-US/pg060-floating-point)
in half precision ('Half'), with explicit clock and enable arguments.

"Clash.Cores.Xilinx.Floating.Half" has the same functions with a hidden clock
and enable. See there for how the functions instantiate the IP, how they behave
and the maximum latency of each operation.

The IP does not support conversions between integers and half precision, so
this module has no @fromU32@, @fromS32@, @fromU64@, @fromS64@ and @toS32@.

Related modules:

* "Clash.Cores.Xilinx.Floating.Explicit" and
  "Clash.Cores.Xilinx.Floating.Double.Explicit" are the same for single and
  double precision.
