-- | Customizable conversion of a floating point number in precision @a@ to
-- precision @b@. The precisions can be the same.
--
-- Conversions to a narrower precision round like the arithmetic operations: to
-- nearest, ties to even, with results below the smallest normal number of
-- precision @b@ flushed to a zero of the same sign. Numbers beyond the largest
-- finite number of precision @b@ become an infinity of the same sign.
-- Conversions to the same or a wider precision are exact. Like the other
-- operations, the IP treats subnormal inputs as a zero of the same sign and
-- turns every NaN into 'xilinxNaN', also when both precisions are the same.
--
-- Only the delay is configurable, so this function does not take a @Config@
-- argument.
convertWith
  :: forall a b d dom n
   . ( XilinxFloat a
     , XilinxFloat b
     , KnownDomain dom
     , KnownNat d
     , HasCallStack
     )
  => Clock dom
  -> Enable dom
  -> DSignal dom n a
  -> DSignal dom (n + d) b
convertWith clk en inp
  | clashSimulation = sim
  | otherwise = synth
 where
  sim = delayI und en clk $ fmap xilinxConvert inp
  und = withFrozenCallStack $ deepErrorX "Initial values of convert undefined"
  extraOpts =
       ("CONFIG.A_Precision_Type",      StrOpt (precisionName (Proxy @a)))
    :> ("CONFIG.Result_Precision_Type", StrOpt (precisionName (Proxy @b)))
