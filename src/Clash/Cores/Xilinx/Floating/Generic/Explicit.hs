-- | Floating point absolute value.
--
-- The IP only clears the sign bit. Unlike the other operations, it leaves
-- subnormal numbers and the payloads of NaNs alone.
--
-- The IP only supports a latency of zero, so the result has the same delay as
-- the input. With that latency the IP is combinational: it has no clock and no
-- clock enable, so this function does not take them either.
abs
  :: forall a dom n
   . ( XilinxFloat a
     , KnownDomain dom
     )
  => DSignal dom n a
  -> DSignal dom n a
abs x
  | clashSimulation = xilinxAbs <$> x
  | otherwise =
      unaryCombinationalInst "abs" "Absolute" (precisionOpts (Proxy @a)) x
{-# INLINE abs #-}

