     , KnownDomain dom
     , HasCallStack
     )
  => Clock dom
  -> Enable dom
  -> DSignal dom n a
  -> DSignal dom n a
  -> DSignal dom (n + AddDefDelay a) a
add = withFrozenCallStack $ addWith defConfig
{-# INLINE add #-}

