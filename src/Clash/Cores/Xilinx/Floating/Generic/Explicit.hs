-- | Customizable floating point comparison
--
-- Produces 'NaN' if any of the inputs is NaN. Otherwise, it behaves like
-- Haskell's 'Prelude.compare'.
--
-- Only the delay is configurable, so this function does not take a @Config@
-- argument.
compareWith
  :: forall a d dom n
   . ( XilinxFloat a
     , KnownDomain dom
     , KnownNat d
     , HasCallStack
     )
  => Clock dom
  -> Enable dom
  -> DSignal dom n a
  -> DSignal dom n a
  -> DSignal dom (n + d) Ordering
compareWith clk ena a b
  | clashSimulation = sim
  | otherwise = synth
 where
  sim = delayI und ena clk (xilinxCompare <$> a <*> b)
  und = withFrozenCallStack $ errorX "Initial values of compare undefined"
  extraOpts =
       ("CONFIG.C_Compare_Operation",     StrOpt "Condition_Code")
    :> ("CONFIG.A_Precision_Type",        StrOpt (precisionName (Proxy @a)))
    :> ("CONFIG.C_A_Exponent_Width",      IntegerOpt (exponentWidth (Proxy @a)))
    :> ("CONFIG.C_A_Fraction_Width",      IntegerOpt (fractionWidth (Proxy @a)))
    :> ("CONFIG.Result_Precision_Type",   StrOpt "Custom")
    :> ("CONFIG.C_Result_Exponent_Width", IntegerOpt 4)
    :> ("CONFIG.C_Result_Fraction_Width", IntegerOpt 0)
    :> ("CONFIG.C_Mult_Usage",            StrOpt "No_Usage")
    :> ("CONFIG.C_Rate",                  IntegerOpt 1)
    :> Nil
  synth = binaryInst "compare" "Compare" extraOpts clk ena a b
{-# INLINE compareWith #-}

-- | Floating point comparison, with default delay
--
-- Produces 'NaN' if any of the inputs is NaN. Otherwise, it behaves like
-- Haskell's 'Prelude.compare'.
compare
  :: forall a dom n
   . ( XilinxFloat a
     , KnownNat (CompareDefDelay a)
     , KnownDomain dom
     , HasCallStack
     )
  => Clock dom
  -> Enable dom
  -> DSignal dom n a
  -> DSignal dom n a
  -> DSignal dom (n + CompareDefDelay a) Ordering
compare = compareWith
{-# INLINE compare #-}

-- | The default delay for floating point comparison
type family CompareDefDelay a :: Nat where
  CompareDefDelay Half = 2
  CompareDefDelay Float = 2
  CompareDefDelay Double = 2

-- | Default customization options.
--
-- For those operations that support it, the default options are:
--
-- * Speed-optimized architecture ('SpeedArch')
-- * Full DSP slice usage ('FullDspUsage')
-- * Exponential operator does not use block memory ('NoBMemUsage')
defConfig :: Config
defConfig = Config
  { archOpt = SpeedArch
  , dspUsage = FullDspUsage
  , bMemUsage = NoBMemUsage
  }
