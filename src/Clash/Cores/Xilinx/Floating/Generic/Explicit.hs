-- | Precisions the IP can convert 32-bit integers to. The IP does not support
-- these conversions for 'Half'.
class XilinxFloat a => FromInt32 a
instance FromInt32 Float
instance FromInt32 Double

-- | NaN as generated by the IP: quiet, no payload, positive.
xilinxNaN :: XilinxFloat a => a
xilinxNaN = ipNaN

-- | Wizard settings selecting the precision of both inputs and the result
precisionOpts ::
  XilinxFloat a => Proxy a -> Vec 2 (OptionName, XilinxWizardOption)
precisionOpts p =
     ("CONFIG.A_Precision_Type",      StrOpt (precisionName p))
  :> ("CONFIG.Result_Precision_Type", StrOpt (precisionName p))
  :> Nil
{-# INLINE precisionOpts #-}

-- | Customizable floating point addition.
addWith
  :: forall a d dom n
   . ( XilinxFloat a
     , KnownDomain dom
     , KnownNat d
     , HasCallStack
     )
  => Config
  -> Clock dom
  -> Enable dom
  -> DSignal dom n a
  -> DSignal dom n a
  -> DSignal dom (n + d) a
addWith Config{archOpt, dspUsage} clk en x y
  | clashSimulation = sim
  | otherwise = synth
 where
  sim = delayI und en clk (xilinxBinary (+) <$> x <*> y)
  und = withFrozenCallStack $ deepErrorX "Initial values of add undefined"
  extraOpts =
       ("CONFIG.Add_Sub_Value",  StrOpt "Add")
    :> ("CONFIG.C_Optimization", StrOpt (archOptToTcl archOpt))
    :> ("CONFIG.C_Mult_Usage",   StrOpt (dspUsageToTcl dspUsage))
    :> precisionOpts (Proxy @a)
  synth = binaryInst "add" "Add_Subtract" extraOpts clk en x y
{-# INLINE addWith #-}

-- | Floating point addition with default settings.
add
  :: forall a dom n
   . ( XilinxFloat a
     , KnownNat (AddDefDelay a)
     , KnownDomain dom
     , HasCallStack
     )
  => Clock dom
  -> Enable dom
  -> DSignal dom n a
  -> DSignal dom n a
  -> DSignal dom (n + AddDefDelay a) a
add = withFrozenCallStack $ addWith defConfig
{-# INLINE add #-}

-- | The default delay for floating point addition with default customization.
type family AddDefDelay a :: Nat where
  AddDefDelay Half = 11
  AddDefDelay Float = 11
  AddDefDelay Double = 14

