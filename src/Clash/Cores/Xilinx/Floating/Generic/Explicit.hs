  :: forall a d dom n
   . ( ToInt32 a
     , KnownDomain dom
     , KnownNat d
     , HasCallStack
     )
  => Clock dom
  -> Enable dom
  -> DSignal dom n a
  -> DSignal dom (n + d) (Signed 32)
