-- | Wizard settings selecting the precision of both inputs and the result
precisionOpts ::
  XilinxFloat a => Proxy a -> Vec 2 (OptionName, XilinxWizardOption)
precisionOpts p =
     ("CONFIG.A_Precision_Type",      StrOpt (precisionName p))
  :> ("CONFIG.Result_Precision_Type", StrOpt (precisionName p))
  :> Nil
{-# INLINE precisionOpts #-}

-- | Conversion of an integer to a floating point number, rounding to nearest,
-- ties to even. This implements 'fromU32With', 'fromS32With', 'fromU64With'
-- and 'fromS64With'.
fixedToFloatWith
  :: forall i a d dom n
   . ( Integral i
     , BitPack i
     , XilinxFloat a
     , KnownDomain dom
     , KnownNat d
     , HasCallStack
     )
  => String
  -- ^ Instantiation type hint, e.g. @fromU32@
  -> String
  -- ^ @CONFIG.A_Precision_Type@ of the integer, e.g. @Uint32@
  -> Clock dom
  -> Enable dom
  -> DSignal dom n i
  -> DSignal dom (n + d) a
fixedToFloatWith nm precType clk en inp
  | clashSimulation = sim
  | otherwise = synth
 where
  sim = delayI und en clk $ fmap (xilinxFromInteger . toInteger) inp
  und =
    withFrozenCallStack $ errorX ("Initial values of " <> nm <> " undefined")
  extraOpts =
       ("CONFIG.A_Precision_Type",      StrOpt precType)
    :> ("CONFIG.C_A_Exponent_Width",    IntegerOpt (natToNum @(BitSize i)))
    :> ("CONFIG.C_A_Fraction_Width",    IntegerOpt 0)
    :> ("CONFIG.C_Rate",                IntegerOpt 1)
    :> ("CONFIG.Result_Precision_Type", StrOpt (precisionName (Proxy @a)))
    :> Nil
  synth = unaryInst nm "Fixed_to_float" extraOpts clk en inp
{-# INLINE fixedToFloatWith #-}

-- | Customizable floating point addition.
addWith
  :: forall a d dom n
   . ( XilinxFloat a
     , KnownDomain dom
     , KnownNat d
     , HasCallStack
     )
  => Config
  -> Clock dom
  -> Enable dom
  -> DSignal dom n a
  -> DSignal dom n a
  -> DSignal dom (n + d) a
addWith Config{archOpt, dspUsage} clk en x y
  | clashSimulation = sim
  | otherwise = synth
 where
  sim = delayI und en clk (xilinxBinary (+) <$> x <*> y)
  und = withFrozenCallStack $ deepErrorX "Initial values of add undefined"
  extraOpts =
       ("CONFIG.Add_Sub_Value",  StrOpt "Add")
    :> ("CONFIG.C_Optimization", StrOpt (archOptToTcl archOpt))
    :> ("CONFIG.C_Mult_Usage",   StrOpt (dspUsageToTcl dspUsage))
    :> precisionOpts (Proxy @a)
  synth = binaryInst "add" "Add_Subtract" extraOpts clk en x y
{-# INLINE addWith #-}

