-- | The ALTERA_CORDIC IP, with the latency performance goal and an enable
-- port
cordicIp ::
  -- | Function, e.g. @SINCOS@
  String ->
  -- | Latency
  Integer ->
  -- | Extra parameters
  Vec n (String, IpParam) ->
  IntelIp (n + 5)
cordicIp function latency extra = IntelIp
  { ipKind = "altera_CORDIC"
  , ipParams =
       ("FUNCTION_FAMILY", StrParam "ALL")
    :> ("ALL_function", StrParam function)
    :> ("performance_goal", StrParam "latency")
    :> ("latency_target", IntegerParam latency)
    :> ("gen_enable", BoolParam True)
    :> extra
  }
{-# INLINE cordicIp #-}

-- | The ALTERA_CORDIC IP computing sine and cosine
cordicIpSinCos ::
  -- | Signed input?
  Bool ->
  -- | Fractional bits of the input
  Integer ->
  -- | Fractional bits of the outputs
  Integer ->
  -- | Latency
  Integer ->
  IntelIp 8
cordicIpSinCos signed fIn fOut latency =
  cordicIp "SINCOS" latency
    (  ("fxpt_in_fraction", IntegerParam fIn)
    :> ("fxpt_in_sign", StrParam (if signed then "1" else "0"))
    :> ("fxpt_out_fraction", IntegerParam fOut)
    :> Nil )
{-# INLINE cordicIpSinCos #-}

-- | Simulation model of the pipeline of the IP: @d@ registers that are
-- enabled by the 'Enable' signal. The registers have undefined initial values,
-- and are undefined after a reset: the IP clears its registers, but the
-- corresponding outputs don't have specified values.
pipeline ::
  forall d n dom a.
  (KnownDomain dom, KnownNat d, NFDataX a) =>
  -- | Undefined value
  a ->
  Clock dom ->
  Reset dom ->
  Enable dom ->
  DSignal dom n a ->
  DSignal dom (n + d) a
pipeline und clk rst en =
  D.unsafeFromSignal . C.last . C.iterate (SNat @(d + 1)) (register clk rst en und) . D.toSignal
{-# INLINE pipeline #-}

-- | 'BitVector' of an 'Enable', for the @en@ port of the IP
enPort :: Enable dom -> Signal dom (BitVector 1)
enPort en = pack . boolToBit <$> fromEnable en
