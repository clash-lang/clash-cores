{- Note [Inferring the datapath of ALTERA_CORDIC]
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
The ALTERA_CORDIC user guide (UG-20017) describes the functions of the IP and
their input and output formats, and promises results that are "faithfully
rounded": within one unit in the last place. It does not describe the
datapath. The models in this module reproduce the IP generated by Quartus
Prime Lite 21.1 bit for bit. They implement the textbook CORDIC algorithm
(Volder 1959, Walther 1971), with the structure (widths, truncations, rounding
points) inferred by observing the generated IP as a black box:

* Simulating the IP on chosen inputs (exhaustively for small widths, and
  millions of random inputs for wide ones), with the IP's own simulation model.

* The ordinary Quartus synthesis report, which lists the IP's pipeline
  registers with their widths. This gave the width of the X and Y datapath,
  the number of iterations, and the names of a few blocks (an absolute value,
  the comparison of the angle with pi\/2, a rounding adder and a negation
  after rounding).

* For sine and cosine, X and Y only depend on the sequence of rotation
  directions, which only depends on the angle datapath. So, the boundaries
  between runs of consecutive inputs with equal outputs are the angles at
  which a rotation direction changes. Their greatest common divisor shows how
  many bits of the input the IP uses, and their positions pin down the
  precision of the angle datapath and its constants. Once the angle datapath
  was known, the remaining parameters (the precision of X and Y and of the
  inverse CORDIC gain) followed from the rare inputs whose results are close
  to a rounding boundary.

The parameters did not depend on the target frequency, the latency or the
device family (checked for MAX 10 and Cyclone V), only on the formats.

Sine and cosine, with @wOut@ the width of the output (@fOut + 2@ for a signed
input, @fOut + 1@ for an unsigned input):

1. The magnitude of the input angle is truncated to @fT@ fractional bits:
   @fOut + 3 + (fOut + 1) \`div\` 4@ for a signed input and @fZ@ (below) for an
   unsigned one. An input with fewer fractional bits is used as is.

2. For a signed input, if the magnitude is at least pi\/2, rounded to the
   nearest multiple of @2^-fT@, the IP subtracts that constant, computes the
   sine and cosine of the result, and swaps and negates them: cos(a) =
   -sin(a - pi\/2) and sin(a) = cos(a - pi\/2).

3. A CORDIC in rotation mode with @fOut + 2@ iterations, with shifts
   @0, 1 .. fOut + 1@. The angle has @fZ = wOut + 4 + ceil(log2(wOut + 1))@
   fractional bits, and its constants, arctan(2^-i), are rounded to the
   nearest multiple of @2^-fZ@. X and Y have @fIn + fOut + 4@ (signed) or
   @fIn + fOut + 2@ (unsigned) fractional bits. X starts at the inverse of the
   limit of the CORDIC gain, 1\/1.6467602..., rounded to nearest; Y at zero.
   The shifted operands are truncated (rounded towards negative infinity).

4. X and Y are rounded to @fOut@ fractional bits, ties towards positive
   infinity (adding half a unit and truncating).

5. Finally, the sine is negated if the input is negative. The negation comes
   after rounding, so the results are exactly odd and even.

Inputs outside the range in the user guide ([-pi, pi] for a signed input, [0,
pi\/2] for an unsigned one) make the internal angle overflow its
representation, which these models do not reproduce: they return an undefined
value for such inputs.

The models were validated against the IP for all inputs of 20 signed and 11
unsigned configurations with up to 23 input bits (input fractions 4 to 20,
output fractions 3 to 16), and for 5,000 to 340,000 random inputs (including
the ones around pi\/2) of 27 configurations with input fractions from 1 to 63
and output fractions from 1 to 34, signed and unsigned. With more than 34
fractional output bits, a few results (signed 36 and 38, unsigned 38) and
eventually most results (61 and 63) differ: the IP's datapath for those
widths is different, and was not pursued. The API rejects those widths.

The arctangent (ATAN2) and the vector translation (VECTRANSLATE) were
inferred the same way, with exhaustive simulations of small configurations
(up to 2^20 input pairs), random and near-boundary inputs for wide ones, and
some 800 Quartus synthesis runs whose reports give the number of iterations
and the widths of the X and Y registers for each format. Let @n0@ be the
width of the angle output (@fOut + 3@ for signed and @fOut + 2@ for unsigned
inputs) and @wm@ the magnitude bits of the inputs (@w - 1@ and @w@):

1. The IP takes @|x|@ and @|y|@ and runs a CORDIC in vectoring mode on them:
   rotate clockwise if Y >= 0, anticlockwise otherwise, with shifts @0, 1 ..
   n - 1@. Normally @n = n0@.

2. X and Y start as the inputs, as integers in units of the last bit of the
   inputs. The IP keeps all bits of the shifted operands until X and Y have
   @g@ fractional bits, after that the shifted operands are truncated (that
   is the same as starting with @g@ fractional bits). Normally @g = max n0
   (lambda n0 - 1 - wm)@, where @lambda@ is a width requirement that only
   depends on @n0@. Its values (16, 18, 19, 21, 24, 27, 28, ... for @n0 = 9,
   10, 11 ...@) are irregular, and no formula for them was found: they were
   read from the register widths of the Y datapath in the synthesis reports
   (the width of every Y register equals its most significant bit, which
   falls by one per iteration, plus @g@), for each @n0@ up to 51, and
   confirmed by the exhaustive simulations. 'lambdaTable' has them. They are
   the same for signed and unsigned inputs, except at @n0 = 19@, and differ
   for VECTRANSLATE, which has its own table.

3. If that would give X and Y more than @n0 + 10@ fractional bits, the
   generator instead adds one or two iterations (for some formats, listed in
   'transitions') or uses @n = fOut + 8@ iterations with @g = n0@. These
   formats are the ones with many more output bits than input bits.

4. From the shift @(wm + g + 5) \`div\` 2@ on, the IP stops updating X:
   the change would be below the last bit of X by the generator's bounds.
   (The synthesis reports show this for every format measured.)

5. ATAN2 accumulates the rotation angle exactly, with the constant of
   iteration @i@, arctan(2^-i), rounded to the nearest multiple of
   @2^-(fZ + 2 i)@, where @fZ = n0 + 4 + ceil(log2(n0 + 1))@: the same
   formula as for sine and cosine, and the angle's registers in the
   synthesis reports grow by two bits per iteration. VECTRANSLATE instead
   looks up the sum of the signed constants of each group of four iterations
   in a table, with entries rounded to the nearest multiple of @2^-(fOut + 2 +
   ceil(n / 4))@, and adds those.

6. For signed inputs, the angle is truncated to @fOut + 2@ fractional bits,
   subtracted from pi, truncated to @fOut + 3@ fractional bits, if @x < 0@,
   negated if @y < 0@, and rounded to @fOut@ fractional bits (ties towards
   positive infinity). For @x = 0@ the angle before the reconstruction is
   pi\/2 rounded to @fOut + 2@ fractional bits, for @y = 0@ it is zero, and
   @atan2 0 0 = 0@. For unsigned inputs the angle is rounded to @fOut@
   fractional bits (ties towards positive infinity), and for @x = 0@ the
   result is pi\/2 rounded to @fOut - 1@ fractional bits, in an @fOut + 1@
   bit field (so it wraps around to 0 for @fOut = 1@).

7. VECTRANSLATE's magnitude is the final X rounded to the format of the
   magnitude (ties towards positive infinity). With scale factor
   compensation, X is truncated to two more fractional bits than the
   magnitude, multiplied by 1\/K rounded to @fOut + 5@ fractional bits, and
   rounded by adding three quarters of a unit and truncating.

The results don't depend on the fractional bits of the inputs, as atan2 is
scale invariant and the IP sizes everything relative to the last bit of the
inputs. The ATAN2 model reproduced all results of 58 exhaustively simulated
formats (input widths 4 to 10, output fractions 1 to 24, signed and
unsigned) and of 37,000 to 40,000 random and near-boundary input pairs for
each of 23 formats with input widths up to 64 and output fractions up to 45.
The VECTRANSLATE model reproduced both outputs of 15 exhaustively simulated
formats (output fractions 3 to 16, 9 of them with scale factor compensation)
and of 4 sampled ones. For VECTRANSLATE with more than 16 fractional output
bits, the compensated magnitude (from about 30 bits) and the angle's tables
(in one of six formats tried) differ from these rules, so the API stops at
16. The API only accepts formats where these rules were measured, see
'atanWidths'. With more than 45 (signed) or 40 (unsigned) fractional output
bits, ATAN2's generator makes other choices that no rule here covers.

The IP's @useLUTs@ option makes ATAN2 compute the angle with tables like
VECTRANSLATE. That matched for the three configurations tried, but the width
requirement of such configurations was not measured, so it isn't offered.

The vector rotation (VECROTATE, signed inputs only: the generator of Quartus
21.1 fails for unsigned ones) was inferred the same way, from exhaustive
simulations of all bit patterns of nine small formats (input fractions 3 to
5, output fractions 0 to 12, including inputs outside the documented ranges)
and 25,000 to 50,000 random inputs of 17 wider formats. With @wOut = fOut +
3@:

1. The angle is truncated to @fT = wOut + ceil(wOut / 4)@ fractional bits.
   If its magnitude is at least pi\/2, rounded to the nearest multiple of
   @2^-fT@, the IP subtracts that constant (or adds it, for a negative
   angle) and rotates the vector by 90 degrees first: @(x, y)@ becomes @(-y,
   x)@ for a positive angle and @(y, -x)@ for a negative one. The negation is
   done in the format of the inputs, so -(-2) = -2.

2. The angle is aligned to @wOut + 4 + ceil(log2(wOut + 1))@ fractional bits
   (as for sine and cosine), in a register with two integer bits that wraps
   around for angles beyond pi.

3. A CORDIC in rotation mode with @fOut + 4@ iterations (shifts @0 .. fOut +
   3@) rotates X and Y, which start as the inputs with @fOut + 4@ more
   fractional bits, without the inverse gain: the results are K times the
   rotated vector. The shifted operands are truncated, the constants
   arctan(2^-i) rounded to nearest, and X and Y have three integer bits and
   wrap around (for vectors longer than one).

4. X and Y are rounded to @fOut@ fractional bits, ties towards positive
   infinity.

The model reproduces all of those results. The results didn't depend on the
target frequency or the device family. With scale factor compensation, the
IP multiplies X and Y by a constant close to 1\/K, with a shift-and-add or a
table based multiplier that round differently. Which one the generator
picks is a cost decision that couldn't be reduced to a rule, so the API
doesn't offer it.
-}

