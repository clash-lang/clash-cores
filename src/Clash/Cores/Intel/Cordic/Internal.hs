-- | @ceil(log2 k)@ for positive @k@
ceilLog2 :: Int -> Int
ceilLog2 k = length (takeWhile (< k) (iterate (* 2) 1))

-- | Integer square root: the largest @r@ with @r * r <= n@
isqrt :: Integer -> Integer
isqrt n
  | n < 0 = error "isqrt: negative argument"
  | n < 2 = n
  | otherwise = go (1 `shiftL` ((bitLength n + 1) `div` 2))
 where
  go r =
    let r' = (r + n `div` r) `div` 2
    in if r' >= r then r else go r'
  bitLength m = length (takeWhile (> 0) (iterate (`shiftR` 1) m))

-- | Rational lower and upper bounds of a real number, with a requested
-- absolute accuracy of about @2^-bits@
type Bounds = Int -> (Rational, Rational)

-- | Bounds on @atan(1/m)@ for an integer @m >= 2@, from its Taylor series
atanRecipBounds :: Integer -> Bounds
atanRecipBounds m bits = (s - r, s + r)
 where
  terms = [ (if even k then 1 else -1) % ((2 * k + 1) * m ^ (2 * k + 1)) | k <- [0 :: Integer ..] ]
  eps = 1 % (2 ^ (bits + 2))
  (used, rest) = span ((>= eps) . abs) terms
  s = sum used
  -- Alternating series with decreasing terms: the remainder is bounded by
  -- the first omitted term.
  r = case rest of
    (t : _) -> abs t
    [] -> 0

-- | Bounds on pi, with Machin's formula: @pi = 16 atan(1/5) - 4 atan(1/239)@
piBounds :: Bounds
piBounds bits = (16 * lo5 - 4 * hi239, 16 * hi5 - 4 * lo239)
 where
  (lo5, hi5) = atanRecipBounds 5 (bits + 5)
  (lo239, hi239) = atanRecipBounds 239 (bits + 3)

-- | Round a real number given by its bounds to the nearest integer,
-- increasing the accuracy until the bounds agree. The numbers rounded here
-- are irrational, so there are no ties.
roundBounds :: Bounds -> Integer
roundBounds = roundBoundsWith (\q -> ratFloor (q + 1 % 2))

-- | Round a real number given by its bounds down
floorBounds :: Bounds -> Integer
floorBounds = roundBoundsWith ratFloor

ratFloor :: Rational -> Integer
ratFloor q = numerator q `div` denominator q

roundBoundsWith :: (Rational -> Integer) -> Bounds -> Integer
roundBoundsWith rnd bnds = go 64
 where
  go bits =
    let (lo, hi) = bnds bits
    in if rnd lo == rnd hi then rnd lo else go (2 * bits)

-- | Scale bounds by @2^k@
scaleBounds :: Int -> Bounds -> Bounds
scaleBounds k bnds bits =
  let (lo, hi) = bnds (bits + max 0 k)
  in (lo * 2 ^^ k, hi * 2 ^^ k)

-- | @round(atan(2^-i) * 2^k)@, rounding to nearest
atanRounded :: Int -> Int -> Integer
atanRounded 0 k = roundBounds (scaleBounds k (\b -> let (lo, hi) = piBounds b in (lo / 4, hi / 4)))
atanRounded i k = roundBounds (scaleBounds k (atanRecipBounds (2 ^ i)))

-- | @round(pi/2 * 2^k)@, rounding to nearest
halfPiRounded :: Int -> Integer
halfPiRounded k = roundBounds (scaleBounds k halfPiBounds)

-- | @floor(pi/2 * 2^k)@
halfPiFloor :: Int -> Integer
halfPiFloor k = floorBounds (scaleBounds k halfPiBounds)

halfPiBounds :: Bounds
halfPiBounds b = let (lo, hi) = piBounds b in (lo / 2, hi / 2)

-- | @floor(pi * 2^k)@
piFloor :: Int -> Integer
piFloor k = floorBounds (scaleBounds k piBounds)

-- | Bounds on @atan(2^-i)@
atanBounds :: Int -> Bounds
atanBounds 0 b = let (lo, hi) = piBounds b in (lo / 4, hi / 4)
atanBounds i b = atanRecipBounds (2 ^ i) b

-- | @round(sum [+-atan(2^-i)] * 2^k)@, rounding to nearest: the sum of the
-- arctangents of the given shifts, with the given signs (@True@ for plus)
atanSumRounded :: [(Int, Bool)] -> Int -> Integer
atanSumRounded terms k = roundBounds (scaleBounds k sumBounds)
 where
  m = length terms
  sumBounds b =
    let bs = [ if plus then (lo, hi) else (negate hi, negate lo)
             | (i, plus) <- terms, let (lo, hi) = atanBounds i (b + m) ]
    in (sum (map fst bs), sum (map snd bs))

-- | The inverse of the limit of the CORDIC gain, @prod_{i>=0} 1 / sqrt(1 +
-- 2^-2i)@ (about 0.6072529), rounded to the nearest multiple of @2^-k@
inverseGainRounded :: Int -> Integer
inverseGainRounded k = go 16
 where
  -- With P_n = prod_{i=0..n} (1 + 4^-i), the full product P lies in
  -- [P_n, P_n * (1 + 4^-n)], as the remaining factors multiply to less than
  -- exp(4^-n / 3).
  go (n :: Int) =
    let pn = product [1 + 1 % (4 ^ i) | i <- [0 .. n]] :: Rational
        lo = roundRecipSqrt (pn * (1 + 1 % (4 ^ n)))
        hi = roundRecipSqrt pn
    in if lo == hi then lo else go (2 * n)
  -- round(2^k / sqrt p) = floor((floor(2^(k+1) / sqrt p) + 1) / 2)
  roundRecipSqrt p =
    let v = isqrt ((4 ^ (k + 1) * denominator p) `div` numerator p)
    in (v + 1) `div` 2

