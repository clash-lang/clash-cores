{- Note [Inferring the datapath of ALTERA_CORDIC]
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
The ALTERA_CORDIC user guide (UG-20017) describes the functions of the IP and
their input and output formats, and promises results that are "faithfully
rounded": within one unit in the last place. It does not describe the
datapath. The models in this module reproduce the IP generated by Quartus
Prime Lite 21.1 bit for bit. They implement the textbook CORDIC algorithm
(Volder 1959, Walther 1971), with the structure (widths, truncations, rounding
points) inferred by observing the generated IP as a black box:

* Simulating the IP on chosen inputs (exhaustively for small widths, and
  millions of random inputs for wide ones), with the IP's own simulation model.

* The ordinary Quartus synthesis report, which lists the IP's pipeline
  registers with their widths. This gave the width of the X and Y datapath,
  the number of iterations, and the names of a few blocks (an absolute value,
  the comparison of the angle with pi\/2, a rounding adder and a negation
  after rounding).

* For sine and cosine, X and Y only depend on the sequence of rotation
  directions, which only depends on the angle datapath. So, the boundaries
  between runs of consecutive inputs with equal outputs are the angles at
  which a rotation direction changes. Their greatest common divisor shows how
  many bits of the input the IP uses, and their positions pin down the
  precision of the angle datapath and its constants. Once the angle datapath
  was known, the remaining parameters (the precision of X and Y and of the
  inverse CORDIC gain) followed from the rare inputs whose results are close
  to a rounding boundary.

The parameters did not depend on the target frequency, the latency or the
device family (checked for MAX 10 and Cyclone V), only on the formats.

Sine and cosine, with @wOut@ the width of the output (@fOut + 2@ for a signed
input, @fOut + 1@ for an unsigned input):

1. The magnitude of the input angle is truncated to @fT@ fractional bits:
   @fOut + 3 + (fOut + 1) \`div\` 4@ for a signed input and @fZ@ (below) for an
   unsigned one. An input with fewer fractional bits is used as is.

2. For a signed input, if the magnitude is at least pi\/2, rounded to the
   nearest multiple of @2^-fT@, the IP subtracts that constant, computes the
   sine and cosine of the result, and swaps and negates them: cos(a) =
   -sin(a - pi\/2) and sin(a) = cos(a - pi\/2).

3. A CORDIC in rotation mode with @fOut + 2@ iterations, with shifts
   @0, 1 .. fOut + 1@. The angle has @fZ = wOut + 4 + ceil(log2(wOut + 1))@
   fractional bits, and its constants, arctan(2^-i), are rounded to the
   nearest multiple of @2^-fZ@. X and Y have @fIn + fOut + 4@ (signed) or
   @fIn + fOut + 2@ (unsigned) fractional bits. X starts at the inverse of the
   limit of the CORDIC gain, 1\/1.6467602..., rounded to nearest; Y at zero.
   The shifted operands are truncated (rounded towards negative infinity).

4. X and Y are rounded to @fOut@ fractional bits, ties towards positive
   infinity (adding half a unit and truncating).

5. Finally, the sine is negated if the input is negative. The negation comes
   after rounding, so the results are exactly odd and even.

Inputs outside the range in the user guide ([-pi, pi] for a signed input, [0,
pi\/2] for an unsigned one) make the internal angle overflow its
representation, which these models do not reproduce: they return an undefined
value for such inputs.

The models were validated against the IP for all inputs of 20 signed and 11
unsigned configurations with up to 23 input bits (input fractions 4 to 20,
output fractions 3 to 16), and for 5,000 to 340,000 random inputs (including
the ones around pi\/2) of 27 configurations with input fractions from 1 to 63
and output fractions from 1 to 34, signed and unsigned. With more than 34
fractional output bits, a few results (signed 36 and 38, unsigned 38) and
eventually most results (61 and 63) differ: the IP's datapath for those
widths is different, and was not pursued. The API rejects those widths.
-}

