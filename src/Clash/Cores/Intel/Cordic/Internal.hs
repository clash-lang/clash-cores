-- | Parameters of the datapath of sine and cosine, see
-- @Note [Inferring the datapath of ALTERA_CORDIC]@
data SinCosWidths = SinCosWidths
  { scSigned :: Bool
  -- ^ Whether the input is signed
  , scFracIn :: Int
  -- ^ Fractional bits of the input
  , scFracOut :: Int
  -- ^ Fractional bits of the outputs
  , scFracTrunc :: Int
  -- ^ Fractional bits of the input that the IP uses
  , scFracZ :: Int
  -- ^ Fractional bits of the angle in the CORDIC iterations
  , scFracXY :: Int
  -- ^ Fractional bits of X and Y
  , scIterations :: Int
  -- ^ Number of iterations, with shifts @0 .. scIterations - 1@
  } deriving (Eq, Show)

-- | Parameters of the datapath of sine and cosine for a signed or unsigned
-- input with @fIn@ fractional bits, and outputs with @fOut@ fractional bits
sinCosWidths :: Bool -> Int -> Int -> SinCosWidths
sinCosWidths signed fIn fOut = SinCosWidths
  { scSigned = signed
  , scFracIn = fIn
  , scFracOut = fOut
  , scFracTrunc = if signed then fOut + 3 + (fOut + 1) `div` 4 else fZ
  , scFracZ = fZ
  , scFracXY = fIn + fOut + (if signed then 4 else 2)
  , scIterations = fOut + 2
  }
 where
  wOut = fOut + (if signed then 2 else 1)
  fZ = wOut + 4 + ceilLog2 (wOut + 1)

-- | Model of sine and cosine. The input is the raw integer value of the
-- fixed point angle (with 'scFracIn' fractional bits), the results are the
-- raw values of @(cos, sin)@ with 'scFracOut' fractional bits. Returns
-- 'Nothing' for inputs outside the range the IP supports: [-pi, pi] for a
-- signed input and [0, pi\/2] for an unsigned one.
sinCosModel :: SinCosWidths -> Integer -> Maybe (Integer, Integer)
sinCosModel SinCosWidths{..} = \a ->
  if abs a > maxIn || a < 0 && not scSigned then Nothing else Just $
  let
    a0 = alignTo scFracIn scFracTrunc (abs a)
    -- Second quadrant: subtract pi/2, and rotate the result by 90 degrees
    secondQuadrant = scSigned && a0 >= halfPi
    z0 = alignTo scFracTrunc scFracZ (if secondQuadrant then a0 - halfPi else a0)
    (x, y) = rotate steps z0 (x0, 0)
    c = rnd x
    s = rnd y
    (c', s') = if secondQuadrant then (negate s, c) else (c, s)
  in (c', if a < 0 then negate s' else s')
 where
  -- The largest input in range: floor(pi * 2^fIn) for a signed input, and
  -- floor(pi/2 * 2^fIn) for an unsigned one
  maxIn = halfPiFloor (if scSigned then scFracIn + 1 else scFracIn)
  halfPi = halfPiRounded scFracTrunc
  steps = [ (i, atanRounded i scFracZ) | i <- [0 .. scIterations - 1] ]
  x0 = inverseGainRounded scFracXY
  rnd v = (v + 1 `shiftL` (scFracXY - scFracOut - 1)) `shiftR` (scFracXY - scFracOut)
  rotate [] _ xy = xy
  rotate ((i, at) : rest) z (x, y)
    | z >= 0 = rotate rest (z - at) (x - (y `shiftR` i), y + (x `shiftR` i))
    | otherwise = rotate rest (z + at) (x + (y `shiftR` i), y - (x `shiftR` i))

-- | How close an input of 'sinCosModel' is to changing the result when a
-- detail of the datapath changes: the smallest magnitude of the angle at a
-- rotation (in units of its last place), and the smallest distance of X or Y
-- to a rounding boundary of the outputs (in units of the last place of X and
-- Y). Used to find test inputs that tell such details apart.
sinCosMargins :: SinCosWidths -> Integer -> (Integer, Integer)
sinCosMargins SinCosWidths{..} = \a ->
  let
    a0 = alignTo scFracIn scFracTrunc (abs a)
    z0 = alignTo scFracTrunc scFracZ (if scSigned && a0 >= halfPi then a0 - halfPi else a0)
    (zMin, (x, y)) = go steps z0 (abs z0) (x0, 0)
  in (zMin, min (dist x) (dist y))
 where
  halfPi = halfPiRounded scFracTrunc
  steps = [ (i, atanRounded i scFracZ) | i <- [0 .. scIterations - 1] ]
  x0 = inverseGainRounded scFracXY
  sh = scFracXY - scFracOut
  dist v = abs ((v `mod` (1 `shiftL` sh)) - (1 `shiftL` (sh - 1)))
  go [] _ m xy = (m, xy)
  go ((i, at) : rest) z m (x, y)
    | z >= 0 = go rest (z - at) (min m (abs z)) (x - (y `shiftR` i), y + (x `shiftR` i))
    | otherwise = go rest (z + at) (min m (abs z)) (x + (y `shiftR` i), y - (x `shiftR` i))

