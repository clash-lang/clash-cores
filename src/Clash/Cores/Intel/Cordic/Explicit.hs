Support for Intel's CORDIC IP (@ALTERA_CORDIC@), as described in the
[ALTERA_CORDIC IP Core User Guide (UG-20017)](https://www.intel.com/content/www/us/en/docs/programmable/683808/),
with explicit clock, reset and enable arguments. "Clash.Cores.Intel.Cordic"
has the same functions with a hidden clock, reset and enable.

Compilation instantiates the IP. Clash writes a Platform Designer system
(@.qsys@ file) for every instance, see "Clash.Cores.Intel.Internal" for how to
generate the IP from it. Simulation in Clash produces bit-identical results to
the IP's simulation model, cycle by cycle, for the inputs the user guide allows.

The user guide promises results that are faithfully rounded, but doesn't say
which way the IP rounds. The simulation models reproduce the IP's datapath,
which was inferred by observing the IP generated by Quartus Prime Lite 21.1,
and validated against it for a wide range of formats. See
"Clash.Cores.Intel.Cordic.Internal" for the details.

All IP instantiated by this module has the following properties:

* An enable input, driven by the 'Enable' argument. De-asserting it stalls the
  whole pipeline.
* Its asynchronous reset input @areset@ is driven by the 'Reset' argument. The
  outputs during reset, and until the pipeline has filled again, are
  undefined in simulation.
* The latency is set through the delay argument of the 'DSignal'. The IP is
  generated with the \"latency\" performance goal: Quartus picks the highest
  frequency at which it can implement the IP with that latency. Any latency
  works, including zero (which makes the IP combinational).

The results don't depend on the latency or the device family.
-}

{-# OPTIONS_GHC -fconstraint-solver-iterations=10 #-}

module Clash.Cores.Intel.Cordic.Explicit
  ( -- * Sine and cosine
    sinCos
  , sinCosUnsigned
    -- * Simulation models
  , sinCosModel
  , sinCosUnsignedModel
  ) where

import Clash.Explicit.Prelude

import GHC.Stack (HasCallStack, withFrozenCallStack)

import qualified Clash.Signal.Delayed as D

import Clash.Cores.Intel.Cordic.Internal hiding (sinCosModel)
import qualified Clash.Cores.Intel.Cordic.Internal as I
import Clash.Cores.Intel.Internal
  (ClockPort(..), IntelIp, Port(..), ResetPort(..), instConfig, instWithIntelIp)
import Clash.Cores.Xilinx.Xpm.Cdc.Internal (unPort)

-- | Sine and cosine of an angle in radians between -pi and pi. Returns
-- @(cos angle, sin angle)@. The input has @fIn + 3@ bits, the outputs have
-- @fOut + 2@ bits. The IP requires @fOut <= fIn@. Outputs with more than 34
-- fractional bits are not supported: the IP's datapath for those differs
-- from the model.
--
-- The results are within one unit in the last place of the exact values. See
-- 'sinCosModel' for which way they round. For angles outside [-pi, pi], the
-- results of the IP are not modelled: they are undefined in simulation.
--
-- The latency @d@ is set by the type, see "Clash.Cores.Intel.Cordic.Explicit".
sinCos ::
  forall d dom n fIn fOut.
  ( KnownDomain dom
  , KnownNat d
  , KnownNat fIn
  , KnownNat fOut
  , fOut <= fIn
  , fOut <= 34
  , HasCallStack
  ) =>
  Clock dom ->
  Reset dom ->
  Enable dom ->
  -- | Angle, in radians
  DSignal dom n (SFixed 3 fIn) ->
  -- | Cosine and sine
  DSignal dom (n + d) (SFixed 2 fOut, SFixed 2 fOut)
sinCos clk rst en a
  | clashSimulation = pipeline und clk rst en (sinCosModel <$> a)
  | otherwise = D.unsafeFromSignal (bundle (unpack <$> c, unpack <$> s))
 where
  und = withFrozenCallStack $ deepErrorX "Undefined output of sinCos"
  (c, s) =
    sinCosInst @(fOut + 2)
      (cordicIpSinCos True (natToNum @fIn) (natToNum @fOut) (natToNum @d))
      clk rst en (pack <$> D.toSignal a)
{-# INLINE sinCos #-}

-- | Sine and cosine of an angle in radians between 0 and pi\/2. Returns
-- @(cos angle, sin angle)@. The input has @fIn + 1@ bits, the outputs have
-- @fOut + 1@ bits. Unlike 'sinCos', the outputs can have more fractional bits
-- than the input. Outputs with more than 34 fractional bits are not
-- supported: the IP's datapath for those differs from the model.
--
-- The results are within one unit in the last place of the exact values. See
-- 'sinCosUnsignedModel' for which way they round. For angles above pi\/2, the
-- results of the IP are not modelled: they are undefined in simulation.
--
-- The latency @d@ is set by the type, see "Clash.Cores.Intel.Cordic.Explicit".
sinCosUnsigned ::
  forall d dom n fIn fOut.
  ( KnownDomain dom
  , KnownNat d
  , KnownNat fIn
  , KnownNat fOut
  , fOut <= 34
  , HasCallStack
  ) =>
  Clock dom ->
  Reset dom ->
  Enable dom ->
  -- | Angle, in radians
  DSignal dom n (UFixed 1 fIn) ->
  -- | Cosine and sine
  DSignal dom (n + d) (UFixed 1 fOut, UFixed 1 fOut)
sinCosUnsigned clk rst en a
  | clashSimulation = pipeline und clk rst en (sinCosUnsignedModel <$> a)
  | otherwise = D.unsafeFromSignal (bundle (unpack <$> c, unpack <$> s))
 where
  und = withFrozenCallStack $ deepErrorX "Undefined output of sinCosUnsigned"
  (c, s) =
    sinCosInst @(fOut + 1)
      (cordicIpSinCos False (natToNum @fIn) (natToNum @fOut) (natToNum @d))
      clk rst en (pack <$> D.toSignal a)
{-# INLINE sinCosUnsigned #-}

-- | Instantiate the IP for 'sinCos' or 'sinCosUnsigned'
sinCosInst ::
  forall wOut dom wIn.
  (KnownDomain dom, KnownNat wIn, KnownNat wOut) =>
  IntelIp 8 ->
  Clock dom ->
  Reset dom ->
  Enable dom ->
  Signal dom (BitVector wIn) ->
  (Signal dom (BitVector wOut), Signal dom (BitVector wOut))
sinCosInst ip clk rst en a = (unPort c, unPort s)
 where
  c :: Port "c" dom (BitVector wOut)
  s :: Port "s" dom (BitVector wOut)
  (c, s) =
    instWithIntelIp
      (instConfig "cordic_sincos")
      ip
      (ClockPort @"clk" clk)
      (ResetPort @"areset" @ActiveHigh rst)
      (Port @"en" (enPort en))
      (Port @"a" a)
{-# INLINE sinCosInst #-}

-- | Simulation model of 'sinCos'. Inputs outside [-pi, pi] give an undefined
-- result.
sinCosModel ::
  forall fIn fOut.
  (KnownNat fIn, KnownNat fOut, HasCallStack) =>
  SFixed 3 fIn ->
  (SFixed 2 fOut, SFixed 2 fOut)
sinCosModel a =
  case I.sinCosModel widths (toInteger (unSF a)) of
    Just (c, s) -> (sf (SNat @fOut) (fromInteger c), sf (SNat @fOut) (fromInteger s))
    Nothing -> withFrozenCallStack $ deepErrorX "sinCos: angle outside [-pi, pi]"
 where
  widths = sinCosWidths True (natToNum @fIn) (natToNum @fOut)

-- | Simulation model of 'sinCosUnsigned'. Inputs above pi\/2 give an undefined
-- result.
sinCosUnsignedModel ::
  forall fIn fOut.
  (KnownNat fIn, KnownNat fOut, HasCallStack) =>
  UFixed 1 fIn ->
  (UFixed 1 fOut, UFixed 1 fOut)
sinCosUnsignedModel a =
  case I.sinCosModel widths (toInteger (unUF a)) of
    Just (c, s) -> (uf (SNat @fOut) (fromInteger c), uf (SNat @fOut) (fromInteger s))
    Nothing -> withFrozenCallStack $ deepErrorX "sinCosUnsigned: angle above pi/2"
 where
  widths = sinCosWidths False (natToNum @fIn) (natToNum @fOut)
