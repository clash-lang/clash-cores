-- | Sine and cosine of an angle in radians between -pi and pi. Returns
-- @(cos angle, sin angle)@. The input has @fIn + 3@ bits, the outputs have
-- @fOut + 2@ bits. The IP requires @fOut <= fIn@. Outputs with more than 34
-- fractional bits are not supported: the IP's datapath for those differs
-- from the model.
--
-- The results are within one unit in the last place of the exact values. See
-- 'sinCosModel' for which way they round. For angles outside [-pi, pi], the
-- results of the IP are not modelled: they are undefined in simulation.
--
-- The latency @d@ is set by the type, see "Clash.Cores.Intel.Cordic.Explicit".
sinCos ::
  forall d dom n fIn fOut.
  ( KnownDomain dom
  , KnownNat d
  , KnownNat fIn
  , KnownNat fOut
  , fOut <= fIn
  , fOut <= 34
  , HasCallStack
  ) =>
  Clock dom ->
  Reset dom ->
  Enable dom ->
  -- | Angle, in radians
  DSignal dom n (SFixed 3 fIn) ->
  -- | Cosine and sine
  DSignal dom (n + d) (SFixed 2 fOut, SFixed 2 fOut)
sinCos clk rst en a
  | clashSimulation = pipeline und clk rst en (sinCosModel <$> a)
  | otherwise = D.unsafeFromSignal (bundle (unpack <$> c, unpack <$> s))
 where
  und = withFrozenCallStack $ deepErrorX "Undefined output of sinCos"
  (c, s) =
    sinCosInst @(fOut + 2)
      (cordicIpSinCos True (natToNum @fIn) (natToNum @fOut) (natToNum @d))
      clk rst en (pack <$> D.toSignal a)
{-# INLINE sinCos #-}

