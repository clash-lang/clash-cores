= Differences from Intel's documentation

The IP generated by Quartus Prime Lite 21.1 differs from the
[ALTERA_CORDIC IP Core User Guide](https://www.intel.com/content/www/us/en/docs/programmable/683808/)
(UG-20017, version 2016.05.01) as follows. Each was found by black-box
testing: simulating the generated IP's simulation model on chosen inputs.

* /Faithful rounding./ The guide (\"ALTERA_CORDIC IP Core Features\")
  promises \"faithfully rounded results to either of the two closest
  representable numbers\". The arctangent of unsigned inputs ('atan2Unsigned',
  'atan2UnsignedLut', 'vectorTranslateUnsigned' and
  'vectorTranslateUnsignedCompensated') with @x = 0@ and @y > 0@ is pi\/2
  rounded to one bit fewer than the output has, and with one fractional output
  bit that wraps around to 0 instead of 1.5. Found on exhaustive simulations of
  formats with input widths 4 to 10 (MAX 10).

* /Unsigned vector rotation./ The guide (\"ALTERA_CORDIC IP Core Functional
  Description\", vector rotation, and Table 5) describes unsigned inputs for
  VECROTATE, with @x@ and @y@ in [0, 1] and the angle in [0, pi]. The
  generator of Quartus 21.1 fails for unsigned inputs, so 'vectorRotate' only
  takes signed ones.

* /LUT size optimization./ The guide (Table 3) describes the option \"LUT Size
  Optimization\" of ATAN2 as moving \"some of the typical CORDIC operations
  into look up tables to reduce implementation cost\". It also changes the
  results: they are the angles of VECTRANSLATE, which can differ from the ones
  of ATAN2 without the option in the last place ('atan2Lut'). Found by
  comparing the two on 205 formats (MAX 10) and with the sweeps of
  'atan2Lut' on all four families.

* /Device family./ The guide doesn't say that results depend on the device
  family. The angle of VECTRANSLATE (and of ATAN2 with LUT size optimization)
  does: Cyclone V sums the arctangent constants with tables of six rotation
  directions, the other families with tables of four, which round
  differently (on Cyclone V about 6% of the results of signed 8 bit inputs
  with 6 fractional output bits differ). Found by simulating the IP generated
  for each family on the same inputs. ATAN2 without the option gives the same
  results on all four families, sine and cosine on MAX 10 and Cyclone V;
  VECROTATE was only checked on MAX 10.
-}

