#differences#

= Differences from Intel's documentation

The IP generated by Quartus Prime Lite 21.1 differs from the
[ALTERA_CORDIC IP Core User Guide](https://www.intel.com/content/www/us/en/docs/programmable/683808/)
(UG-20017, version 2016.05.01) as follows. Each was found by black-box
testing: simulating the generated IP's simulation model on chosen inputs.

* /Faithful rounding./ The guide (\"ALTERA_CORDIC IP Core Features\")
  promises \"faithfully rounded results to either of the two closest
  representable numbers\". The arctangent of unsigned inputs ('atan2Unsigned',
  'atan2UnsignedLut', 'vectorTranslateUnsigned' and
  'vectorTranslateUnsignedCompensated') with @x = 0@ and @y > 0@ is pi\/2
  rounded to one bit fewer than the output has, and with one fractional output
  bit that wraps around to 0 instead of 1.5. Found on exhaustive simulations of
  formats with input widths 4 to 10 (MAX 10).

* /Unsigned vector rotation./ The guide (\"ALTERA_CORDIC IP Core Functional
  Description\", vector rotation, and Table 5) describes unsigned inputs for
  VECROTATE, with @x@ and @y@ in [0, 1] and the angle in [0, pi]. The
  generator of Quartus 21.1 fails for unsigned inputs, so 'vectorRotate' only
  takes signed ones.

* /LUT size optimization./ The guide (Table 3) describes the option \"LUT Size
  Optimization\" of ATAN2 as moving \"some of the typical CORDIC operations
  into look up tables to reduce implementation cost\". It also changes the
  results: they are the angles of VECTRANSLATE, which can differ from the ones
  of ATAN2 without the option in the last place ('atan2Lut'). Found by
  comparing the two on 205 formats (MAX 10) and with the sweeps of
  'atan2Lut' on all four families.

* /Device family./ The guide doesn't say that results depend on the device
  family. Some do, through the number of inputs of the family's LUTs (six on
  Cyclone V, four on the others). The angle of VECTRANSLATE (and of ATAN2
  with LUT size optimization) sums the arctangent constants with tables of
  that many rotation directions, which round differently (on Cyclone V about
  6% of the results of signed 8 bit inputs with 6 fractional output bits
  differ). SINCOS with a signed input and VECROTATE truncate the angle to a
  number of bits that depends on it (for VECROTATE with 8 fractional input
  bits and 2 fractional output bits, about 4% of the results differ on
  Cyclone V; for SINCOS with 12 and 3, about 5%). Found by simulating the IP
  generated for each family on the same inputs. ATAN2 without the option
  gives the same results on all four families, and so does SINCOS with an
  unsigned input on MAX 10 and Cyclone V.

* /Scale factor compensation of VECROTATE./ The guide only documents the
  option's effect on the range of the outputs. The IP multiplies by 1\/K with
  a constant multiplier made of tables or of shifts and additions, whichever
  its generator counts as cheaper for the format and the device family, and
  the two use the constant at different precisions, so their results differ
  in the last place (for up to 3% of the inputs).
  'vectorRotateCompensated' follows that choice, see
  "Clash.Cores.Intel.Cordic.Internal". The constant is 0.6072529380035, the
  inverse of K rounded to 1.64676025, so with many output bits the results
  are less accurate than the output format suggests: the constant is off by
  3e-9, which is more than one unit in the last place from 28 fractional
  output bits on.

* /Latencies that Cyclone V reaches with memory./ The guide says the IP adds
  registers to reach a requested latency. For ATAN2 with 6 bit inputs and 20
  fractional output bits on Cyclone V, Quartus 21.1 reaches the latencies 20
  to 29 (and 40) by padding a datapath of 14 (or 30) cycles with a delay
  line in MLAB memory (120 memory bits in the synthesis report), and that IP
  gives zero for every input in simulation (in GHDL, and at latency 25 also in
  the Vivado simulator). At the latencies 14 to 18 and 30 to 32 it uses no memory, and the
  results are those of the other families. Whether the IP also fails in
  hardware was not tested. Found when the test of this format ran on Cyclone
  V; other formats and latencies were not surveyed for this.

* /Generating on a busy machine./ The generator searches for a target
  frequency at which the IP has the requested latency, and it fails when the
  machine is busy: with all CPUs saturated, Quartus 21.1 reports
  \"Frequency Target is too low for this parameterization\" or \"Could not
  achieve the requested latency at any frequency\" for a latency it reaches
  on an idle machine. Formats that take long to generate are affected
  first, such as ATAN2 with many more fractional output bits than input
  bits (about 8 seconds per attempt for 6 bit inputs and 20 fractional
  output bits, against 1 to 5 seconds for most formats).
-}

