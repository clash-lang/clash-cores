Instantiate Intel IP, generated by Quartus's Platform Designer, from Clash.
This is the Intel counterpart of
'Clash.Cores.Xilinx.Xpm.Cdc.Internal.instWithXilinxWizard'.

'instWithIntelIp' instantiates a component like
'Clash.Cores.Xilinx.Xpm.Cdc.Internal.inst' does, and makes Clash write an
/IP variation/: a Platform Designer system (@.qsys@ file) with a single
instance of the IP, whose interfaces are all exported. The generated entity has
the IP's own port names and is named after the @.qsys@ file. This is the same
format @clash-prelude@ uses for 'Clash.Intel.ClockGen.alteraPll'.

= Synthesis

Add the @.qsys@ files Clash generates to the Quartus project, e.g.

> set_global_assignment -name QSYS_FILE <file>.qsys

or generate the IP from the command line with:

> qsys-generate <file>.qsys --synthesis=VHDL --family="Cyclone V"

and add the generated @.qip@ file to the project. The files don't fix a device
family: Quartus generates the IP for the family of the project, or the one
passed to @qsys-generate@.

= Simulation

Platform Designer generates simulation models with:

> qsys-generate <file>.qsys --simulation=VHDL --family="Cyclone V"

To save that step, Clash can run it itself and add the simulation model of
every IP to its output. Set the environment variable
@CLASH_INTEL_SIM_FAMILY@ to the device family to generate the models for,
e.g. @Cyclone V@, before running Clash. Clash runs @qsys-generate@ from
@$QUARTUS_ROOTDIR\/sopc_builder\/bin@, or from the @PATH@ if
@QUARTUS_ROOTDIR@ isn't set. The models need Intel's simulation libraries,
such as @altera_mf@ and @lpm@ (from @$QUARTUS_ROOTDIR\/eda\/sim_lib@),
compiled into libraries with those names (see also 'simLibraryFiles').
Files that the models refer to by name, such as memory initialization files,
are not part of the HDL output: simulators look for them relative to the
directory they run in. Clash keeps them in a directory named after a hash of
their contents, under @$XDG_CACHE_HOME\/clash-cores\/intel-ip@ (or
@$CLASH_INTEL_SIM_CACHE\/data@, see below), and the models refer to them by
their absolute path.

Generating takes a few seconds per IP. Set @CLASH_INTEL_SIM_CACHE@ to a
directory to keep the generated models there, and reuse them the next time
Clash generates HDL.

Tested with Quartus Prime Lite 21.1. Quartus Prime Pro uses @.ip@ files
instead, which is not supported.
-}

