-- | Value of a parameter of Intel IP, as set in Platform Designer.
data IpParam
  = StrParam String
  -- ^ String parameter, e.g. @StrParam \"ADD\"@
  | IntegerParam Integer
  -- ^ Integer parameter
  | BoolParam Bool
  -- ^ Boolean parameter, rendered as @true@ or @false@
  deriving (Show)

-- | Intel IP to generate with Platform Designer.
--
-- The parameter names and values are the ones Platform Designer uses, which
-- can be found in the @.qsys@ or @.ip@ file the IP Parameter Editor saves,
-- with @ip-generate --help@, or in the IP's @_hw.tcl@ file in the Quartus
-- installation directory.
data IntelIp n = IntelIp
  { ipKind :: String
  -- ^ Name of the IP component, e.g. @altera_fp_functions@
  , ipParams :: Vec n (String, IpParam)
  -- ^ Parameters, e.g. @(\"FUNCTION_FAMILY\", StrParam \"ARITH\")@.
  -- Parameters not listed get their default values.
  } deriving (Show)

-- Note that this splice also separates the declaration of 'IntelIp' from the
-- splice in its 'TermLiteral' instance, which needs to reify it.
deriveTermLiteral ''IpParam

#if MIN_VERSION_clash_lib(1,11,0)
#define TERM_TO_DATA termToData#
#else
#define TERM_TO_DATA termToData
#endif
instance KnownNat n => TermLiteral (IntelIp n) where
  TERM_TO_DATA = $(deriveTermToData ''IntelIp)

-- | Render the value of a parameter the way Platform Designer expects it in
-- a @.qsys@ file
ipParamValue :: IpParam -> String
ipParamValue = \case
  StrParam s -> s
  IntegerParam i -> show i
  BoolParam True -> "true"
  BoolParam False -> "false"

-- | Render a @.qsys@ file with a single instance of the IP, with all its
-- interfaces exported. The system is named @name@. Platform Designer
-- replaces @$${FILENAME}@ by the file name of the @.qsys@ file.
renderQsys ::
  -- | Name of the system, e.g. @$${FILENAME}@
  String ->
  IntelIp n ->
  Text
renderQsys name IntelIp{ipKind, ipParams} = Text.pack [__i|
  <?xml version="1.0" encoding="UTF-8"?>
  <system name="#{xmlEscape name}">
   <module
     name="ip_0"
     kind="#{xmlEscape ipKind}"
     enabled="1"
     autoexport="1">
  #{params}
   </module>
  </system>
  |]
 where
  params = intercalate "\n"
    [ "  <parameter name=\"" <> xmlEscape nm <> "\" value=\""
        <> xmlEscape (ipParamValue v) <> "\" />"
    | (nm, v) <- toList ipParams ]

  xmlEscape = P.concatMap $ \case
    '&' -> "&amp;"
    '<' -> "&lt;"
    '>' -> "&gt;"
    '"' -> "&quot;"
    '\'' -> "&apos;"
    c -> [c]

-- | Like 'Clash.Cores.Xilinx.Xpm.Cdc.Internal.inst', but also generates a
-- @.qsys@ file for Platform Designer that creates the instantiated component.
-- The component's name is a unique derivative of 'compName'. See the module
-- documentation for how to generate the IP for synthesis and simulation.
--
-- Example usage:
--
-- > fpAdd ::
-- >   forall dom. KnownDomain dom =>
-- >   Clock dom -> Signal dom (BitVector 32) -> Signal dom (BitVector 32) -> Signal dom (BitVector 32)
-- > fpAdd clk a b = unPort q
-- >  where
-- >   q :: Port "q" dom (BitVector 32)
-- >   q =
-- >     instWithIntelIp
-- >       (instConfig "fp_add")
-- >       IntelIp
-- >         { ipKind = "altera_fp_functions"
-- >         , ipParams =
-- >                ("FUNCTION_FAMILY", StrParam "ARITH")
-- >             :> ("ARITH_function", StrParam "ADD")
-- >             :> ("performance_goal", StrParam "latency")
-- >             :> ("latency_target", IntegerParam 3)
-- >             :> Nil
-- >         }
-- >       (ClockPort @"clk" clk)
-- >       (Port @"areset" @dom (pure (0 :: Bit)))
-- >       (Port @"a" a)
-- >       (Port @"b" b)
instWithIntelIp ::
  forall a n.
  (Inst a, KnownNat n) =>
  InstConfig ->
  IntelIp n ->
  a
instWithIntelIp i x = instWithIntelIp# x i
{-# INLINE instWithIntelIp #-}

