-- | Environment variable that makes Clash generate simulation models, see the
-- module documentation
simFamilyEnvVar :: String
simFamilyEnvVar = "CLASH_INTEL_SIM_FAMILY"

-- | Environment variable with a directory in which Clash keeps the simulation
-- models it generates, to save running @qsys-generate@ again for the same IP,
-- device family and Quartus installation. Optional.
simCacheEnvVar :: String
simCacheEnvVar = "CLASH_INTEL_SIM_CACHE"

-- | Name of the Platform Designer system when Clash generates the simulation
-- model. Clash replaces it in the generated files by the name of the @.qsys@
-- file.
placeholderName :: Text
placeholderName = "clash_intel_ip_placeholder"

-- | 'BlackBoxFunction' for 'instWithIntelIp'
instWithIntelIpBBF :: HasCallStack => BlackBoxFunction
instWithIntelIpBBF isD primName args resTys
  | _instConstraint
  : (either error P.id . Compat.termToDataError -> n)
  : ipAsTerm
  : _config
  : _userArgs <- lefts args
  = withSomeSNat n $ \(SNat :: SNat n) -> do
      let
        !(ip :: IntelIp n) = either error P.id $ Compat.termToDataError ipAsTerm
        qsys = renderQsys "$${FILENAME}" ip
        -- 'instWithIntelIp' takes two extra arguments: a @KnownNat n@
        -- constraint, and an 'IntelIp'. These arguments should be dropped
        -- in the general black box functions.
        nExtraArgs = 2
      hdl <- Lens.use (backend . fromSomeBackend hdlKind)
      family <- liftIO (lookupEnv simFamilyEnvVar)
      simFiles <- case family of
        Just fam@(_:_) ->
          liftIO (generateSimModel hdl fam (renderQsys (Text.unpack placeholderName) ip))
        _ -> pure []
      instBBFWorkerWithIncludes
        nExtraArgs (Just (includes qsys simFiles)) isD primName args resTys
instWithIntelIpBBF _ _ args resTys = error $
     show 'instWithIntelIpBBF
  <> ", bad args:\n\n"
  <> ppShow args
  <> "\n\nor result types:\n\n"
  <> ppShow resTys

-- | The @.qsys@ file, followed by the simulation model (if any)
includes :: Text -> [SimFile] -> InstConfig -> [((Text, Text), BlackBox)]
includes qsys simFiles InstConfig{compName} =
    ( (Text.pack compName, "qsys")
    , BBFunction "Clash.Cores.Intel.Internal.qsys" 0
        (TemplateFunction [] (const True) (\_ -> pure (pretty qsys)))
    )
  : P.map simInclude simFiles
 where
  simInclude f@SimFile{simFileExt, simFileContents} =
    ( (simFileIncludeName (Text.pack compName) f, simFileExt)
    , BBFunction "Clash.Cores.Intel.Internal.simFile" 0
        (TemplateFunction [] (const True)
          (\bbCtx -> pure (pretty (header <> substituteNames (bbQsysIncName bbCtx) f))))
    )
   where
    -- Clash names an include after a hash of its contents, rendered with
    -- placeholders for the names of the includes. Files that differ only in
    -- those names, like the top level files of two configurations of the same
    -- IP, would get the same name. Files that refer to the name of the IP
    -- therefore get a header with its parameters.
    header
      | placeholderName `Text.isInfixOf` simFileContents
      , Just c <- commentStart simFileExt
      = c <> " Simulation model generated by Platform Designer for: "
          <> Text.unwords (Text.words qsys) <> "\n"
      | otherwise = ""
    commentStart = \case
      "vhdl" -> Just "--"
      "v" -> Just "//"
      "sv" -> Just "//"
      _ -> Nothing

-- | A file of a simulation model generated by Platform Designer
data SimFile = SimFile
  { simFileBase :: Text
  -- ^ File name without extension, e.g. @dspba_library@
  , simFileOrigExt :: Text
  -- ^ Original extension, e.g. @vhd@
  , simFileExt :: Text
  -- ^ Extension Clash should use, e.g. @vhdl@
  , simFileContents :: Text
  } deriving (Show, Read)

-- | Name of the Clash include for a generated file: its file name, where the
-- name of the Platform Designer system is replaced by 'compName'.
simFileIncludeName :: Text -> SimFile -> Text
simFileIncludeName compName SimFile{simFileBase} =
  Text.replace placeholderName compName simFileBase

-- | Clash names includes after their contents, rendered with placeholders
-- for the names of the includes. Replace the name of the Platform Designer
-- system in the contents of a generated file by the name Clash gives the
-- @.qsys@ file, which is the first name.
substituteNames :: [Text] -> SimFile -> Text
substituteNames names SimFile{simFileContents}
  | qsysName : _ <- names
  = Text.replace placeholderName qsysName simFileContents
  | otherwise
  = error ("Internal error: unexpected include names: " <> show names)

-- | Cache of generated simulation models, so that every combination of
-- language, family and IP is generated once per Clash run
simModelCache :: IORef (Map.Map (String, String, Text) [SimFile])
simModelCache = unsafePerformIO (newIORef Map.empty)
{-# NOINLINE simModelCache #-}

-- | Run @qsys-generate@ to generate the simulation model of a @.qsys@ file
-- for the given device family. Returns the generated files, HDL files of
-- sub modules first.
generateSimModel ::
  -- | Language of the simulation model is the language of the Clash output.
  -- Note that some IP only has VHDL simulation models.
  HDL ->
  -- | Device family, e.g. @Cyclone V@
  String ->
  -- | Contents of the @.qsys@ file, with system name @clash_intel_ip_placeholder@
  Text ->
  IO [SimFile]
generateSimModel hdl family qsys = do
  let key = (lang, family, qsys)
  cached <- Map.lookup key <$> readIORef simModelCache
  case cached of
    Just files -> pure files
    Nothing -> do
      files <- diskCached runQsysGenerate
      _ <- evaluate (P.length (show files))
      atomicModifyIORef' simModelCache (\m -> (Map.insert key files m, ()))
      pure files
 where
  lang = case hdl of
    VHDL -> "VHDL"
    _ -> "VERILOG"

  -- If 'simCacheEnvVar' is set, keep generated models in that directory
  diskCached act = do
    cacheDir <- lookupEnv simCacheEnvVar
    root <- lookupEnv "QUARTUS_ROOTDIR"
    case cacheDir of
      Just dir@(_:_) -> do
        let
          key = show (lang, family, qsys, root)
          file = dir </> showHex64 (fnv1a key) <> ".simmodel"
        exists <- doesFileExist file
        cached <-
          if exists
            then do
              contents <- Text.readFile file
              pure $ case reads (Text.unpack contents) of
                [((key', files), "")] | key' == key -> Just files
                _ -> Nothing
            else pure Nothing
        case cached of
          Just files -> pure files
          Nothing -> do
            files <- act
            createDirectoryIfMissing True dir
            Text.writeFile file (Text.pack (show (key, files)))
            pure files
      _ -> act

  fnv1a :: String -> Word64
  fnv1a = P.foldl (\h c -> (h `xor` P.fromIntegral (fromEnum c)) * 1099511628211) 14695981039346656037

  showHex64 w = P.reverse (P.take 16 (P.map hexDigit (P.iterate (`shiftR` 4) w)))
  hexDigit w = "0123456789abcdef" P.!! P.fromIntegral (w .&. 15)

  runQsysGenerate =
    withSystemTempDirectory "clash-intel-ip" $ \dir -> do
      let
        qsysFile = dir </> Text.unpack placeholderName <> ".qsys"
        outDir = dir </> "out"
      Text.writeFile qsysFile qsys
      qsysGenerate <- findQsysGenerate
      let
        args =
          [ qsysFile
          , "--simulation=" <> lang
          , "--family=" <> family
          , "--output-directory=" <> outDir
          ]
      res <- try (readCreateProcessWithExitCode (proc qsysGenerate args) "")
      case res of
        Left (e :: SomeException) ->
          failGen qsysGenerate args ("Could not run qsys-generate: " <> show e)
        Right (ExitFailure c, out, err) ->
          failGen qsysGenerate args
            ("qsys-generate exited with code " <> show c <> ":\n" <> out <> err)
        Right (ExitSuccess, out, err)
          | any ("Error:" `Text.isInfixOf`) (Text.lines (Text.pack (out <> err))) ->
              failGen qsysGenerate args ("qsys-generate reported errors:\n" <> out <> err)
          | otherwise -> do
              let simDir = outDir </> "simulation"
              subFiles <- listFiles (simDir </> "submodules")
              topFiles <- listFiles simDir
              -- Platform Designer lists the HDL files in compilation order in
              -- its simulation package description. Put the other files, like
              -- memory initialization files, first.
              let spdFile = outDir </> Text.unpack placeholderName <> ".spd"
              spdExists <- doesFileExist spdFile
              hdlOrder <-
                if spdExists then P.map (outDir </>) . spdPaths <$> Text.readFile spdFile else pure []
              let
                allFiles = subFiles <> topFiles
                ordered =
                     [f | f <- allFiles, f `P.notElem` hdlOrder, not (isHdl f)]
                  <> [f | f <- hdlOrder, f `P.elem` allFiles]
                  <> [f | f <- allFiles, f `P.notElem` hdlOrder, isHdl f]
              files <- mapM readSimFile ordered
              let (hdlFiles, dataFiles) = P.span ((`P.elem` ["vhdl", "v", "sv"]) . simFileExt) (P.reverse files)
              dataPaths <- mapM storeDataFile dataFiles
              case hdlFiles of
                [] -> failGen qsysGenerate args ("qsys-generate generated no files:\n" <> out <> err)
                _ -> pure (P.map (referToData dataPaths) (P.reverse hdlFiles))

  -- Simulators look for files the HDL refers to by name, like memory
  -- initialization files, relative to the directory they run in, which is
  -- unknown to Clash. So keep them in a directory named after a hash of their
  -- contents, and refer to them by their absolute path.
  storeDataFile f@SimFile{simFileBase, simFileOrigExt, simFileContents} = do
    root <- dataDir
    let
      name = Text.unpack (simFileBase <> "." <> simFileOrigExt)
      dir = root </> showHex64 (fnv1a (Text.unpack simFileContents))
      path = dir </> name
    createDirectoryIfMissing True dir
    exists <- doesFileExist path
    if exists then pure () else Text.writeFile path simFileContents
    pure (f, path)

  referToData dataPaths f@SimFile{simFileContents} =
    f { simFileContents = P.foldl replaceRef simFileContents dataPaths }
   where
    replaceRef t (SimFile{simFileBase, simFileOrigExt}, path) =
      Text.replace
        ("\"" <> simFileBase <> "." <> simFileOrigExt <> "\"")
        ("\"" <> Text.pack path <> "\"")
        t

  dataDir = do
    cacheDir <- lookupEnv simCacheEnvVar
    case cacheDir of
      Just dir@(_:_) -> pure (dir </> "data")
      _ -> getXdgDirectory XdgCache ("clash-cores" </> "intel-ip")

  -- Paths in a simulation package description (@.spd@ file), in order
  spdPaths :: Text -> [FilePath]
  spdPaths t = case Text.breakOn "path=\"" t of
    (_, rest)
      | Text.null rest -> []
      | otherwise ->
          let (path, rest1) = Text.breakOn "\"" (Text.drop 6 rest)
          in Text.unpack path : spdPaths rest1

  isHdl f = takeExtension f `P.elem` [".vhd", ".vhdl", ".v", ".sv"]

  listFiles d = do
    exists <- doesDirectoryExist d
    if not exists then pure [] else do
      es <- P.map (d </>) <$> listDirectory d
      fs <- filterM doesFileExist es
      pure [f | f <- fs, takeExtension f `P.notElem` [".sip", ".spd", ".csv"]]

  readSimFile f = do
    contents <- Text.readFile f
    let
      origExt = P.drop 1 (takeExtension f)
      ext = case origExt of
        "vhd" -> "vhdl"
        e -> e
      base = Text.pack (lastComponent (dropExtension f))
    pure SimFile
      { simFileBase = base
      , simFileOrigExt = Text.pack origExt
      , simFileExt = Text.pack ext
      , simFileContents = contents
      }

  lastComponent = P.reverse . P.takeWhile (/= '/') . P.reverse

  failGen exe args msg = error [__i|
    Clash.Cores.Intel.Internal: generating the simulation model of Intel IP
    for device family "#{family}" failed (because #{simFamilyEnvVar} is set).
    Command:

      #{P.unwords (exe : args)}

    #{msg}

    .qsys file:

    #{qsys}
    |]

  findQsysGenerate = do
    root <- lookupEnv "QUARTUS_ROOTDIR"
    case root of
      Just r@(_:_) -> pure (r </> "sopc_builder" </> "bin" </> "qsys-generate")
      _ -> do
        exe <- findExecutable "qsys-generate"
        case exe of
          Just e -> pure e
          Nothing -> error [__i|
            Clash.Cores.Intel.Internal: #{simFamilyEnvVar} is set, but
            qsys-generate could not be found. Set QUARTUS_ROOTDIR or add
            qsys-generate to the PATH.
            |]

-- | Behaves like 'id', but makes Clash add the given files from Intel's
-- simulation libraries to the HDL output. The files are given relative to
-- @$QUARTUS_ROOTDIR\/eda\/sim_lib@, and are read when Clash generates HDL.
--
-- The simulation models of Intel IP (see 'simFamilyEnvVar') refer to VHDL
-- libraries such as @altera_mf@, @lpm@ and @altera_lnsim@. Some tools, like
-- Clash's Vivado integration, compile the VHDL files of a top entity into a
-- library named after the top entity. A top entity named after an Intel
-- library that uses this function then creates that library. E.g.:
--
-- > alteraLnsim :: Bool -> Bool
-- > alteraLnsim =
-- >   simLibraryFiles ("altera_lnsim_components.vhd" :> "altera_lnsim.sv" :> Nil)
-- > {-# OPAQUE alteraLnsim #-}
-- > {-# ANN alteraLnsim (Synthesize "altera_lnsim" [PortName "i"] (PortName "o")) #-}
--
-- Use the function somewhere in a design, e.g. on a test bench's @done@
-- signal, to make it part of the HDL output.
simLibraryFiles :: KnownNat n => Vec n String -> Bool -> Bool
simLibraryFiles = simLibraryFiles#
{-# INLINE simLibraryFiles #-}

-- | Primitive for 'simLibraryFiles'
simLibraryFiles# :: KnownNat n => Vec n String -> Bool -> Bool
simLibraryFiles# !_ b = b
{-# OPAQUE simLibraryFiles# #-}
{-# ANN simLibraryFiles# (
  let
    primName = show 'simLibraryFiles#
    tfName = show 'simLibraryFilesBBF
  in
    InlineYamlPrimitive [minBound..] [__i|
      BlackBoxHaskell:
        name: #{primName}
        templateFunction: #{tfName}
        workInfo: Never
    |]) #-}

-- | 'BlackBoxFunction' for 'simLibraryFiles#'
simLibraryFilesBBF :: HasCallStack => BlackBoxFunction
simLibraryFilesBBF _isD _primName args _resTys
  | [ (either error P.id . Compat.termToDataError -> n)
    , filesAsTerm
    , _b ] <- lefts args
  = withSomeSNat n $ \(SNat :: SNat n) -> do
      let files = toList (either error P.id (Compat.termToDataError filesAsTerm) :: Vec n String)
      root <- liftIO (lookupEnv "QUARTUS_ROOTDIR")
      dir <- case root of
        Just r@(_:_) -> pure (r </> "eda" </> "sim_lib")
        _ -> error "simLibraryFiles: QUARTUS_ROOTDIR is not set"
      contents <- liftIO (mapM (fmap Text.decodeLatin1 . ByteString.readFile . (dir </>)) files)
      let
        inc f c =
          ( ( Text.pack (lastComponent (dropExtension f))
            , case takeExtension f of
                ".vhd" -> "vhdl"
                e -> Text.pack (P.drop 1 e)
            )
          , BBFunction "Clash.Cores.Intel.Internal.simLibraryFile" 0
              (TemplateFunction [] (const True)
                (\_ -> pure (pretty (sanitize (Text.pack (comment f <> (dir </> f) <> "\n") <> c)))))
          )
        meta = emptyBlackBoxMeta
          { bbKind = TDecl
          , bbIncludes = P.zipWith inc files contents
          }
      pure (Right (meta, BBFunction "Clash.Cores.Intel.Internal.simLibraryFiles" 0 tf))
 where
  tf = TemplateFunction [2] (const True) $ \bbCtx ->
    case DSL.tInputs bbCtx of
      [_, _, (b, _)] -> DSL.declarationReturn bbCtx "sim_library" (pure [b])
      _ -> error ("simLibraryFiles: unexpected arguments: " <> ppShow (DSL.tInputs bbCtx))
  lastComponent = P.reverse . P.takeWhile (/= '/') . P.reverse
  comment f
    | takeExtension f `P.elem` [".vhd", ".vhdl"] = "-- "
    | otherwise = "// "
  -- Clash expects includes in valid UTF-8; drop the few characters outside of
  -- ASCII some of Intel's files have in their comments
  sanitize = Text.map (\c -> if c == '\t' || c == '\n' || (c >= ' ' && c < '\DEL') then c else ' ')
                . Text.filter (/= '\r')
simLibraryFilesBBF _ _ args _ = error $
  show 'simLibraryFilesBBF <> ", bad args:\n\n" <> ppShow args
