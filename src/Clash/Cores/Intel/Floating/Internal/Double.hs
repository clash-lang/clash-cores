import Clash.Explicit.Prelude

import Data.Word (Word64)
import GHC.Float (castDoubleToWord64, castWord64ToDouble)

import Clash.Cores.Intel.Floating.Internal
  (Config, DeviceFamily, familyMultipliers, fpFunctionsFormat)
import Clash.Cores.Intel.Floating.Internal.BitExactDouble
import Clash.Cores.Intel.Internal (IntelIp, IpParam(..))

-- | Lift a function on bit patterns to 'Double'
onBits :: (Word64 -> Word64) -> Double -> Double
onBits f = castWord64ToDouble . f . castDoubleToWord64

-- | NaN as generated by the Intel IP in double precision: positive, with the
-- least significant bit of the fraction set (@0x7FF0000000000001@).
intelNaN :: Double
intelNaN = castWord64ToDouble 0x7FF0000000000001

-- | Model of a binary operation of the IP
onBits2 :: (Word64 -> Word64 -> Word64) -> Double -> Double -> Double
onBits2 f x y = castWord64ToDouble (f (castDoubleToWord64 x) (castDoubleToWord64 y))

-- | Model of the floating point addition of the IP in double precision: IEEE
-- 754 addition, rounding to nearest with ties to even, but with subnormal
-- inputs treated as zero and results flushed to zero as in single precision
-- (see "Clash.Cores.Intel.Floating.Explicit"): the result is rounded as if
-- the exponent were unbounded, and flushed to a zero of the same sign if that
-- is below the smallest normal number. NaN results are always 'intelNaN'.
--
-- Verified against the simulated IP (Quartus Prime Lite 21.1) for MAX 10,
-- Cyclone IV E, Cyclone 10 LP and Cyclone V, at several latencies, on 700,000
-- pairs of inputs each: all pairs of special values, random inputs of several
-- kinds (around one, close to each other, near the ends of the exponent
-- range, with few fraction bits set) and inputs whose result is close to the
-- smallest normal number. The same goes for 'subModel', 'mulModel' and
-- 'divModel'.
addModel :: Double -> Double -> Double
addModel = onBits2 addDouble

-- | Model of the floating point subtraction of the IP in double precision,
-- see 'addModel'
subModel :: Double -> Double -> Double
subModel = onBits2 subDouble

-- | Model of the floating point multiplication of the IP in double precision,
-- see 'addModel'
mulModel :: Double -> Double -> Double
mulModel = onBits2 mulDouble

-- | Model of the floating point division of the IP in double precision, see
-- 'addModel'. Unlike 'recipModel', it flushes every result below the
-- smallest normal number.
divModel :: Double -> Double -> Double
divModel = onBits2 divDouble

-- | Model of the square root of the IP in double precision. It gives the IP's
-- results bit for bit, see Note [Bit-exact double precision models] in
-- "Clash.Cores.Intel.Floating.Internal.BitExactDouble": a significand
-- computed with a polynomial of degree five, which is faithfully rounded but
-- not always rounded to nearest. Subnormal inputs are treated as zero,
-- @sqrt (-0) = -0@, and negative inputs give 'intelNaN'.
--
-- Verified against the simulated IP (Quartus Prime Lite 21.1) for MAX 10,
-- Cyclone IV E, Cyclone 10 LP and Cyclone V, at several latencies, on 4.3
-- million inputs each: special values, random inputs, inputs in every segment
-- of its tables, inputs close to the rounding boundaries, and on another
-- 600,000 inputs per family whose results would change with a small change of
-- the model's structure.
sqrtModel :: DeviceFamily -> Double -> Double
sqrtModel fam = onBits (sqrtDouble (familyMultipliers fam))

-- | Model of the reciprocal square root of the IP in double precision. It
-- gives the IP's results bit for bit, see Note [Bit-exact double precision
-- reciprocal square root] in
-- "Clash.Cores.Intel.Floating.Internal.BitExactDouble": a significand computed
-- with a polynomial of degree five, which is faithfully rounded (up to 0.63
-- units in the last place off on MAX 10, Cyclone IV E and Cyclone 10 LP, and
-- 0.73 on Cyclone V) but not always rounded to nearest. Zero and subnormal
-- inputs give an infinity of the same sign, @+inf@ gives @+0@, and negative
-- inputs and NaN give 'intelNaN'.
--
-- In two of its 512 table segments the model uses coefficients observed from
-- the IP's outputs instead of computed ones, see Note [Observed double
-- precision rsqrt coefficients].
--
-- Verified against the simulated IP (Quartus Prime Lite 21.1) for MAX 10,
-- Cyclone IV E, Cyclone 10 LP and Cyclone V, at 200 MHz and at the minimum
-- latency, on 3.8 million inputs each: special values at every exponent,
-- random inputs, inputs in every segment of its table, 685,000 inputs in the
-- two segments with observed coefficients, and inputs whose results would
-- change with a small change of the model's structure or with the other
-- family's datapath.
rsqrtModel :: DeviceFamily -> Double -> Double
rsqrtModel fam = onBits (rsqrtDouble (familyMultipliers fam))

-- | Model of the reciprocal of the IP in double precision. Like in single
-- precision, it is the IEEE 754 reciprocal, rounded to nearest, ties to even,
-- of the input with subnormal inputs treated as zero and the exponent
-- unbounded. Results below the smallest normal number are flushed to zero,
-- except when the unbounded exponent is one below the one of the smallest
-- normal number: then the IP returns the result's fraction bits with a zero
-- exponent field, dropping the leading one. On every device family, the IP
-- gives the same results.
--
-- Verified against the simulated IP (Quartus Prime Lite 21.1) for MAX 10,
-- Cyclone IV E, Cyclone 10 LP and Cyclone V, at several latencies, on 2.4
-- million inputs each: special values, random inputs, inputs at every
-- exponent, and inputs whose reciprocal is very close to a rounding boundary.
recipModel :: Double -> Double
recipModel = onBits recipDouble

-- | Model of the exponential, @e^x@, of the IP in double precision. It gives
-- the IP's results bit for bit, see Note [Bit-exact double precision
-- exponential] in "Clash.Cores.Intel.Floating.Internal.BitExactDouble": the
-- argument is reduced to @r = x - k * ln 2@ in @[0, ln 2)@ and @e^r@ is
-- computed with a polynomial of degree five. The result is not always rounded
-- to nearest, nor always faithful: it is up to 1.8 units in the last place
-- below and 0.6 above the exact result. For about one in 35 multiples
-- @k * ln 2@, the IP's estimate of @k@ is one too high for the double closest
-- to and just below it: the result is then exactly @2^k@, up to 30 units in the
-- last place above the exact result. Results below the smallest normal number
-- are flushed to +0 and results that overflow give +inf; @e^(-inf) = 0@, NaN
-- inputs give 'intelNaN'. Subnormal inputs are treated as zero, but as a zero with a
-- leading one: @e^(-0)@ and @e^x@ for a negative subnormal @x@ are the
-- largest double below one.
--
-- Verified against the simulated IP (Quartus Prime Lite 21.1) for MAX 10,
-- Cyclone IV E, Cyclone 10 LP and Cyclone V, at 200 MHz, 100 MHz and a latency
-- of 20 cycles, on 2.7 million inputs each: special values, random inputs of
-- several kinds, the 41 doubles around every multiple of @ln 2@ in the range,
-- inputs in every segment of its table, and 600,000 inputs whose results
-- differ between the families.
expModel :: DeviceFamily -> Double -> Double
expModel fam = onBits (expDouble (familyMultipliers fam))

-- | Parameters of an @altera_fp_functions@ IP in double precision, see
-- 'fpFunctionsFormat'
fpFunctionsDouble ::
  KnownNat n =>
  Config ->
  -- | Function family, e.g. @ROOTS@
  String ->
  -- | Function, e.g. @SQRT@
  String ->
  -- | Latency
  Integer ->
  -- | Extra parameters
  Vec n (String, IpParam) ->
  IntelIp (n + 7)
fpFunctionsDouble = fpFunctionsFormat (("fp_format", StrParam "double") :> Nil)
{-# INLINE fpFunctionsDouble #-}

-- | Model of the three-dimensional hypotenuse, @sqrt (x^2 + y^2 + z^2)@, of the
-- IP in double precision. It gives the IP's results bit for bit, see Note
-- [Bit-exact double precision hypotenuse] in
-- "Clash.Cores.Intel.Floating.Internal.BitExactDouble": the squares are
-- truncated to 53 bits and added (aligned to the largest one, truncated 54
-- bits below it), the sum is rounded to nearest with ties away from zero, and
-- the square root's polynomial gives the result with an extra half unit in the
-- last place. The result is not always faithful: it is up to 1.1 units in the
-- last place below and 1.25 above the exact result. Subnormal inputs are
-- treated as zero and signs are ignored; any NaN input gives 'intelNaN',
-- otherwise any infinite input gives +inf; results that overflow give +inf.
--
-- Verified against the simulated IP (Quartus Prime Lite 21.1) for MAX 10,
-- Cyclone IV E, Cyclone 10 LP and Cyclone V, at 200 MHz, 100 MHz and
-- latencies of 14 and 16 cycles, on 400,000 input triples each: all
-- combinations of special values, exponent differences up to 70, sums with few
-- bits (ties), inputs near overflow and underflow, and random triples.
hypotModel :: DeviceFamily -> Double -> Double -> Double -> Double
hypotModel fam x y z =
  castWord64ToDouble
    (hypotDouble (familyMultipliers fam) (castDoubleToWord64 x) (castDoubleToWord64 y) (castDoubleToWord64 z))

