{-# OPTIONS_HADDOCK hide #-}

module Clash.Cores.Intel.Floating.Internal.Double
  ( -- * Simulation models
    intelNaN
  , sqrtModel
  , recipModel
    -- * Instantiation
  , fpFunctionsDouble
  ) where

import Clash.Explicit.Prelude

import Data.Word (Word64)
import GHC.Float (castDoubleToWord64, castWord64ToDouble)

import Clash.Cores.Intel.Floating.Internal
  (Config, DeviceFamily, familyMultipliers, fpFunctionsFormat)
import Clash.Cores.Intel.Floating.Internal.BitExactDouble
import Clash.Cores.Intel.Internal (IntelIp, IpParam(..))

-- | Lift a function on bit patterns to 'Double'
onBits :: (Word64 -> Word64) -> Double -> Double
onBits f = castWord64ToDouble . f . castDoubleToWord64

-- | NaN as generated by the Intel IP in double precision: positive, with the
-- least significant bit of the fraction set (@0x7FF0000000000001@).
intelNaN :: Double
intelNaN = castWord64ToDouble 0x7FF0000000000001

-- | Model of the square root of the IP in double precision. It gives the IP's
-- results bit for bit, see Note [Bit-exact double precision models] in
-- "Clash.Cores.Intel.Floating.Internal.BitExactDouble": a significand
-- computed with a polynomial of degree five, which is faithfully rounded but
-- not always rounded to nearest. Subnormal inputs are treated as zero,
-- @sqrt (-0) = -0@, and negative inputs give 'intelNaN'.
--
-- Verified against the simulated IP (Quartus Prime Lite 21.1) for MAX 10,
-- Cyclone IV E, Cyclone 10 LP and Cyclone V, at several latencies, on 4.3
-- million inputs each: special values, random inputs, inputs in every segment
-- of its tables, inputs close to the rounding boundaries, and on another
-- 600,000 inputs per family whose results would change with a small change of
-- the model's structure.
sqrtModel :: DeviceFamily -> Double -> Double
sqrtModel fam = onBits (sqrtDouble (familyMultipliers fam))

-- | Model of the reciprocal of the IP in double precision. Like in single
-- precision, it is the IEEE 754 reciprocal, rounded to nearest, ties to even,
-- of the input with subnormal inputs treated as zero and the exponent
-- unbounded. Results below the smallest normal number are flushed to zero,
-- except when the unbounded exponent is one below the one of the smallest
-- normal number: then the IP returns the result's fraction bits with a zero
-- exponent field, dropping the leading one. On every device family, the IP
-- gives the same results.
--
-- Verified against the simulated IP (Quartus Prime Lite 21.1) for MAX 10,
-- Cyclone IV E, Cyclone 10 LP and Cyclone V, at several latencies, on 2.4
-- million inputs each: special values, random inputs, inputs at every
-- exponent, and inputs whose reciprocal is very close to a rounding boundary.
recipModel :: Double -> Double
recipModel = onBits recipDouble

-- | Parameters of an @altera_fp_functions@ IP in double precision, see
-- 'fpFunctionsFormat'
fpFunctionsDouble ::
  KnownNat n =>
  Config ->
  -- | Function family, e.g. @ROOTS@
  String ->
  -- | Function, e.g. @SQRT@
  String ->
  -- | Latency
  Integer ->
  -- | Extra parameters
  Vec n (String, IpParam) ->
  IntelIp (n + 7)
fpFunctionsDouble = fpFunctionsFormat (("fp_format", StrParam "double") :> Nil)
{-# INLINE fpFunctionsDouble #-}
