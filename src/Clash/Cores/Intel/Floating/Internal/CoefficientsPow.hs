Polynomial coefficients of the power function of Intel's Floating Point
Functions IP in single precision, see
"Clash.Cores.Intel.Floating.Internal.BitExact".

This module is generated by @gen_coefficients_pow.py@; don't edit it by hand.

The IP computes @x ** y@ as @exp (y * ln x)@, with a logarithm and an
exponential of about 34 bits, each a cubic polynomial per segment. The integer
coefficients of each segment were computed from first principles: the
monomials @1, t, t^2, t^3@, each scaled by the weight of its coefficient's
least significant bit and evaluated at the five Chebyshev nodes (of the first
kind) of the segment's range of @t@, span a lattice; LLL reduction
(delta = 0.99) and Babai's nearest plane algorithm give a close lattice vector
to the function's values at the nodes (absolute error), whose coordinates are
the coefficients (the method behind Sollya's @fpminimax@). Coefficient formats
were inferred from the IP's outputs and its resource reports; the coefficients
themselves are not taken from the IP and the module contains no data taken from
Intel's IP. The tables hold the plain polynomial coefficients: the model adds
the rounding constants of the datapath itself.

Each list holds @(C0, C1, C2, C3)@ per segment, in table order.
-}

