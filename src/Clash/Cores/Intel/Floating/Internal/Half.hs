-- | Lift a function on bit patterns to t'Half'
onBits :: (Word16 -> Word16) -> Half -> Half
onBits f = Half . fromIntegral . f . fromIntegral . getHalf

-- | NaN as generated by the Intel IP in half precision: positive, with the
-- least significant bit of the fraction set (@0x7C01@).
intelNaN :: Half
intelNaN = Half 0x7C01

-- | Model of the square root of the IP in half precision. It gives the IP's
-- results bit for bit, see Note [Bit-exact half precision models] in
-- "Clash.Cores.Intel.Floating.Internal.BitExactHalf": a significand computed
-- with a polynomial of degree one, which is faithfully rounded but not
-- always rounded to nearest. Subnormal inputs are treated as zero,
-- @sqrt (-0) = -0@, and negative inputs give 'intelNaN'.
--
-- Verified against the simulated IP (Quartus Prime Lite 21.1) on all inputs,
-- for MAX 10, Cyclone IV E, Cyclone 10 LP and Cyclone V, at several
-- latencies.
sqrtModel :: DeviceFamily -> Half -> Half
sqrtModel fam = onBits (sqrtHalf (familyMultipliers fam))

-- | Model of the reciprocal square root of the IP in half precision, see
-- 'sqrtModel'. Zero and subnormal inputs give infinity of their sign,
-- negative inputs and NaN give 'intelNaN', and infinity gives zero.
--
-- Verified like 'sqrtModel'.
rsqrtModel :: DeviceFamily -> Half -> Half
rsqrtModel fam = onBits (rsqrtHalf (familyMultipliers fam))

-- | Model of the reciprocal of the IP in half precision. Like in single
-- precision, it is the IEEE 754 reciprocal, rounded to nearest, ties to
-- even, of the input with subnormal inputs treated as zero and the exponent
-- unbounded. Results below the smallest normal number are flushed to zero,
-- except when the unbounded exponent is one below the one of the smallest
-- normal number: then the IP returns the result's fraction bits with a zero
-- exponent field, dropping the leading one. On every device family, the IP
-- gives the same results.
--
-- Verified like 'sqrtModel'.
recipModel :: Half -> Half
recipModel = onBits recipHalf

-- | Model of the exponential of the IP in half precision, see 'sqrtModel'.
-- The IP computes @x - k * ln 2@ for an estimate of @k = floor (x / ln 2)@,
-- and its exponential with a polynomial of degree one, so the result can be
-- off by up to one and a half units in the last place: unlike what the user
-- guide promises, it is not always faithfully rounded (for 2% of the
-- inputs). Like in single precision, the IP computes @exp (-0)@ and the
-- exponential of small negative numbers as the largest number below one
-- (@0x3BFF@). Results below the smallest normal number are flushed to zero.
--
-- Verified like 'sqrtModel'.
expModel :: DeviceFamily -> Half -> Half
expModel fam = onBits (expHalf (familyMultipliers fam))

-- | Model of the base-2 exponential of the IP in half precision, see
-- 'expModel'. The IP truncates its input to 10 fraction bits, so for inputs
-- below one in magnitude the result can be off by almost two units in the
-- last place (it is at least one unit off for 6% of the inputs). Like
-- 'expModel', the IP computes @2^(-0)@ as @0x3BFF@.
--
-- Verified like 'sqrtModel'.
exp2Model :: DeviceFamily -> Half -> Half
exp2Model fam = onBits (exp2Half (familyMultipliers fam))

-- | Model of the base-10 exponential of the IP in half precision, see
-- 'expModel'. Like in single precision, the IP adds a whole unit in the last
-- place before truncating the result, so @10^0@ is @1 + 2^-10@ (@0x3C01@) and
-- @10^(-0)@ is @0x3BFE@; the result can be off by more than two units in the
-- last place (at least one unit for 14% of the inputs).
--
-- Verified like 'sqrtModel'.
exp10Model :: DeviceFamily -> Half -> Half
exp10Model fam = onBits (exp10Half (familyMultipliers fam))

-- | Model of the natural logarithm of the IP in half precision, see
-- 'sqrtModel'. The result can be off by up to almost two units in the last
-- place (at least one unit for 0.5% of the inputs): unlike what the user
-- guide promises, it is not always faithfully rounded. Zero and subnormal
-- inputs give minus infinity, negative inputs and NaN give 'intelNaN'.
--
-- Verified like 'sqrtModel'.
logModel :: DeviceFamily -> Half -> Half
logModel fam = onBits (logHalf (familyMultipliers fam))

-- | Model of the base 2 logarithm of the IP in half precision, see
-- 'logModel'. It is faithfully rounded, and powers of two give exact results.
--
-- Verified like 'sqrtModel'.
log2Model :: DeviceFamily -> Half -> Half
log2Model fam = onBits (log2Half (familyMultipliers fam))

-- | Model of the base 10 logarithm of the IP in half precision, see
-- 'logModel'. The result is off by a unit in the last place or more for a
-- few inputs.
--
-- Verified like 'sqrtModel'.
log10Model :: DeviceFamily -> Half -> Half
log10Model fam = onBits (log10Half (familyMultipliers fam))

-- | Model of @log (1 + x)@ of the IP in half precision, see 'logModel'. Small
-- inputs keep their precision, as in single precision. The result can be off
-- by up to one and a half units in the last place (at least one unit for 1%
-- of the inputs). Zero and subnormal inputs give a zero of the same sign, -1
-- gives minus infinity, inputs below -1 and NaN give 'intelNaN'.
--
-- Verified like 'sqrtModel'.
log1pModel :: DeviceFamily -> Half -> Half
log1pModel fam = onBits (log1pHalf (familyMultipliers fam))

-- | Model of the cube root of the IP in half precision, see 'sqrtModel'. It is
-- faithfully rounded. Zero and subnormal inputs give a zero of the same sign,
-- negative inputs the negated cube root of their magnitude, and a NaN input
-- gives a NaN with the sign of the input (@0x7C01@ or @0xFC01@), like in single
-- precision.
--
-- Verified like 'sqrtModel'.
cbrtModel :: DeviceFamily -> Half -> Half
cbrtModel fam = onBits (cbrtHalf (familyMultipliers fam))

-- | Model of the three-dimensional hypotenuse of the IP in half precision,
-- @sqrt (x^2 + y^2 + z^2)@, see 'sqrtModel'. Like in single precision, the IP
-- truncates the squares to 11 bits, and the smaller ones further when it
-- aligns them to the largest, rounds their sum to nearest and takes its square
-- root like 'sqrtModel' with a larger rounding constant. So the result can be
-- off by up to about two units in the last place (by a unit or more for about
-- 1% of random inputs). Subnormal inputs are treated as zero and the signs of
-- the inputs are ignored. A NaN input gives 'intelNaN', otherwise an infinite
-- input gives infinity; results of @2^16@ or more overflow to infinity.
--
-- Verified against the simulated IP (Quartus Prime Lite 21.1) for MAX 10 and
-- Cyclone V on all pairs of non-negative inputs (with the third input zero),
-- 50 million triples with overlapping squares, every input with the other
-- two zero, all combinations of special values, inputs near the overflow
-- boundary and random triples; and for Cyclone IV E, Cyclone 10 LP and other
-- latencies on 2.5 million of those triples.
hypotModel :: DeviceFamily -> Half -> Half -> Half -> Half
hypotModel fam x y z =
  Half (fromIntegral (hypotHalf (familyMultipliers fam) (bits x) (bits y) (bits z)))
 where
  bits = fromIntegral . getHalf

-- | Model of the IP's @sin (pi * x)@ in half precision (the \"SIN\" function
-- with the angle represented as a multiple of pi), see 'sqrtModel'. As in
-- single precision, the IP computes @r * P(r)@ with @r@ the distance of @x@
-- to the nearest integer and @P@ a polynomial approximation of
-- @sin (pi * r) / r@. For @x@ in @[2^-6, 0.25)@ it drops the last bit of @x@'s
-- significand, so the result can be off by more than two units in the last
-- place (by a unit or more for 4% of the inputs): unlike what the user guide
-- promises, it is not always faithfully rounded. Integers and inputs of
-- magnitude @1024@ and above give a zero with the sign of @x@, as do zero and
-- subnormal inputs. Infinities and NaNs give 'intelNaN' with the sign of the
-- input (unlike in single precision, where a NaN input gives a NaN of the
-- opposite sign).
--
-- Verified like 'sqrtModel'.
sinPiModel :: DeviceFamily -> Half -> Half
sinPiModel fam = onBits (sinPiHalf (familyMultipliers fam))

-- | Model of the IP's @cos (pi * x)@ in half precision (the \"COS\" function
-- with the angle represented as a multiple of pi), see 'sqrtModel' and
-- 'sinPiModel': the IP computes @sin (pi * r)@ with @r@ the distance of @x@ to
-- the nearest half integer, with the polynomial of 'sinPiModel'. The result
-- can be off by up to almost two units in the last place (by a unit or more
-- for 2% of the inputs). Half integers give positive zero; NaN and the
-- infinities give 'intelNaN'.
--
-- Verified like 'sqrtModel'.
cosPiModel :: DeviceFamily -> Half -> Half
cosPiModel fam = onBits (cosPiHalf (familyMultipliers fam))

-- | Model of the IP's @tan (pi * x)@ in half precision (the \"TAN\" function
-- with the angle represented as a multiple of pi), see 'sqrtModel'. The IP
-- divides its sine of pi times x ('sinPiModel') by its cosine of pi times x
-- ('cosPiModel'), both rounded to half precision, multiplying by a polynomial
-- approximation of the reciprocal, so the result can be off by up to four
-- units in the last place (by a unit or more for 9% of the inputs). Inputs of
-- magnitude below @2^-7@ give @x@ times pi rounded to half precision, rounded;
-- zero and subnormal inputs are returned unchanged; integers give a zero and
-- half integers an infinity, with the sign of the quotient; NaN and the
-- infinities give 'intelNaN'.
--
-- Verified like 'sqrtModel'.
tanPiModel :: DeviceFamily -> Half -> Half
tanPiModel fam = onBits (tanPiHalf (familyMultipliers fam))

-- | Model of the IP's arcsine in half precision (the \"ARCSIN\" function), in
-- radians, see 'sqrtModel'. The IP's arcsine is odd. For @|x| <= 1/2@ it
-- multiplies @x@ by a polynomial approximation of degree two of @asin x / x@
-- at @|x|@ truncated to @2^-13@, rounding to nearest with ties away from zero.
-- For @1/2 < |x| < 1@ it computes @pi / 2 - 2 asin z@ in fixed point, with a
-- polynomial approximation of @2 asin z@ at @z = sqrt ((1 - |x|) / 2)@ (half
-- the correctly rounded @2 z@, truncated to @2^-12@), rounding to nearest with
-- ties away from zero. The result can be off by up to 1.14 units in the last
-- place. @asin 1@ is pi / 2 rounded to nearest; zero and subnormal inputs give
-- a zero of the same sign; NaN, the infinities and @|x| > 1@ give 'intelNaN'.
-- See Note [Bit-exact half precision arcsine].
--
-- Verified against the simulated IP (Quartus Prime Lite 21.1) on all 2^16
-- inputs, for all four families at 200 MHz and at a latency of 8 cycles.
asinModel :: DeviceFamily -> Half -> Half
asinModel fam = onBits (asinHalf (familyMultipliers fam))

-- | Model of the IP's arcsine divided by pi in half precision (the \"ARCSIN\"
-- function with the angle represented as a multiple of pi), see 'sqrtModel':
-- the IP multiplies its arcsine ('asinModel'), rounded to half precision, by
-- 1 \/ pi rounded to half precision (@0x3518@), rounding to nearest with ties
-- away from zero, so the result can be off by up to 1.68 units in the last
-- place. Results below the smallest normal number become a zero of the same
-- sign; NaN, the infinities and @|x| > 1@ give 'intelNaN'.
--
-- Verified against the simulated IP (Quartus Prime Lite 21.1) on all 2^16
-- inputs, for all four families at 200 MHz and at a latency of 10 cycles (9
-- on Cyclone V).
asinPiModel :: DeviceFamily -> Half -> Half
asinPiModel fam = onBits (asinPiHalf (familyMultipliers fam))

-- | Parameters of an @altera_fp_functions@ IP in half precision, see
-- 'fpFunctionsFormat'
fpFunctionsHalf ::
  KnownNat n =>
  Config ->
  -- | Function family, e.g. @ROOTS@
  String ->
  -- | Function, e.g. @SQRT@
  String ->
  -- | Latency
  Integer ->
  -- | Extra parameters
  Vec n (String, IpParam) ->
  IntelIp (n + 9)
fpFunctionsHalf = fpFunctionsFormat halfFormat
 where
  halfFormat =
       ("fp_format", StrParam "custom")
    :> ("fp_exp", IntegerParam 5)
    :> ("fp_man", IntegerParam 10)
    :> Nil
{-# INLINE fpFunctionsHalf #-}
