-- | Customizable floating point addition.
--
-- The latency @d@ is set by the type. Quartus fails to generate the IP if the
-- latency is lower than the IP can achieve on the target device family.
addWith
  :: forall d dom n
   . ( KnownDomain dom
     , KnownNat d
     , HasCallStack
     )
  => Config
  -> Clock dom
  -> Reset dom
  -> Enable dom
  -> DSignal dom n Float
  -> DSignal dom n Float
  -> DSignal dom (n + d) Float
addWith cfg clk rst en x y
  | clashSimulation = pipeline und clk rst en (addModel <$> x <*> y)
  | otherwise = binaryInst "fp_add" ip clk rst en x y
 where
  und = withFrozenCallStack $ deepErrorX "Undefined output of add"
  ip = fpFunctions cfg "ARITH" "ADD" (natToNum @d) Nil
{-# INLINE addWith #-}

-- | Floating point addition, with the default configuration and delay.
add
  :: forall dom n
   . ( KnownDomain dom
     , HasCallStack
     )
  => Clock dom
  -> Reset dom
  -> Enable dom
  -> DSignal dom n Float
  -> DSignal dom n Float
  -> DSignal dom (n + AddDefDelay) Float
add = withFrozenCallStack $ addWith defConfig
{-# INLINE add #-}

-- | The default delay of 'add': the latency Quartus Prime Lite 21.1 picks for
-- a target frequency of 200 MHz, on the device family where this is the
-- largest.
type AddDefDelay = 11

