Support for Intel's Floating Point Functions IP (@altera_fp_functions@), as
described in the
[Floating-Point IP Cores User Guide (UG-01058)](https://www.intel.com/content/www/us/en/docs/programmable/683750/).
The API follows "Clash.Cores.Xilinx.Floating.Explicit", to make it easy to
switch between the vendors.

Compilation instantiates the IP. Clash writes a Platform Designer system
(@.qsys@ file) for every instance, see "Clash.Cores.Intel.Internal" for how to
generate the IP from it. Simulation in Clash produces bit-identical results to
the IP's simulation model, cycle by cycle.

All IP instantiated by this module has the following properties:

* Single precision
* An enable input, driven by the 'Enable' argument. De-asserting it stalls the
  whole pipeline.
* Its asynchronous reset input @areset@ is driven by the 'Reset' argument. The
  reset clears the pipeline registers of the IP, which is needed in HDL
  simulation: without it, some IP (like division) keeps producing undefined
  results. The outputs during reset, and until the pipeline has filled again,
  are undefined in simulation.

The latency of the IP is set through the delay argument of the 'DSignal'. The
IP is generated with the \"latency\" performance goal, which makes Quartus
search for a frequency at which it can implement the IP with exactly that
latency. Generation fails if the latency is lower than the IP can achieve on the
device family.

The IP's results differ from IEEE 754 arithmetic as follows. The simulation
models, such as 'addModel' and 'roundToFloat', describe them precisely.

* Subnormal inputs are treated as zero (keeping their sign).
* Results are rounded to nearest, ties to even, as if the exponent were
  unbounded. Results that round to a magnitude below the smallest normal number
  are flushed to zero, keeping their sign. So a result just below the smallest
  normal number can round up to it.
* Every NaN result of an arithmetic function is 'intelNaN' (@0x7F800001@),
  regardless of the inputs. Conversions between 'Float' and 'Double' keep the
  sign of NaNs.
* 'mulAdd' is not a fused multiply-add: the product is rounded before the
  addition.
* Comparisons with NaN, including \"not equal\", are 'False'.
* Conversions to integers round to nearest with ties away from zero, and
  saturate.

The models were derived from the user guide and validated against the IP
generated by Quartus Prime Lite 21.1 for Cyclone V and MAX 10 devices.

The user guide only promises that the square root ('sqrt'), reciprocal square
root ('rsqrt'), exponential ('exp') and logarithm ('log') are faithfully
rounded: within one unit in the last place, but which way they round is
unspecified. Their models ('sqrtModel' etc.) nevertheless give the IP's results
bit for bit. They were obtained by black-box testing of the IP: they implement
the published piecewise polynomial algorithms, with the widths and roundings
inferred from the IP's outputs and its resource reports, and tables computed
from first principles, see Note [Bit-exact models] in
"Clash.Cores.Intel.Floating.Internal.BitExact". They were validated on all
inputs of two binades and many millions of other inputs, on MAX 10, Cyclone IV
E, Cyclone 10 LP and Cyclone V, at several latencies. The results of these
functions depend on the multipliers of the device family, so they take a
'DeviceFamily' argument. The reciprocal ('recip') is correctly rounded (with a
quirk just below the smallest normal number, see 'recipModel').

Other functions of the IP, such as the trigonometric functions, are not
supported.

For each customizable operation, there also exists a function that uses the
default configuration and a default latency, which is defined as a type.
-}

