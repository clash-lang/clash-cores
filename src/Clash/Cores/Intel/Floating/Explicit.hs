-- | Customizable comparison of floating point numbers. The IP doesn't have a
-- function that returns an ordering, so this instantiates three comparison
-- functions (less than, equal and greater than). See 'compareModel'.
compareWith
  :: forall d dom n
   . ( KnownDomain dom
     , KnownNat d
     , HasCallStack
     )
  => Config
  -> Clock dom
  -> Reset dom
  -> Enable dom
  -> DSignal dom n Float
  -> DSignal dom n Float
  -> DSignal dom (n + d) Ordering
compareWith cfg clk rst en x y = toOrdering <$> lt <*> eq <*> gt
 where
  lt = predicateWith @d cfg Lt clk rst en x y
  eq = predicateWith @d cfg Eq clk rst en x y
  gt = predicateWith @d cfg Gt clk rst en x y
  toOrdering True _ _ = LT
  toOrdering _ True _ = EQ
  toOrdering _ _ True = GT
  toOrdering _ _ _ = NaN
{-# INLINE compareWith #-}

