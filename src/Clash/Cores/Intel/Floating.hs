#differences#

= Differences from Intel's documentation

The IP generated by Quartus Prime Lite 21.1 (for MAX 10, Cyclone IV E, Cyclone
10 LP and Cyclone V) differs from the
[Floating-Point IP Cores User Guide](https://www.intel.com/content/www/us/en/docs/programmable/683750/)
(UG-01058) and from the IP's parameter editor as follows. Each was found by
black-box testing: simulating the generated IP's simulation model on chosen
inputs and comparing generated IP with different parameters. The functions'
models document the details.

* /Accuracy./ The user guide says the floating-point IP computes results with
  an error of at most one unit in the last place (\"Floating-Point IP Cores
  General Features\", version 2015.07.30). These single precision functions
  are off by more for some inputs (maximum errors found, in units in the last
  place): 'exp2' (2, for inputs below one in magnitude), 'exp10' (a few, just
  below multiples of log10 2), 'hypot' (1.4), 'sinPi' (2.5), 'tanPi' (5),
  'sin' (1.6), 'cos' (1.2), 'tan' (2.5), 'atan' (2.2), 'atanPi' (1.9),
  'atan2' (2.5), 'pow' (1.3), 'acos' (3) and 'acosPi' (4.4). In half precision
  ("Clash.Cores.Intel.Floating.Half") only the square root, the reciprocal
  square root, the cube root and the base 2
  logarithm keep within one unit; the other exponentials and logarithms, the
  hypotenuse, 'sinPi', 'cosPi' and 'tanPi' don't. Found with the bit-exact
  models, on all inputs of whole binades and millions of other inputs per
  function, on all four families. The arcsine (not supported by this module)
  is off by up to 1.3 units in the last place for inputs in [0.5, 1) (all
  inputs of that binade, Cyclone V datapath). In double
  precision, the exponential
  ('Clash.Cores.Intel.Floating.Double.Explicit.expModel') is off by up to 1.8
  units in the last place, and by up to 30 units for the double just below
  about one in 35 multiples of ln 2, where it returns the power of two above
  (all four families; 2.7 million inputs per family).

* /Power of one./ IEEE 754's @powr@, which the IP's POWR follows otherwise,
  gives one for @1 ** y@ with a finite @y@. The IP gives @+inf@ or @+0@ for
  some @y@ with @2^63 <= |y| < 2^66@ and @+0@ for @y <= -1.365 * 2^127@
  (about): its logarithm of one is 2^-57 instead of zero, see
  'Clash.Cores.Intel.Floating.Explicit.powModel' (all four families).

* /Range reduction option./ For SIN, COS and TAN the parameter editor offers
  \"Inputs are within range -2pi to +2pi\" (@trig_no_range_reduction@), which
  its description calls an option that \"disables range reduction for Hard
  Floating Point\". On the Lite families it has no effect: the generator
  produces the same IP with and without it (MAX 10, all three functions).
  Together with \"Represent angle as multiple of Pi\" it is rejected for SIN
  and COS and ignored for TAN.
-}

